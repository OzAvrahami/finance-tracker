const docker = (args, input, allowFailure = false) => {
  const result = spawnSync('docker', args, { input, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 });
  if (!allowFailure && result.status !== 0) {
    throw new Error(`docker ${args.join(' ')} failed:\n${result.stdout}\n${result.stderr}`);
  }
  return result;
};

const psql = (database, sql, allowFailure = false) => docker([
  'exec', '-i', container, 'psql', '-U', 'postgres', '-d', database,
  '-v', 'ON_ERROR_STOP=1', '-At',
], sql, allowFailure);

const psqlAsync = (database, sql) => new Promise((resolve) => {
  const child = spawn('docker', [
    'exec', '-i', container, 'psql', '-U', 'postgres', '-d', database,
    '-v', 'ON_ERROR_STOP=1', '-At',
  ]);
  let stdout = '';
  let stderr = '';
  child.stdout.setEncoding('utf8');
  child.stderr.setEncoding('utf8');
  child.stdout.on('data', (chunk) => { stdout += chunk; });
  child.stderr.on('data', (chunk) => { stderr += chunk; });
  child.on('close', (status) => resolve({ status, stdout, stderr }));
  child.stdin.end(sql);
});

const delay = (milliseconds) => new Promise((resolve) => setTimeout(resolve, milliseconds));

const waitForGrantedTableLock = async (database, table, mode) => {
  for (let attempt = 0; attempt < 40; attempt += 1) {
    const granted = psql(database, `SELECT EXISTS (
      SELECT 1 FROM pg_locks
      WHERE database = (SELECT oid FROM pg_database WHERE datname = current_database())
        AND relation = '${table}'::regclass
        AND mode = '${mode}'
        AND granted
    );`).stdout.trim();
    if (granted === 't') return;
    await delay(50);
  }
  assert.fail(`timed out waiting for ${mode} on ${table}`);
};

