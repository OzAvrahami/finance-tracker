test('RPCs enforce funding, explicit zero, idempotency, removal, and reactivation', () => {
  createDatabase('rpc_domain');
  psql('rpc_domain', fixture());
  psql('rpc_domain', migration);
  psql('rpc_domain', `
    SELECT add_manual_budget_funding('2026-09',1000,'Confirmed opening cash','11111111-1111-4111-8111-111111111111');
    SELECT add_manual_budget_funding('2026-09',1000,'Confirmed opening cash','11111111-1111-4111-8111-111111111111');
    SELECT establish_funded_budget('2026-09',2,0,'manual','22222222-2222-4222-8222-222222222222');
    SELECT establish_funded_budget('2026-09',1,600,'manual','33333333-3333-4333-8333-333333333333');
    SELECT set_funded_budget_amount(
      (SELECT budget_id FROM budget_category_state WHERE month='2026-09' AND category_id=1),
      700,'44444444-4444-4444-8444-444444444444'
    );
    INSERT INTO transactions(transaction_date,movement_type,total_amount,category_id)
      VALUES ('2026-09-10','expense',250,1),('2026-09-11','expense',50,3),('2026-09-12','expense',50,2);
    SELECT remove_funded_budget(
      (SELECT budget_id FROM budget_category_state WHERE month='2026-09' AND category_id=1),
      '55555555-5555-4555-8555-555555555555'
    );
    SELECT remove_funded_budget(
      (SELECT budget_id FROM budget_category_state WHERE month='2026-09' AND category_id=2),
      '66666666-6666-4666-8666-666666666666'
    );
    SELECT reactivate_funded_budget(
      (SELECT budget_id FROM budget_category_state WHERE month='2026-09' AND category_id=1),
      100,'77777777-7777-4777-8777-777777777777'
    );
  `);
  const state = JSON.parse(psql('rpc_domain', "SELECT get_funded_budget_month('2026-09');").stdout.trim());
  assert.equal(state.funding.available, '1000.00');
  assert.equal(state.funding.total_allocated, '350.00');
  assert.equal(state.funding.unallocated, '650.00');
  assert.equal(state.actuals.total, '350.00');
  assert.equal(state.actuals.budgeted, '250.00');
  assert.equal(state.actuals.unbudgeted, '100.00');
  assert.equal(state.history.filter((operation) => operation.operation_type === 'manual_funding').length, 1);
  const food = state.categories.find((category) => category.category_id === 1);
  const fuel = state.categories.find((category) => category.category_id === 2);
  assert.equal(food.starting_amount, '600.00');
  assert.equal(food.adjustment_total, '-250.00');
  assert.equal(food.final_funded, '350.00');
  assert.equal(food.lifecycle_state, 'active');
  assert.equal(fuel.final_funded, '0.00');
  assert.equal(fuel.lifecycle_state, 'inactive');
  assert.equal(fuel.actual_spent, '50.00');
  const fuelRemoval = state.history.flatMap((operation) => operation.lifecycle_events)
    .find((event) => event.budget_id === fuel.budget_id && event.state === 'inactive');
  assert.equal(fuelRemoval.actual_spent_snapshot, '50.00');
});

test('RPC failures are atomic and append-only protections reject rewrites', () => {
  const insufficient = psql('rpc_domain', `
    SELECT establish_funded_budget('2026-09',3,700,'manual','88888888-8888-4888-8888-888888888888');
  `, true);
  assert.notEqual(insufficient.status, 0);
  assert.match(insufficient.stderr, /Insufficient unallocated funds/i);
  assert.equal(psql('rpc_domain', "SELECT count(*) FROM budgets b JOIN budget_months bm ON bm.id=b.budget_month_id WHERE bm.month_start='2026-09-01' AND b.category_id=3;").stdout.trim(), '0');

  const nonFinite = psql('rpc_domain', "SELECT add_manual_budget_funding('2026-09','NaN'::numeric,'Invalid','12121212-1212-4212-8212-121212121212');", true);
  assert.notEqual(nonFinite.status, 0);
  assert.match(nonFinite.stderr, /positive two-decimal value/i);

  const budgetId = psql('rpc_domain', "SELECT budget_id FROM budget_category_state WHERE month='2026-09' AND category_id=1;").stdout.trim();
  const spentRelease = psql('rpc_domain', `SELECT set_funded_budget_amount(${budgetId},200,'99999999-9999-4999-8999-999999999999');`, true);
  assert.notEqual(spentRelease.status, 0);
  assert.match(spentRelease.stderr, /Cannot release spent funding/i);

  for (const sql of [
    `UPDATE budgets SET starting_amount=999 WHERE id=${budgetId};`,
    'UPDATE budget_operations SET reason=\'rewrite\' WHERE id=(SELECT min(id) FROM budget_operations);',
    'DELETE FROM budget_movements;',
    'DELETE FROM budgets WHERE id=' + budgetId + ';',
  ]) {
    const result = psql('rpc_domain', sql, true);
    assert.notEqual(result.status, 0);
    assert.match(result.stderr, /immutable|append-only/i);
  }
});

