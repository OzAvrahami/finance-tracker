const expectMigrationFailure = (database, expected) => {
  const result = psql(database, migration, true);
  assert.notEqual(result.status, 0, `migration unexpectedly succeeded for ${database}`);
  assert.match(`${result.stdout}\n${result.stderr}`, expected);
  const rolledBack = psql(database, "SELECT to_regclass('public.budget_months') IS NULL;").stdout.trim();
  assert.equal(rolledBack, 't');
};

const applyRecurringFoundation = (database) => {
  psql(database, migration);
  psql(database, recurringMigration);
};

before(() => {
  docker(['run', '--detach', '--rm', '--name', container, '-e', `POSTGRES_PASSWORD=${password}`, 'postgres:16-alpine']);
  let ready = false;
  for (let attempt = 0; attempt < 30; attempt += 1) {
    const result = docker(['exec', container, 'pg_isready', '-U', 'postgres'], undefined, true);
    if (result.status === 0) {
      ready = true;
      break;
    }
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 250);
  }
  assert.equal(ready, true, 'disposable PostgreSQL did not become ready');
  // public_probe has no explicit grants or memberships, so its effective
  // privileges are exactly those inherited from PostgreSQL PUBLIC. Supabase's
  // service_role bypasses RLS in production; model that property explicitly.
  psql('postgres', 'CREATE ROLE public_probe; CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;');
});

after(() => {
  docker(['stop', container], undefined, true);
});

