const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const { normalizeLoanHandling } = require('../utils/manualLoanPayment');

const migration = fs.readFileSync(path.join(
  __dirname, '..', 'migrations', '015_manual_loan_repayments.sql',
), 'utf8');
const schema = fs.readFileSync(path.join(__dirname, '..', 'full_schema.sql'), 'utf8');

const getLatestFunction = (sql, name) => (
  sql.match(new RegExp(
    `CREATE OR REPLACE FUNCTION public\\.${name}\\([\\s\\S]*?\\n\\$\\$;`,
    'g',
  ))?.at(-1) || ''
);

const applyManualSchedule = ({ nextScheduledDueDate }) => nextScheduledDueDate;

test('manual repayment split is normalized with exact cent arithmetic', () => {
  assert.deepEqual(normalizeLoanHandling({
    transaction: { loan_id: 1, total_amount: '1611.58' },
    loanHandling: {
      mode: 'repayment',
      principal_amount: '1103.36',
      interest_amount: '508.22',
      other_amount: '0',
      next_scheduled_due_date: '2026-09-15',
    },
  }), {
    mode: 'repayment',
    payment: {
      principal_amount: '1103.36',
      interest_amount: '508.22',
      other_amount: '0.00',
      next_scheduled_due_date: '2026-09-15',
    },
  });
  assert.throws(() => normalizeLoanHandling({
    transaction: { loan_id: 1, total_amount: '1611.58' },
    loanHandling: {
      mode: 'repayment',
      principal_amount: '1103.36',
      interest_amount: '508.21',
      other_amount: '0',
      next_scheduled_due_date: '2026-09-15',
    },
  }), /do not reconcile/);
});

