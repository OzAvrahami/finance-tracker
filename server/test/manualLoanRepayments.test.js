test('manual schedule applies the submitted bank date regardless of posting date', () => {
  for (const postingDate of ['2026-08-15', '2026-08-16', '2026-08-17']) {
    assert.equal(
      applyManualSchedule({
        scheduledDueDate: '2026-08-16',
        nextScheduledDueDate: '2026-09-15',
        postingDate,
      }),
      '2026-09-15',
    );
  }

  for (const sql of [migration, schema]) {
    const syncFunction = getLatestFunction(sql, 'sync_manual_loan_payment_from_transaction');
    assert.match(sql, /scheduled_due_date\s+DATE/);
    assert.match(sql, /next_scheduled_due_date\s+DATE/);
    assert.match(syncFunction, /v_scheduled_due_date := v_loan\.next_payment_date/);
    assert.match(syncFunction, /v_next_scheduled_due_date := nullif\([\s\S]*p_loan_payment->>'next_scheduled_due_date'/);
    assert.match(syncFunction, /ELSE v_next_scheduled_due_date/);
    assert.doesNotMatch(syncFunction, /\(v_scheduled_due_date \+ INTERVAL '1 month'\)::date/);
    assert.doesNotMatch(syncFunction, /\(v_payment_date \+ INTERVAL '1 month'\)::date/);
    assert.doesNotMatch(sql, /INTERVAL '30 days'/i);
  }
});

