test('identity synchronization is idempotent and leaves existing IDs unchanged', () => {
  const existingIds = [1, 60, 187, 248];
  const synchronize = (ids) => ({
    lastValue: Math.max(0, ...ids) + 1,
    isCalled: false,
  });
  const nextGeneratedValue = ({ lastValue, isCalled }) => (
    isCalled ? lastValue + 1 : lastValue
  );

  const firstSync = synchronize(existingIds);
  assert.deepEqual(firstSync, { lastValue: 249, isCalled: false });
  assert.equal(nextGeneratedValue(firstSync), 249);
  assert.deepEqual(synchronize(existingIds), firstSync);
  assert.deepEqual(existingIds, [1, 60, 187, 248]);
});

test('omitted or explicit link-only handling can never manufacture accounting data', () => {
  assert.deepEqual(normalizeLoanHandling({
    transaction: { loan_id: 1, total_amount: '5000.00' },
  }), { mode: 'link_only', payment: null });
  assert.deepEqual(normalizeLoanHandling({
    transaction: { loan_id: 1, total_amount: '5000.00' },
    loanHandling: { mode: 'link_only' },
  }), { mode: 'link_only', payment: null });
});

