-- Added by migrations/003_transaction_pagination_and_aggregates.sql
-- Backs the default list branch: ORDER BY transaction_date DESC, id DESC, its
-- keyset seek, and the from/to range filter. One ordered index scan serves the
-- sort and the cursor together.
--
-- It does NOT fully serve the ascending branch, which orders by
-- (transaction_date ASC, id DESC): a backward scan of this index yields
-- (transaction_date ASC, id ASC), so Postgres adds a sort node there. The
-- id DESC tiebreaker is kept uniform across branches on purpose.
--
-- No index is defined for the amount or description sort branches; see the
-- migration for the cost analysis and the four indexes that would be needed.
CREATE INDEX idx_transactions_date_id_desc ON transactions (transaction_date DESC, id DESC);

-- Authoritative amortization/accounting entries for audited loans. Cash
-- activity remains in transactions; principal and interest live here.
CREATE TABLE IF NOT EXISTS loan_payments (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loan_id               BIGINT NOT NULL REFERENCES loans(id) ON DELETE CASCADE,
  transaction_id        BIGINT REFERENCES transactions(id) ON DELETE SET NULL,
  installment_number    INTEGER,
  payment_date          DATE NOT NULL,
  payment_amount        NUMERIC(18, 2) NOT NULL CHECK (payment_amount >= 0),
  principal_amount      NUMERIC(24, 10) NOT NULL CHECK (principal_amount >= 0),
  interest_amount       NUMERIC(24, 10) NOT NULL CHECK (interest_amount >= 0),
  annual_interest_rate  NUMERIC(12, 6) CHECK (
    annual_interest_rate IS NULL OR annual_interest_rate >= 0
  ),
  source_kind           TEXT NOT NULL
                        CHECK (source_kind IN ('existing_transaction', 'reconstructed', 'manual', 'generated')),
  payment_kind          TEXT NOT NULL DEFAULT 'installment'
                        CHECK (payment_kind IN ('installment', 'catch_up', 'irregular_payment', 'balance_adjustment', 'early_payoff')),
  installments_covered  INTEGER NOT NULL DEFAULT 1,
  other_amount          NUMERIC(24, 10) NOT NULL DEFAULT 0,
  balance_adjustment_amount NUMERIC(24, 10) NOT NULL DEFAULT 0,
  scheduled_due_date    DATE,
  next_scheduled_due_date DATE,
  auto_payment_enabled_before BOOLEAN,
  notes                 TEXT,
  created_at            TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at            TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT timezone('utc'::text, now()),
  UNIQUE (transaction_id),
  CHECK (
    (payment_kind = 'installment' AND installment_number IS NOT NULL
      AND installment_number > 0 AND installments_covered = 1)
    OR (payment_kind = 'catch_up' AND installment_number IS NULL
      AND installments_covered >= 1)
    OR (payment_kind IN ('irregular_payment', 'balance_adjustment', 'early_payoff')
      AND installment_number IS NULL AND installments_covered = 0)
  ),
  CONSTRAINT loan_payments_irregular_payment_shape_check CHECK (
    payment_kind <> 'irregular_payment'
    OR (payment_amount > 0 AND balance_adjustment_amount = 0)
  ),
  CONSTRAINT loan_payments_balance_adjustment_shape_check CHECK (
    payment_kind <> 'balance_adjustment'
    OR (transaction_id IS NULL AND payment_amount = 0
      AND principal_amount = 0 AND interest_amount = 0 AND other_amount = 0)
  ),
  CONSTRAINT loan_payments_components_reconcile CHECK (
    abs(payment_amount - principal_amount - interest_amount - other_amount)
      <= 0.00000001
  )
);

CREATE INDEX idx_loan_payments_loan_date
  ON loan_payments (loan_id, payment_date, installment_number);
CREATE UNIQUE INDEX loan_payments_unique_installment
  ON loan_payments (loan_id, installment_number)
  WHERE payment_kind = 'installment';
CREATE UNIQUE INDEX loan_payments_unique_early_payoff
  ON loan_payments (loan_id)
  WHERE payment_kind = 'early_payoff';

