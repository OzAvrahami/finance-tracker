CREATE OR REPLACE FUNCTION public.add_manual_budget_funding(
  p_month TEXT,
  p_amount NUMERIC,
  p_source_label TEXT,
  p_request_key UUID,
  p_reason TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_month_start DATE := public.budget_month_start_from_key(p_month);
  v_month_id BIGINT;
  v_existing public.budget_operations%ROWTYPE;
  v_fingerprint TEXT;
BEGIN
  IF p_amount IS NULL OR p_amount::text IN ('NaN', 'Infinity', '-Infinity')
     OR p_amount <= 0 OR p_amount <> round(p_amount, 2)
     OR p_amount > 9999999999999999.99 THEN
    RAISE EXCEPTION 'Manual funding amount must be a positive two-decimal value' USING ERRCODE = '22023';
  END IF;
  IF p_source_label IS NULL OR btrim(p_source_label) = '' THEN
    RAISE EXCEPTION 'Manual funding source label is required' USING ERRCODE = '22023';
  END IF;
  IF p_request_key IS NULL THEN
    RAISE EXCEPTION 'request_key is required' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.budget_months (month_start) VALUES (v_month_start)
  ON CONFLICT (month_start) DO NOTHING;
  SELECT id INTO v_month_id FROM public.budget_months
  WHERE month_start = v_month_start FOR UPDATE;

  v_fingerprint := 'manual_funding|' || p_month || '|' || p_amount::numeric(18, 2)::text || '|' || btrim(p_source_label);
  SELECT * INTO v_existing FROM public.budget_operations WHERE request_key = p_request_key;
  IF FOUND THEN
    IF v_existing.budget_month_id <> v_month_id
       OR v_existing.operation_type <> 'manual_funding'
       OR v_existing.request_fingerprint <> v_fingerprint THEN
      RAISE EXCEPTION 'request_key was already used for a different budget operation' USING ERRCODE = '23505';
    END IF;
    RETURN public.get_funded_budget_month(p_month);
  END IF;

  INSERT INTO public.budget_operations (
    budget_month_id, request_key, request_fingerprint, operation_type,
    effective_date, reason
  ) VALUES (
    v_month_id, p_request_key, v_fingerprint, 'manual_funding', v_month_start, p_reason
  ) RETURNING id INTO v_existing.id;

  INSERT INTO public.budget_funding_entries (
    operation_id, amount_delta, source_kind, source_label
  ) VALUES (
    v_existing.id, p_amount::numeric(18, 2), 'manual_available_funds', btrim(p_source_label)
  );

  PERFORM public.budget_assert_reconciled(v_month_id);
  RETURN public.get_funded_budget_month(p_month);
END;
$$;

CREATE OR REPLACE FUNCTION public.establish_funded_budget(
  p_month TEXT,
  p_category_id BIGINT,
  p_starting_amount NUMERIC,
  p_starting_kind TEXT,
  p_request_key UUID,
  p_reason TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_month_start DATE := public.budget_month_start_from_key(p_month);
  v_month_id BIGINT;
  v_operation_id BIGINT;
  v_budget_id BIGINT;
  v_existing public.budget_operations%ROWTYPE;
  v_unallocated NUMERIC(18, 2);
  v_fingerprint TEXT;
BEGIN
  IF p_starting_amount IS NULL OR p_starting_amount::text IN ('NaN', 'Infinity', '-Infinity')
     OR p_starting_amount < 0 OR p_starting_amount <> round(p_starting_amount, 2)
     OR p_starting_amount > 9999999999999999.99 THEN
    RAISE EXCEPTION 'starting_amount must be a nonnegative two-decimal value' USING ERRCODE = '22023';
  END IF;
  IF p_starting_kind NOT IN ('manual', 'copied') THEN
    RAISE EXCEPTION 'Runtime starting_kind must be manual or copied' USING ERRCODE = '22023';
  END IF;
  IF p_request_key IS NULL THEN
    RAISE EXCEPTION 'request_key is required' USING ERRCODE = '22023';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.categories WHERE id = p_category_id AND type = 'expense'
  ) THEN
    RAISE EXCEPTION 'Category % is not an expense category', p_category_id USING ERRCODE = '23503';
  END IF;

  INSERT INTO public.budget_months (month_start) VALUES (v_month_start)
  ON CONFLICT (month_start) DO NOTHING;
  SELECT id INTO v_month_id FROM public.budget_months
  WHERE month_start = v_month_start FOR UPDATE;

  v_fingerprint := 'establish|' || p_month || '|' || p_category_id || '|' || p_starting_amount::numeric(18, 2)::text || '|' || p_starting_kind;
  SELECT * INTO v_existing FROM public.budget_operations WHERE request_key = p_request_key;
  IF FOUND THEN
    IF v_existing.budget_month_id <> v_month_id
       OR v_existing.operation_type <> 'establish_budget'
       OR v_existing.request_fingerprint <> v_fingerprint THEN
      RAISE EXCEPTION 'request_key was already used for a different budget operation' USING ERRCODE = '23505';
    END IF;
    RETURN public.get_funded_budget_month(p_month);
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.budgets
    WHERE budget_month_id = v_month_id AND category_id = p_category_id
  ) THEN
    RAISE EXCEPTION 'A monthly budget snapshot already exists for category %', p_category_id USING ERRCODE = '23505';
  END IF;

  SELECT unallocated INTO v_unallocated
  FROM public.budget_month_funding_state
  WHERE budget_month_id = v_month_id;
  IF p_starting_amount > coalesce(v_unallocated, 0) THEN
    RAISE EXCEPTION 'Insufficient unallocated funds: requested %, available %', p_starting_amount, coalesce(v_unallocated, 0)
      USING ERRCODE = '23514';
  END IF;

  INSERT INTO public.budget_operations (
    budget_month_id, request_key, request_fingerprint, operation_type,
    effective_date, reason
  ) VALUES (
    v_month_id, p_request_key, v_fingerprint, 'establish_budget', v_month_start, p_reason
  ) RETURNING id INTO v_operation_id;

  INSERT INTO public.budgets (
    category_id, month, amount, budget_month_id, starting_amount,
    starting_kind, created_by_operation_id
  ) VALUES (
    p_category_id, p_month, p_starting_amount, v_month_id, p_starting_amount,
    p_starting_kind, v_operation_id
  ) RETURNING id INTO v_budget_id;

  INSERT INTO public.budget_lifecycle_events (operation_id, budget_id, state)
  VALUES (v_operation_id, v_budget_id, 'active');

  PERFORM public.budget_assert_reconciled(v_month_id);
  RETURN public.get_funded_budget_month(p_month);
END;
$$;

CREATE OR REPLACE FUNCTION public.set_funded_budget_amount(
  p_budget_id BIGINT,
  p_target_amount NUMERIC,
  p_request_key UUID,
  p_reason TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_budget public.budgets%ROWTYPE;
  v_month public.budget_months%ROWTYPE;
  v_state public.budget_category_state%ROWTYPE;
  v_latest_state TEXT;
  v_actual NUMERIC(18, 2);
  v_unallocated NUMERIC(18, 2);
  v_delta NUMERIC(18, 2);
  v_operation_id BIGINT;
  v_existing public.budget_operations%ROWTYPE;
  v_fingerprint TEXT;
BEGIN
  IF p_target_amount IS NULL OR p_target_amount::text IN ('NaN', 'Infinity', '-Infinity')
     OR p_target_amount < 0 OR p_target_amount <> round(p_target_amount, 2)
     OR p_target_amount > 9999999999999999.99 THEN
    RAISE EXCEPTION 'target_amount must be a nonnegative two-decimal value' USING ERRCODE = '22023';
  END IF;
  IF p_request_key IS NULL THEN RAISE EXCEPTION 'request_key is required' USING ERRCODE = '22023'; END IF;

  SELECT * INTO v_budget FROM public.budgets WHERE id = p_budget_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Budget % does not exist', p_budget_id USING ERRCODE = 'P0002'; END IF;
  SELECT * INTO v_month FROM public.budget_months WHERE id = v_budget.budget_month_id FOR UPDATE;
  SELECT * INTO v_budget FROM public.budgets WHERE id = p_budget_id FOR UPDATE;
  SELECT * INTO v_state FROM public.budget_category_state WHERE budget_id = p_budget_id;
  v_latest_state := v_state.lifecycle_state;

  v_fingerprint := 'set_amount|' || p_budget_id || '|' || p_target_amount::numeric(18, 2)::text;
  SELECT * INTO v_existing FROM public.budget_operations WHERE request_key = p_request_key;
  IF FOUND THEN
    IF v_existing.budget_month_id <> v_month.id
       OR v_existing.operation_type <> 'adjustment'
       OR v_existing.request_fingerprint <> v_fingerprint THEN
      RAISE EXCEPTION 'request_key was already used for a different budget operation' USING ERRCODE = '23505';
    END IF;
    RETURN public.get_funded_budget_month(to_char(v_month.month_start, 'YYYY-MM'));
  END IF;

  IF v_latest_state <> 'active' THEN
    RAISE EXCEPTION 'Budget % is inactive; reactivate it before adjusting funding', p_budget_id USING ERRCODE = '55000';
  END IF;
  v_delta := p_target_amount - v_state.final_funded;
  IF v_delta = 0 THEN
    INSERT INTO public.budget_operations (
      budget_month_id, request_key, request_fingerprint, operation_type, effective_date, reason
    ) VALUES (v_month.id, p_request_key, v_fingerprint, 'adjustment', v_month.month_start, p_reason);
    PERFORM public.budget_assert_reconciled(v_month.id);
    RETURN public.get_funded_budget_month(to_char(v_month.month_start, 'YYYY-MM'));
  END IF;

  SELECT unallocated INTO v_unallocated FROM public.budget_month_funding_state
  WHERE budget_month_id = v_month.id;
  IF EXISTS (
    SELECT 1 FROM public.transactions
    WHERE movement_type = 'expense' AND category_id = v_budget.category_id
      AND transaction_date >= v_month.month_start
      AND transaction_date < (v_month.month_start + interval '1 month')::date
      AND total_amount::text IN ('NaN', 'Infinity', '-Infinity')
  ) THEN
    RAISE EXCEPTION 'Budget actual spending contains a non-finite amount' USING ERRCODE = '22003';
  END IF;
  SELECT coalesce(sum(total_amount), 0)::numeric(18, 2) INTO v_actual
  FROM public.transactions
  WHERE movement_type = 'expense' AND category_id = v_budget.category_id
    AND transaction_date >= v_month.month_start
    AND transaction_date < (v_month.month_start + interval '1 month')::date;

  IF v_delta > 0 AND v_delta > v_unallocated THEN
    RAISE EXCEPTION 'Insufficient unallocated funds: requested %, available %', v_delta, v_unallocated USING ERRCODE = '23514';
  END IF;
  IF v_delta < 0 AND -v_delta > greatest(v_state.final_funded - v_actual, 0) THEN
    RAISE EXCEPTION 'Cannot release spent funding; eligible release is %', greatest(v_state.final_funded - v_actual, 0)
      USING ERRCODE = '23514';
  END IF;

  INSERT INTO public.budget_operations (
    budget_month_id, request_key, request_fingerprint, operation_type, effective_date, reason
  ) VALUES (v_month.id, p_request_key, v_fingerprint, 'adjustment', v_month.month_start, p_reason)
  RETURNING id INTO v_operation_id;

  INSERT INTO public.budget_movements (operation_id, source_budget_id, destination_budget_id, amount)
  VALUES (
    v_operation_id,
    CASE WHEN v_delta < 0 THEN p_budget_id ELSE NULL END,
    CASE WHEN v_delta > 0 THEN p_budget_id ELSE NULL END,
    abs(v_delta)
  );

  PERFORM public.budget_assert_reconciled(v_month.id);
  RETURN public.get_funded_budget_month(to_char(v_month.month_start, 'YYYY-MM'));
END;
$$;

CREATE OR REPLACE FUNCTION public.remove_funded_budget(
  p_budget_id BIGINT,
  p_request_key UUID,
  p_reason TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_budget public.budgets%ROWTYPE;
  v_month public.budget_months%ROWTYPE;
  v_state public.budget_category_state%ROWTYPE;
  v_actual NUMERIC(18, 2);
  v_release NUMERIC(18, 2);
  v_operation_id BIGINT;
  v_existing public.budget_operations%ROWTYPE;
  v_fingerprint TEXT;
BEGIN
  IF p_request_key IS NULL THEN RAISE EXCEPTION 'request_key is required' USING ERRCODE = '22023'; END IF;
  SELECT * INTO v_budget FROM public.budgets WHERE id = p_budget_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Budget % does not exist', p_budget_id USING ERRCODE = 'P0002'; END IF;
  SELECT * INTO v_month FROM public.budget_months WHERE id = v_budget.budget_month_id FOR UPDATE;
  SELECT * INTO v_budget FROM public.budgets WHERE id = p_budget_id FOR UPDATE;
  v_fingerprint := 'remove|' || p_budget_id;
  SELECT * INTO v_existing FROM public.budget_operations WHERE request_key = p_request_key;
  IF FOUND THEN
    IF v_existing.budget_month_id <> v_month.id OR v_existing.operation_type <> 'removal'
       OR v_existing.request_fingerprint <> v_fingerprint THEN
      RAISE EXCEPTION 'request_key was already used for a different budget operation' USING ERRCODE = '23505';
    END IF;
    RETURN public.get_funded_budget_month(to_char(v_month.month_start, 'YYYY-MM'));
  END IF;

  SELECT * INTO v_state FROM public.budget_category_state WHERE budget_id = p_budget_id;
  IF v_state.lifecycle_state <> 'active' THEN
    RAISE EXCEPTION 'Budget % is not active', p_budget_id USING ERRCODE = '55000';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.transactions
    WHERE movement_type = 'expense' AND category_id = v_budget.category_id
      AND transaction_date >= v_month.month_start
      AND transaction_date < (v_month.month_start + interval '1 month')::date
      AND total_amount::text IN ('NaN', 'Infinity', '-Infinity')
  ) THEN
    RAISE EXCEPTION 'Budget actual spending contains a non-finite amount' USING ERRCODE = '22003';
  END IF;
  SELECT coalesce(sum(total_amount), 0)::numeric(18, 2) INTO v_actual
  FROM public.transactions
  WHERE movement_type = 'expense' AND category_id = v_budget.category_id
    AND transaction_date >= v_month.month_start
    AND transaction_date < (v_month.month_start + interval '1 month')::date;
  v_release := greatest(v_state.final_funded - v_actual, 0);

  INSERT INTO public.budget_operations (
    budget_month_id, request_key, request_fingerprint, operation_type, effective_date, reason
  ) VALUES (v_month.id, p_request_key, v_fingerprint, 'removal', v_month.month_start, p_reason)
  RETURNING id INTO v_operation_id;
  IF v_release > 0 THEN
    INSERT INTO public.budget_movements (operation_id, source_budget_id, destination_budget_id, amount)
    VALUES (v_operation_id, p_budget_id, NULL, v_release);
  END IF;
  INSERT INTO public.budget_lifecycle_events (operation_id, budget_id, state, actual_spent_snapshot)
  VALUES (v_operation_id, p_budget_id, 'inactive', v_actual);

  PERFORM public.budget_assert_reconciled(v_month.id);
  RETURN public.get_funded_budget_month(to_char(v_month.month_start, 'YYYY-MM'));
END;
$$;

CREATE OR REPLACE FUNCTION public.reactivate_funded_budget(
  p_budget_id BIGINT,
  p_additional_amount NUMERIC,
  p_request_key UUID,
  p_reason TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_budget public.budgets%ROWTYPE;
  v_month public.budget_months%ROWTYPE;
  v_state public.budget_category_state%ROWTYPE;
  v_unallocated NUMERIC(18, 2);
  v_operation_id BIGINT;
  v_existing public.budget_operations%ROWTYPE;
  v_fingerprint TEXT;
BEGIN
  IF p_additional_amount IS NULL OR p_additional_amount::text IN ('NaN', 'Infinity', '-Infinity')
     OR p_additional_amount < 0 OR p_additional_amount <> round(p_additional_amount, 2)
     OR p_additional_amount > 9999999999999999.99 THEN
    RAISE EXCEPTION 'additional_amount must be a nonnegative two-decimal value' USING ERRCODE = '22023';
  END IF;
  IF p_request_key IS NULL THEN RAISE EXCEPTION 'request_key is required' USING ERRCODE = '22023'; END IF;
  SELECT * INTO v_budget FROM public.budgets WHERE id = p_budget_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Budget % does not exist', p_budget_id USING ERRCODE = 'P0002'; END IF;
  SELECT * INTO v_month FROM public.budget_months WHERE id = v_budget.budget_month_id FOR UPDATE;
  SELECT * INTO v_budget FROM public.budgets WHERE id = p_budget_id FOR UPDATE;
  v_fingerprint := 'reactivate|' || p_budget_id || '|' || p_additional_amount::numeric(18, 2)::text;
  SELECT * INTO v_existing FROM public.budget_operations WHERE request_key = p_request_key;
  IF FOUND THEN
    IF v_existing.budget_month_id <> v_month.id OR v_existing.operation_type <> 'reactivation'
       OR v_existing.request_fingerprint <> v_fingerprint THEN
      RAISE EXCEPTION 'request_key was already used for a different budget operation' USING ERRCODE = '23505';
    END IF;
    RETURN public.get_funded_budget_month(to_char(v_month.month_start, 'YYYY-MM'));
  END IF;
  SELECT * INTO v_state FROM public.budget_category_state WHERE budget_id = p_budget_id;
  IF v_state.lifecycle_state <> 'inactive' THEN
    RAISE EXCEPTION 'Budget % is not inactive', p_budget_id USING ERRCODE = '55000';
  END IF;
  SELECT unallocated INTO v_unallocated FROM public.budget_month_funding_state WHERE budget_month_id = v_month.id;
  IF p_additional_amount > v_unallocated THEN
    RAISE EXCEPTION 'Insufficient unallocated funds: requested %, available %', p_additional_amount, v_unallocated
      USING ERRCODE = '23514';
  END IF;

  INSERT INTO public.budget_operations (
    budget_month_id, request_key, request_fingerprint, operation_type, effective_date, reason
  ) VALUES (v_month.id, p_request_key, v_fingerprint, 'reactivation', v_month.month_start, p_reason)
  RETURNING id INTO v_operation_id;
  IF p_additional_amount > 0 THEN
    INSERT INTO public.budget_movements (operation_id, destination_budget_id, amount)
    VALUES (v_operation_id, p_budget_id, p_additional_amount);
  END IF;
  INSERT INTO public.budget_lifecycle_events (operation_id, budget_id, state)
  VALUES (v_operation_id, p_budget_id, 'active');

  PERFORM public.budget_assert_reconciled(v_month.id);
  RETURN public.get_funded_budget_month(to_char(v_month.month_start, 'YYYY-MM'));
END;
$$;

CREATE OR REPLACE FUNCTION public.reverse_funded_budget_operation(
  p_operation_id BIGINT,
  p_request_key UUID,
  p_reason TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_original public.budget_operations%ROWTYPE;
  v_month public.budget_months%ROWTYPE;
  v_existing public.budget_operations%ROWTYPE;
  v_funding public.budget_funding_entries%ROWTYPE;
  v_movement public.budget_movements%ROWTYPE;
  v_source_state public.budget_category_state%ROWTYPE;
  v_actual NUMERIC(18, 2);
  v_unallocated NUMERIC(18, 2);
  v_reversal_id BIGINT;
  v_fingerprint TEXT;
BEGIN
  IF p_request_key IS NULL THEN RAISE EXCEPTION 'request_key is required' USING ERRCODE = '22023'; END IF;
  SELECT * INTO v_original FROM public.budget_operations WHERE id = p_operation_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Budget operation % does not exist', p_operation_id USING ERRCODE = 'P0002'; END IF;
  SELECT * INTO v_month FROM public.budget_months WHERE id = v_original.budget_month_id FOR UPDATE;
  SELECT * INTO v_original FROM public.budget_operations WHERE id = p_operation_id;
  v_fingerprint := 'reverse|' || p_operation_id;
  SELECT * INTO v_existing FROM public.budget_operations WHERE request_key = p_request_key;
  IF FOUND THEN
    IF v_existing.operation_type <> 'reversal' OR v_existing.reverses_operation_id <> p_operation_id
       OR v_existing.request_fingerprint <> v_fingerprint THEN
      RAISE EXCEPTION 'request_key was already used for a different budget operation' USING ERRCODE = '23505';
    END IF;
    RETURN public.get_funded_budget_month(to_char(v_month.month_start, 'YYYY-MM'));
  END IF;
  IF EXISTS (SELECT 1 FROM public.budget_operations WHERE reverses_operation_id = p_operation_id) THEN
    RAISE EXCEPTION 'Budget operation % has already been reversed', p_operation_id USING ERRCODE = '23505';
  END IF;

  IF v_original.operation_type = 'adjustment' THEN
    SELECT * INTO v_movement FROM public.budget_movements WHERE operation_id = p_operation_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Adjustment operation % has no movement', p_operation_id; END IF;
    PERFORM 1 FROM public.budgets
    WHERE id IN (v_movement.source_budget_id, v_movement.destination_budget_id)
    ORDER BY id FOR UPDATE;
  END IF;

  INSERT INTO public.budget_operations (
    budget_month_id, request_key, request_fingerprint, operation_type,
    effective_date, reason, reverses_operation_id
  ) VALUES (
    v_month.id, p_request_key, v_fingerprint, 'reversal', v_month.month_start,
    p_reason, p_operation_id
  ) RETURNING id INTO v_reversal_id;

  IF v_original.operation_type = 'manual_funding' THEN
    SELECT * INTO v_funding FROM public.budget_funding_entries WHERE operation_id = p_operation_id;
    IF v_funding.source_kind <> 'manual_available_funds' OR v_funding.amount_delta <= 0 THEN
      RAISE EXCEPTION 'Only positive manual funding operations can be reversed';
    END IF;
    SELECT unallocated INTO v_unallocated FROM public.budget_month_funding_state WHERE budget_month_id = v_month.id;
    IF v_funding.amount_delta > v_unallocated THEN
      RAISE EXCEPTION 'Funding reversal would make unallocated funds negative' USING ERRCODE = '23514';
    END IF;
    INSERT INTO public.budget_funding_entries (
      operation_id, amount_delta, source_kind, source_label, reverses_funding_entry_id
    ) VALUES (
      v_reversal_id, -v_funding.amount_delta, 'manual_available_funds',
      'Reversal: ' || v_funding.source_label, v_funding.id
    );
  ELSIF v_original.operation_type = 'adjustment' THEN
    IF v_movement.source_budget_id IS NULL THEN
      SELECT * INTO v_source_state FROM public.budget_category_state WHERE budget_id = v_movement.destination_budget_id;
      IF EXISTS (
        SELECT 1 FROM public.transactions t
        JOIN public.budgets b ON b.category_id = t.category_id
        WHERE b.id = v_movement.destination_budget_id
          AND t.movement_type = 'expense'
          AND t.transaction_date >= v_month.month_start
          AND t.transaction_date < (v_month.month_start + interval '1 month')::date
          AND t.total_amount::text IN ('NaN', 'Infinity', '-Infinity')
      ) THEN
        RAISE EXCEPTION 'Budget actual spending contains a non-finite amount' USING ERRCODE = '22003';
      END IF;
      SELECT coalesce(sum(t.total_amount), 0)::numeric(18, 2) INTO v_actual
      FROM public.transactions t
      JOIN public.budgets b ON b.category_id = t.category_id
      WHERE b.id = v_movement.destination_budget_id
        AND t.movement_type = 'expense'
        AND t.transaction_date >= v_month.month_start
        AND t.transaction_date < (v_month.month_start + interval '1 month')::date;
      IF v_movement.amount > greatest(v_source_state.final_funded - v_actual, 0) THEN
        RAISE EXCEPTION 'Adjustment reversal would release spent funding' USING ERRCODE = '23514';
      END IF;
    ELSE
      SELECT unallocated INTO v_unallocated FROM public.budget_month_funding_state WHERE budget_month_id = v_month.id;
      IF v_movement.amount > v_unallocated THEN
        RAISE EXCEPTION 'Adjustment reversal requires more unallocated funds than are available' USING ERRCODE = '23514';
      END IF;
    END IF;
    INSERT INTO public.budget_movements (
      operation_id, source_budget_id, destination_budget_id, amount
    ) VALUES (
      v_reversal_id, v_movement.destination_budget_id, v_movement.source_budget_id, v_movement.amount
    );
  ELSE
    RAISE EXCEPTION
      'Operation type % must be corrected through its lifecycle command, not generic reversal',
      v_original.operation_type USING ERRCODE = '0A000';
  END IF;

  PERFORM public.budget_assert_reconciled(v_month.id);
  RETURN public.get_funded_budget_month(to_char(v_month.month_start, 'YYYY-MM'));
END;
$$;

CREATE OR REPLACE FUNCTION public.copy_funded_budget_month(
  p_from_month TEXT,
  p_to_month TEXT,
  p_request_key UUID,
  p_reason TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_from_start DATE := public.budget_month_start_from_key(p_from_month);
  v_to_start DATE := public.budget_month_start_from_key(p_to_month);
  v_from_id BIGINT;
  v_to_id BIGINT;
  v_operation_id BIGINT;
  v_existing public.budget_operations%ROWTYPE;
  v_unallocated NUMERIC(18, 2);
  v_additions NUMERIC(18, 2) := 0;
  v_releases NUMERIC(18, 2) := 0;
  v_target_actual NUMERIC(18, 2);
  v_target_id BIGINT;
  v_target_final NUMERIC(18, 2);
  v_target_state TEXT;
  v_delta NUMERIC(18, 2);
  v_fingerprint TEXT;
  source_row RECORD;
BEGIN
  IF p_request_key IS NULL THEN RAISE EXCEPTION 'request_key is required' USING ERRCODE = '22023'; END IF;
  IF v_from_start = v_to_start THEN RAISE EXCEPTION 'Source and target budget months must differ' USING ERRCODE = '22023'; END IF;
  SELECT id INTO v_from_id FROM public.budget_months WHERE month_start = v_from_start;
  IF NOT FOUND THEN RAISE EXCEPTION 'Source month has no funded budget'; END IF;
  INSERT INTO public.budget_months (month_start) VALUES (v_to_start) ON CONFLICT (month_start) DO NOTHING;
  PERFORM 1 FROM public.budget_months WHERE id IN (v_from_id, (SELECT id FROM public.budget_months WHERE month_start = v_to_start)) ORDER BY id FOR UPDATE;
  SELECT id INTO v_to_id FROM public.budget_months WHERE month_start = v_to_start;
  PERFORM 1 FROM public.budgets
  WHERE budget_month_id IN (v_from_id, v_to_id)
  ORDER BY id FOR UPDATE;
  PERFORM public.budget_assert_reconciled(v_from_id);
  PERFORM public.budget_assert_reconciled(v_to_id);

  v_fingerprint := 'copy|' || p_from_month || '|' || p_to_month;
  SELECT * INTO v_existing FROM public.budget_operations WHERE request_key = p_request_key;
  IF FOUND THEN
    IF v_existing.budget_month_id <> v_to_id OR v_existing.operation_type <> 'copy'
       OR v_existing.request_fingerprint <> v_fingerprint THEN
      RAISE EXCEPTION 'request_key was already used for a different budget operation' USING ERRCODE = '23505';
    END IF;
    RETURN public.get_funded_budget_month(p_to_month);
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.budget_category_state
    WHERE budget_month_id = v_from_id AND lifecycle_state = 'active'
  ) THEN
    RAISE EXCEPTION 'Source month has no active category budgets';
  END IF;

  FOR source_row IN
    SELECT * FROM public.budget_category_state
    WHERE budget_month_id = v_from_id AND lifecycle_state = 'active'
    ORDER BY category_id
  LOOP
    SELECT cs.budget_id, cs.final_funded, cs.lifecycle_state
    INTO v_target_id, v_target_final, v_target_state
    FROM public.budget_category_state cs
    WHERE cs.budget_month_id = v_to_id AND cs.category_id = source_row.category_id;
    IF NOT FOUND THEN
      v_additions := v_additions + source_row.final_funded;
    ELSE
      v_delta := source_row.final_funded - v_target_final;
      IF v_delta > 0 THEN
        v_additions := v_additions + v_delta;
      ELSIF v_delta < 0 THEN
        IF EXISTS (
          SELECT 1 FROM public.transactions
          WHERE movement_type = 'expense' AND category_id = source_row.category_id
            AND transaction_date >= v_to_start
            AND transaction_date < (v_to_start + interval '1 month')::date
            AND total_amount::text IN ('NaN', 'Infinity', '-Infinity')
        ) THEN
          RAISE EXCEPTION 'Budget actual spending contains a non-finite amount' USING ERRCODE = '22003';
        END IF;
        SELECT coalesce(sum(total_amount), 0)::numeric(18, 2) INTO v_target_actual
        FROM public.transactions
        WHERE movement_type = 'expense' AND category_id = source_row.category_id
          AND transaction_date >= v_to_start
          AND transaction_date < (v_to_start + interval '1 month')::date;
        IF -v_delta > greatest(v_target_final - v_target_actual, 0) THEN
          RAISE EXCEPTION 'Copy cannot release spent funding from target category %', source_row.category_id USING ERRCODE = '23514';
        END IF;
        v_releases := v_releases + (-v_delta);
      END IF;
    END IF;
  END LOOP;

  SELECT unallocated INTO v_unallocated FROM public.budget_month_funding_state WHERE budget_month_id = v_to_id;
  IF v_additions > v_unallocated + v_releases THEN
    RAISE EXCEPTION 'Destination month needs % additional funded money; only % is available',
      v_additions, v_unallocated + v_releases USING ERRCODE = '23514';
  END IF;

  INSERT INTO public.budget_operations (
    budget_month_id, request_key, request_fingerprint, operation_type, effective_date, reason
  ) VALUES (v_to_id, p_request_key, v_fingerprint, 'copy', v_to_start, p_reason)
  RETURNING id INTO v_operation_id;

  FOR source_row IN
    SELECT * FROM public.budget_category_state
    WHERE budget_month_id = v_from_id AND lifecycle_state = 'active'
    ORDER BY category_id
  LOOP
    SELECT cs.budget_id, cs.final_funded, cs.lifecycle_state
    INTO v_target_id, v_target_final, v_target_state
    FROM public.budget_category_state cs
    WHERE cs.budget_month_id = v_to_id AND cs.category_id = source_row.category_id;
    IF NOT FOUND THEN
      INSERT INTO public.budgets (
        category_id, month, amount, budget_month_id, starting_amount,
        starting_kind, created_by_operation_id
      ) VALUES (
        source_row.category_id, p_to_month, source_row.final_funded, v_to_id,
        source_row.final_funded, 'copied', v_operation_id
      ) RETURNING id INTO v_target_id;
      INSERT INTO public.budget_lifecycle_events (operation_id, budget_id, state)
      VALUES (v_operation_id, v_target_id, 'active');
    ELSE
      v_delta := source_row.final_funded - v_target_final;
      IF v_delta <> 0 THEN
        INSERT INTO public.budget_movements (
          operation_id, source_budget_id, destination_budget_id, amount
        ) VALUES (
          v_operation_id,
          CASE WHEN v_delta < 0 THEN v_target_id ELSE NULL END,
          CASE WHEN v_delta > 0 THEN v_target_id ELSE NULL END,
          abs(v_delta)
        );
      END IF;
      IF v_target_state = 'inactive' THEN
        INSERT INTO public.budget_lifecycle_events (operation_id, budget_id, state)
        VALUES (v_operation_id, v_target_id, 'active');
      END IF;
    END IF;
  END LOOP;

  PERFORM public.budget_assert_reconciled(v_to_id);
  RETURN public.get_funded_budget_month(p_to_month);
END;
$$;

