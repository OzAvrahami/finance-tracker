CREATE OR REPLACE FUNCTION public.validate_budget_snapshot_insert()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_month public.budget_months%ROWTYPE;
  v_operation public.budget_operations%ROWTYPE;
BEGIN
  SELECT * INTO v_month FROM public.budget_months WHERE id = NEW.budget_month_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Budget month % does not exist', NEW.budget_month_id;
  END IF;
  IF NEW.month <> to_char(v_month.month_start, 'YYYY-MM') THEN
    RAISE EXCEPTION 'Legacy month % does not match canonical month %', NEW.month, v_month.month_start;
  END IF;
  IF NEW.amount::text IN ('NaN', 'Infinity', '-Infinity')
     OR NEW.starting_amount::text IN ('NaN', 'Infinity', '-Infinity') THEN
    RAISE EXCEPTION 'Budget starting values must be finite';
  END IF;
  IF NEW.amount <> NEW.starting_amount THEN
    RAISE EXCEPTION 'Legacy amount must equal immutable starting_amount on insert';
  END IF;
  SELECT * INTO v_operation FROM public.budget_operations WHERE id = NEW.created_by_operation_id;
  IF NOT FOUND OR v_operation.budget_month_id <> NEW.budget_month_id THEN
    RAISE EXCEPTION 'Budget creation operation does not belong to the budget month';
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.validate_budget_operation_insert()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_month_start DATE;
BEGIN
  SELECT month_start INTO v_month_start
  FROM public.budget_months
  WHERE id = NEW.budget_month_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Budget month % does not exist', NEW.budget_month_id;
  END IF;
  IF NEW.effective_date < v_month_start
     OR NEW.effective_date >= (v_month_start + interval '1 month')::date THEN
    RAISE EXCEPTION 'Budget operation effective_date must be within its budget month';
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.validate_budget_movement_insert()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_operation_month BIGINT;
  v_source_month BIGINT;
  v_destination_month BIGINT;
BEGIN
  SELECT budget_month_id INTO v_operation_month
  FROM public.budget_operations
  WHERE id = NEW.operation_id;

  IF NEW.source_budget_id IS NOT NULL THEN
    SELECT budget_month_id INTO v_source_month
    FROM public.budgets
    WHERE id = NEW.source_budget_id;
    IF v_source_month IS DISTINCT FROM v_operation_month THEN
      RAISE EXCEPTION 'Movement source budget is outside the operation month';
    END IF;
  END IF;

  IF NEW.destination_budget_id IS NOT NULL THEN
    SELECT budget_month_id INTO v_destination_month
    FROM public.budgets
    WHERE id = NEW.destination_budget_id;
    IF v_destination_month IS DISTINCT FROM v_operation_month THEN
      RAISE EXCEPTION 'Movement destination budget is outside the operation month';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.validate_budget_lifecycle_insert()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_operation_month BIGINT;
  v_budget_month BIGINT;
  v_previous_state TEXT;
BEGIN
  SELECT budget_month_id INTO v_operation_month
  FROM public.budget_operations
  WHERE id = NEW.operation_id;
  SELECT budget_month_id INTO v_budget_month
  FROM public.budgets
  WHERE id = NEW.budget_id;

  IF v_operation_month IS DISTINCT FROM v_budget_month THEN
    RAISE EXCEPTION 'Lifecycle event budget is outside the operation month';
  END IF;

  SELECT state INTO v_previous_state
  FROM public.budget_lifecycle_events
  WHERE budget_id = NEW.budget_id
  ORDER BY id DESC
  LIMIT 1;

  IF v_previous_state IS NULL AND NEW.state <> 'active' THEN
    RAISE EXCEPTION 'A monthly category budget must begin active';
  END IF;
  IF v_previous_state = NEW.state THEN
    RAISE EXCEPTION 'Budget lifecycle transition % -> % is invalid', v_previous_state, NEW.state;
  END IF;

  RETURN NEW;
END;
$$;

