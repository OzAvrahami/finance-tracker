CREATE VIEW public.budget_category_state AS
SELECT
  b.id AS budget_id,
  b.budget_month_id,
  to_char(bm.month_start, 'YYYY-MM') AS month,
  bm.month_start,
  bm.currency_code,
  b.category_id,
  c.name AS category_name,
  c.icon AS category_icon,
  c.type AS category_type,
  b.starting_amount,
  b.starting_amount::text AS starting_amount_text,
  b.starting_kind,
  coalesce(movements.incoming, 0)::numeric(18, 2)
    - coalesce(movements.outgoing, 0)::numeric(18, 2) AS adjustment_total,
  (coalesce(movements.incoming, 0)::numeric(18, 2)
    - coalesce(movements.outgoing, 0)::numeric(18, 2))::text AS adjustment_total_text,
  b.starting_amount
    + coalesce(movements.incoming, 0)::numeric(18, 2)
    - coalesce(movements.outgoing, 0)::numeric(18, 2) AS final_funded,
  (b.starting_amount
    + coalesce(movements.incoming, 0)::numeric(18, 2)
    - coalesce(movements.outgoing, 0)::numeric(18, 2))::text AS final_funded_text,
  lifecycle.state AS lifecycle_state,
  lifecycle.id AS lifecycle_event_id
FROM public.budgets b
JOIN public.budget_months bm ON bm.id = b.budget_month_id
JOIN public.categories c ON c.id = b.category_id
LEFT JOIN LATERAL (
  SELECT
    sum(m.amount) FILTER (WHERE m.destination_budget_id = b.id) AS incoming,
    sum(m.amount) FILTER (WHERE m.source_budget_id = b.id) AS outgoing
  FROM public.budget_movements m
  WHERE m.source_budget_id = b.id OR m.destination_budget_id = b.id
) movements ON true
JOIN LATERAL (
  SELECT le.id, le.state
  FROM public.budget_lifecycle_events le
  WHERE le.budget_id = b.id
  ORDER BY le.id DESC
  LIMIT 1
) lifecycle ON true;

CREATE VIEW public.budget_month_funding_state AS
SELECT
  bm.id AS budget_month_id,
  to_char(bm.month_start, 'YYYY-MM') AS month,
  bm.month_start,
  bm.currency_code,
  coalesce(f.available, 0)::numeric(18, 2) AS available,
  coalesce(s.starting_total, 0)::numeric(18, 2) AS starting_total,
  coalesce(s.total_allocated, 0)::numeric(18, 2) AS total_allocated,
  coalesce(s.active_allocated, 0)::numeric(18, 2) AS active_allocated,
  (coalesce(s.total_allocated, 0) - coalesce(s.active_allocated, 0))::numeric(18, 2)
    AS inactive_retained_funding,
  (coalesce(f.available, 0) - coalesce(s.total_allocated, 0))::numeric(18, 2)
    AS unallocated
FROM public.budget_months bm
LEFT JOIN LATERAL (
  SELECT sum(fe.amount_delta) AS available
  FROM public.budget_funding_entries fe
  JOIN public.budget_operations bo ON bo.id = fe.operation_id
  WHERE bo.budget_month_id = bm.id
) f ON true
LEFT JOIN LATERAL (
  SELECT
    sum(cs.starting_amount) AS starting_total,
    sum(cs.final_funded) AS total_allocated,
    sum(cs.final_funded) FILTER (WHERE cs.lifecycle_state = 'active') AS active_allocated
  FROM public.budget_category_state cs
  WHERE cs.budget_month_id = bm.id
) s ON true;

-- Exact annual/monthly compatibility input. The amount is aggregated in
-- PostgreSQL and exposed as text so PostgREST never converts NUMERIC to a
-- JavaScript floating-point value.
CREATE VIEW public.budget_month_category_actuals AS
SELECT
  to_char(date_trunc('month', t.transaction_date), 'YYYY-MM') AS month,
  t.category_id,
  c.name AS category_name,
  c.icon AS category_icon,
  sum(t.total_amount)::numeric(18, 2)::text AS actual_spent_text
FROM public.transactions t
LEFT JOIN public.categories c ON c.id = t.category_id
WHERE t.movement_type = 'expense'
GROUP BY date_trunc('month', t.transaction_date), t.category_id, c.name, c.icon;

