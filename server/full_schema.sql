AS $$
BEGIN
  IF p_month IS NULL OR p_month !~ '^\d{4}-(0[1-9]|1[0-2])$' THEN
    RAISE EXCEPTION 'month must be a canonical YYYY-MM value' USING ERRCODE = '22023';
  END IF;
  RETURN pg_catalog.to_date(p_month || '-01', 'YYYY-MM-DD');
END;
$$;

CREATE OR REPLACE FUNCTION public.budget_assert_reconciled(p_budget_month_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_state public.budget_month_funding_state%ROWTYPE;
  v_negative_budget BIGINT;
BEGIN
  SELECT * INTO v_state
  FROM public.budget_month_funding_state
  WHERE budget_month_id = p_budget_month_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Budget month % does not exist', p_budget_month_id;
  END IF;
  IF v_state.available::text IN ('NaN', 'Infinity', '-Infinity')
     OR v_state.starting_total::text IN ('NaN', 'Infinity', '-Infinity')
     OR v_state.total_allocated::text IN ('NaN', 'Infinity', '-Infinity')
     OR v_state.active_allocated::text IN ('NaN', 'Infinity', '-Infinity')
     OR v_state.inactive_retained_funding::text IN ('NaN', 'Infinity', '-Infinity')
     OR v_state.unallocated::text IN ('NaN', 'Infinity', '-Infinity')
     OR v_state.available < 0 OR v_state.total_allocated < 0 OR v_state.unallocated < 0 THEN
    RAISE EXCEPTION
      'Budget month % does not reconcile: available %, allocated %, unallocated %',
      p_budget_month_id, v_state.available, v_state.total_allocated, v_state.unallocated
      USING ERRCODE = '23514';
  END IF;

  SELECT budget_id INTO v_negative_budget
  FROM public.budget_category_state
  WHERE budget_month_id = p_budget_month_id
    AND (final_funded::text IN ('NaN', 'Infinity', '-Infinity') OR final_funded < 0)
  LIMIT 1;
  IF v_negative_budget IS NOT NULL THEN
    RAISE EXCEPTION 'Budget % has a negative final funded amount', v_negative_budget
      USING ERRCODE = '23514';
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.get_funded_budget_month(p_month TEXT)
RETURNS JSONB
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_month_start DATE := public.budget_month_start_from_key(p_month);
  v_month_id BIGINT;
  v_funding JSONB;
  v_categories JSONB;
  v_history JSONB;
  v_total_actual NUMERIC(18, 2);
  v_budgeted_actual NUMERIC(18, 2);
BEGIN
  SELECT id INTO v_month_id
  FROM public.budget_months
  WHERE month_start = v_month_start;

  IF EXISTS (
    SELECT 1 FROM public.transactions
    WHERE movement_type = 'expense'
      AND transaction_date >= v_month_start
      AND transaction_date < (v_month_start + interval '1 month')::date
      AND total_amount::text IN ('NaN', 'Infinity', '-Infinity')
  ) THEN
    RAISE EXCEPTION 'Budget actual spending contains a non-finite amount' USING ERRCODE = '22003';
  END IF;

  SELECT jsonb_build_object(
    'available', coalesce(s.available, 0)::numeric(18, 2)::text,
    'starting_total', coalesce(s.starting_total, 0)::numeric(18, 2)::text,
    'total_allocated', coalesce(s.total_allocated, 0)::numeric(18, 2)::text,
    'active_allocated', coalesce(s.active_allocated, 0)::numeric(18, 2)::text,
    'inactive_retained_funding', coalesce(s.inactive_retained_funding, 0)::numeric(18, 2)::text,
    'unallocated', coalesce(s.unallocated, 0)::numeric(18, 2)::text
  ) INTO v_funding
  FROM (SELECT 1) seed
  LEFT JOIN public.budget_month_funding_state s ON s.budget_month_id = v_month_id;

  WITH actuals AS (
    SELECT category_id, sum(total_amount)::numeric(18, 2) AS actual_spent
    FROM public.transactions
    WHERE movement_type = 'expense'
      AND transaction_date >= v_month_start
      AND transaction_date < (v_month_start + interval '1 month')::date
    GROUP BY category_id
  ), category_keys AS (
    SELECT category_id FROM public.budget_category_state WHERE budget_month_id = v_month_id
    UNION
    SELECT category_id FROM actuals
  )
  SELECT coalesce(jsonb_agg(jsonb_build_object(
    'budget_id', cs.budget_id,
    'category_id', keys.category_id,
    'categories', CASE WHEN keys.category_id IS NULL THEN NULL ELSE jsonb_build_object(
      'name', c.name,
      'icon', c.icon,
      'type', c.type
    ) END,
    'lifecycle_state', coalesce(cs.lifecycle_state, 'no_budget'),
    'is_active_budget', coalesce(cs.lifecycle_state = 'active', false),
    'is_active_zero', coalesce(cs.lifecycle_state = 'active' AND cs.final_funded = 0, false),
    'is_unbudgeted', coalesce(cs.lifecycle_state <> 'active', true),
    'starting_amount', CASE WHEN cs.starting_amount IS NULL THEN NULL ELSE cs.starting_amount::numeric(18, 2)::text END,
    'starting_kind', cs.starting_kind,
    'adjustment_total', coalesce(cs.adjustment_total, 0)::numeric(18, 2)::text,
    'final_funded', CASE WHEN cs.final_funded IS NULL THEN NULL ELSE cs.final_funded::numeric(18, 2)::text END,
    'amount', CASE WHEN cs.final_funded IS NULL THEN NULL ELSE cs.final_funded::numeric(18, 2)::text END,
    'actual_spent', coalesce(a.actual_spent, 0)::numeric(18, 2)::text,
    'remaining', CASE WHEN cs.lifecycle_state = 'active'
      THEN (cs.final_funded - coalesce(a.actual_spent, 0))::numeric(18, 2)::text ELSE NULL END,
    'deficit', CASE WHEN cs.lifecycle_state = 'active'
      THEN greatest(coalesce(a.actual_spent, 0) - cs.final_funded, 0)::numeric(18, 2)::text ELSE '0.00' END
  ) ORDER BY coalesce(c.name, ''), keys.category_id), '[]'::jsonb)
  INTO v_categories
  FROM category_keys keys
  LEFT JOIN public.budget_category_state cs
    ON cs.budget_month_id = v_month_id
   AND cs.category_id IS NOT DISTINCT FROM keys.category_id
  LEFT JOIN actuals a ON a.category_id IS NOT DISTINCT FROM keys.category_id
  LEFT JOIN public.categories c ON c.id = keys.category_id;

  SELECT coalesce(sum(total_amount), 0)::numeric(18, 2)
  INTO v_total_actual
  FROM public.transactions
  WHERE movement_type = 'expense'
    AND transaction_date >= v_month_start
    AND transaction_date < (v_month_start + interval '1 month')::date;

  SELECT coalesce(sum(t.total_amount), 0)::numeric(18, 2)
  INTO v_budgeted_actual
  FROM public.transactions t
  WHERE t.movement_type = 'expense'
    AND t.transaction_date >= v_month_start
    AND t.transaction_date < (v_month_start + interval '1 month')::date
    AND EXISTS (
      SELECT 1
      FROM public.budget_category_state cs
      WHERE cs.budget_month_id = v_month_id
        AND cs.lifecycle_state = 'active'
        AND cs.category_id = t.category_id
    );

  SELECT coalesce(jsonb_agg(jsonb_build_object(
    'id', bo.id,
    'operation_type', bo.operation_type,
    'effective_date', bo.effective_date,
    'created_at', bo.created_at,
    'reason', bo.reason,
    'reverses_operation_id', bo.reverses_operation_id,
    'funding_entries', coalesce((
      SELECT jsonb_agg(jsonb_build_object(
        'id', fe.id,
        'amount_delta', fe.amount_delta::numeric(18, 2)::text,
        'source_kind', fe.source_kind,
        'source_label', fe.source_label,
        'reverses_funding_entry_id', fe.reverses_funding_entry_id
      ) ORDER BY fe.id)
      FROM public.budget_funding_entries fe WHERE fe.operation_id = bo.id
    ), '[]'::jsonb),
    'movements', coalesce((
      SELECT jsonb_agg(jsonb_build_object(
        'id', m.id,
        'source_budget_id', m.source_budget_id,
        'destination_budget_id', m.destination_budget_id,
        'amount', m.amount::numeric(18, 2)::text
      ) ORDER BY m.id)
      FROM public.budget_movements m WHERE m.operation_id = bo.id
    ), '[]'::jsonb),
    'lifecycle_events', coalesce((
      SELECT jsonb_agg(jsonb_build_object(
        'id', le.id,
        'budget_id', le.budget_id,
        'state', le.state,
        'actual_spent_snapshot', CASE WHEN le.actual_spent_snapshot IS NULL
          THEN NULL ELSE le.actual_spent_snapshot::numeric(18, 2)::text END
      ) ORDER BY le.id)
      FROM public.budget_lifecycle_events le WHERE le.operation_id = bo.id
    ), '[]'::jsonb)
  ) ORDER BY bo.id), '[]'::jsonb)
  INTO v_history
  FROM public.budget_operations bo
  WHERE bo.budget_month_id = v_month_id;

  RETURN jsonb_build_object(
    'month', p_month,
    'currency', 'ILS',
    'funding', v_funding,
    'actuals', jsonb_build_object(
      'total', v_total_actual::numeric(18, 2)::text,
      'budgeted', v_budgeted_actual::numeric(18, 2)::text,
      'unbudgeted', (v_total_actual - v_budgeted_actual)::numeric(18, 2)::text
    ),
    'categories', v_categories,
    'history', v_history
  );
END;
$$;

