CREATE TABLE IF NOT EXISTS transactions (
  id                      SERIAL PRIMARY KEY,
  transaction_date        DATE NOT NULL,
  description             CHARACTER VARYING,
  movement_type           CHARACTER VARYING NOT NULL CHECK (movement_type IN ('expense', 'income')),
