-- Post-backfill reconciliation is part of the migration transaction.
DO $$
DECLARE
  v_month RECORD;
  v_lifecycle_count BIGINT;
  v_budget_count BIGINT;
BEGIN
  FOR v_month IN SELECT id, month_start FROM public.budget_months ORDER BY month_start LOOP
    PERFORM public.budget_assert_reconciled(v_month.id);
  END LOOP;

  SELECT count(*) INTO v_budget_count FROM public.budgets;
  SELECT count(*) INTO v_lifecycle_count
  FROM public.budget_lifecycle_events
  WHERE state = 'active';
  IF v_lifecycle_count <> v_budget_count THEN
    RAISE EXCEPTION
      'Migration 017 reconciliation: expected one initial active lifecycle event per budget, got % for % budgets',
      v_lifecycle_count, v_budget_count;
  END IF;
END;
$$;

