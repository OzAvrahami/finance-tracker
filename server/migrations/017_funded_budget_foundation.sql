-- Migration 017: funded monthly budget foundation and immutable provenance.
--
-- IMPORTANT: this migration is intentionally self-contained and transactional.
-- It must be rehearsed against a disposable PostgreSQL database and verified
-- against the target catalog before any production execution. Finance Tracker
-- does not currently maintain an authoritative applied-migration ledger.

BEGIN;

-- ---------------------------------------------------------------------------
-- Legacy preflight. Never guess, merge, delete, or silently normalize rows.
-- ---------------------------------------------------------------------------

DO $$
DECLARE
  v_missing_columns TEXT;
  v_bad_rows TEXT;
BEGIN
  IF to_regclass('public.budgets') IS NULL THEN
    RAISE EXCEPTION 'Migration 017 preflight: public.budgets does not exist';
  END IF;

  SELECT string_agg(required.column_name, ', ' ORDER BY required.column_name)
  INTO v_missing_columns
  FROM (VALUES
    ('id'), ('category_id'), ('month'), ('amount'), ('created_at'), ('updated_at')
  ) AS required(column_name)
  WHERE NOT EXISTS (
    SELECT 1
    FROM information_schema.columns c
    WHERE c.table_schema = 'public'
      AND c.table_name = 'budgets'
      AND c.column_name = required.column_name
  );

  IF v_missing_columns IS NOT NULL THEN
    RAISE EXCEPTION
      'Migration 017 preflight: public.budgets has an unexpected shape; missing columns: %',
      v_missing_columns;
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM information_schema.columns c
    WHERE c.table_schema = 'public'
      AND c.table_name = 'budgets'
      AND c.column_name = 'month'
      AND c.data_type = 'text'
  ) OR NOT EXISTS (
    SELECT 1
    FROM information_schema.columns c
    WHERE c.table_schema = 'public'
      AND c.table_name = 'budgets'
      AND c.column_name = 'amount'
      AND c.data_type = 'numeric'
  ) THEN
    RAISE EXCEPTION
      'Migration 017 preflight: expected budgets.month TEXT and budgets.amount NUMERIC';
  END IF;

  SELECT string_agg(format('id=%s month=%L', id, month), ', ' ORDER BY id)
  INTO v_bad_rows
  FROM public.budgets
  WHERE month !~ '^\d{4}-(0[1-9]|1[0-2])$';
  IF v_bad_rows IS NOT NULL THEN
    RAISE EXCEPTION 'Migration 017 preflight: invalid legacy budget month rows: %', v_bad_rows;
  END IF;

  SELECT string_agg(format('id=%s month=%L', id, month), ', ' ORDER BY id)
  INTO v_bad_rows
  FROM public.budgets
  WHERE to_char(to_date(month || '-01', 'YYYY-MM-DD'), 'YYYY-MM') <> month;
  IF v_bad_rows IS NOT NULL THEN
    RAISE EXCEPTION 'Migration 017 preflight: non-canonical calendar month rows: %', v_bad_rows;
  END IF;

  SELECT string_agg(format('id=%s month=%s', id, month), ', ' ORDER BY id)
  INTO v_bad_rows
  FROM public.budgets
  WHERE category_id IS NULL;
  IF v_bad_rows IS NOT NULL THEN
    RAISE EXCEPTION 'Migration 017 preflight: null legacy budget categories: %', v_bad_rows;
  END IF;

  SELECT string_agg(format('category_id=%s month=%s count=%s', category_id, month, row_count), ', ')
  INTO v_bad_rows
  FROM (
    SELECT category_id, month, count(*) AS row_count
    FROM public.budgets
    GROUP BY category_id, month
    HAVING count(*) > 1
  ) duplicates;
  IF v_bad_rows IS NOT NULL THEN
    RAISE EXCEPTION 'Migration 017 preflight: duplicate logical budget rows: %', v_bad_rows;
  END IF;

  SELECT string_agg(format('id=%s amount=%s', id, amount), ', ' ORDER BY id)
  INTO v_bad_rows
  FROM public.budgets
  WHERE amount < 0
     OR amount::text IN ('NaN', 'Infinity', '-Infinity')
     OR amount <> round(amount, 2)
     OR amount > 9999999999999999.99;
  IF v_bad_rows IS NOT NULL THEN
    RAISE EXCEPTION
      'Migration 017 preflight: invalid legacy budget amounts (must be finite, nonnegative NUMERIC(18,2)): %',
      v_bad_rows;
  END IF;

  SELECT string_agg(format('budget_id=%s category_id=%s', b.id, b.category_id), ', ' ORDER BY b.id)
  INTO v_bad_rows
  FROM public.budgets b
  LEFT JOIN public.categories c ON c.id = b.category_id
  WHERE c.id IS NULL;
  IF v_bad_rows IS NOT NULL THEN
    RAISE EXCEPTION 'Migration 017 preflight: legacy budgets reference missing categories: %', v_bad_rows;
  END IF;
END;
$$;

-- ---------------------------------------------------------------------------
-- Canonical month, immutable operations, funding, movements and lifecycle.
-- BIGINT identity operation IDs provide compact, monotonic database ordering;
-- request_key provides client-visible idempotency independently of ordering.
-- ---------------------------------------------------------------------------

CREATE TABLE public.budget_months (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  month_start DATE NOT NULL UNIQUE,
  currency_code TEXT NOT NULL DEFAULT 'ILS' CHECK (currency_code = 'ILS'),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT timezone('utc'::text, now()),
  CONSTRAINT budget_months_canonical_month CHECK (
    month_start = date_trunc('month', month_start)::date
  )
);

CREATE TABLE public.budget_operations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  budget_month_id BIGINT NOT NULL REFERENCES public.budget_months(id) ON DELETE RESTRICT,
  request_key UUID NOT NULL UNIQUE,
  request_fingerprint TEXT NOT NULL CHECK (btrim(request_fingerprint) <> ''),
  operation_type TEXT NOT NULL CHECK (operation_type IN (
    'legacy_import',
    'manual_funding',
    'establish_budget',
    'adjustment',
    'removal',
    'reactivation',
    'copy',
    'reversal'
  )),
  effective_date DATE NOT NULL,
  reason TEXT,
  reverses_operation_id BIGINT UNIQUE REFERENCES public.budget_operations(id) ON DELETE RESTRICT,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT timezone('utc'::text, now()),
  CONSTRAINT budget_operations_not_self_reversing CHECK (
    reverses_operation_id IS NULL OR reverses_operation_id <> id
  )
);

CREATE TABLE public.budget_funding_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operation_id BIGINT NOT NULL UNIQUE REFERENCES public.budget_operations(id) ON DELETE RESTRICT,
  amount_delta NUMERIC(18, 2) NOT NULL,
  source_kind TEXT NOT NULL CHECK (source_kind IN ('manual_available_funds', 'legacy_import')),
  source_label TEXT NOT NULL CHECK (btrim(source_label) <> ''),
  reverses_funding_entry_id BIGINT UNIQUE REFERENCES public.budget_funding_entries(id) ON DELETE RESTRICT,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT timezone('utc'::text, now()),
  CONSTRAINT budget_funding_entry_amount_shape CHECK (
    amount_delta::text NOT IN ('NaN', 'Infinity', '-Infinity')
    AND (
    (source_kind = 'legacy_import' AND amount_delta >= 0 AND reverses_funding_entry_id IS NULL)
    OR
    (source_kind = 'manual_available_funds' AND amount_delta <> 0)
    )
  )
);

ALTER TABLE public.budgets
  ADD COLUMN budget_month_id BIGINT REFERENCES public.budget_months(id) ON DELETE RESTRICT,
  ADD COLUMN starting_amount NUMERIC(18, 2),
  ADD COLUMN starting_kind TEXT,
  ADD COLUMN created_by_operation_id BIGINT REFERENCES public.budget_operations(id) ON DELETE RESTRICT;

CREATE TABLE public.budget_movements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operation_id BIGINT NOT NULL REFERENCES public.budget_operations(id) ON DELETE RESTRICT,
  source_budget_id BIGINT REFERENCES public.budgets(id) ON DELETE RESTRICT,
  destination_budget_id BIGINT REFERENCES public.budgets(id) ON DELETE RESTRICT,
  amount NUMERIC(18, 2) NOT NULL CHECK (
    amount::text NOT IN ('NaN', 'Infinity', '-Infinity') AND amount > 0
  ),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT timezone('utc'::text, now()),
  CONSTRAINT budget_movements_endpoints CHECK (
    (source_budget_id IS NOT NULL OR destination_budget_id IS NOT NULL)
    AND source_budget_id IS DISTINCT FROM destination_budget_id
  )
);

CREATE TABLE public.budget_lifecycle_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operation_id BIGINT NOT NULL REFERENCES public.budget_operations(id) ON DELETE RESTRICT,
  budget_id BIGINT NOT NULL REFERENCES public.budgets(id) ON DELETE RESTRICT,
  state TEXT NOT NULL CHECK (state IN ('active', 'inactive')),
  actual_spent_snapshot NUMERIC(18, 2),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT timezone('utc'::text, now()),
  CONSTRAINT budget_lifecycle_actual_snapshot CHECK (
    (state = 'active' AND actual_spent_snapshot IS NULL)
    OR
    (state = 'inactive'
      AND actual_spent_snapshot IS NOT NULL
      AND actual_spent_snapshot::text NOT IN ('NaN', 'Infinity', '-Infinity')
      AND actual_spent_snapshot >= 0)
  ),
  CONSTRAINT budget_lifecycle_operation_budget_key UNIQUE (operation_id, budget_id)
);

CREATE INDEX idx_budget_operations_month_order
  ON public.budget_operations (budget_month_id, id);
CREATE INDEX idx_budget_movements_source
  ON public.budget_movements (source_budget_id, id);
CREATE INDEX idx_budget_movements_destination
  ON public.budget_movements (destination_budget_id, id);
CREATE INDEX idx_budget_lifecycle_budget_order
  ON public.budget_lifecycle_events (budget_id, id DESC);

