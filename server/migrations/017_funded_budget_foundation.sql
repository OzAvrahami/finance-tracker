  request_key,
  request_fingerprint,
  operation_type,
  effective_date,
  reason,
  created_at
)
SELECT
  bm.id,
  (
    substr(md5('finance-tracker:legacy-budget:' || to_char(bm.month_start, 'YYYY-MM')), 1, 8) || '-' ||
    substr(md5('finance-tracker:legacy-budget:' || to_char(bm.month_start, 'YYYY-MM')), 9, 4) || '-' ||
    substr(md5('finance-tracker:legacy-budget:' || to_char(bm.month_start, 'YYYY-MM')), 13, 4) || '-' ||
    substr(md5('finance-tracker:legacy-budget:' || to_char(bm.month_start, 'YYYY-MM')), 17, 4) || '-' ||
    substr(md5('finance-tracker:legacy-budget:' || to_char(bm.month_start, 'YYYY-MM')), 21, 12)
  )::uuid,
  'legacy_import|' || to_char(bm.month_start, 'YYYY-MM'),
  'legacy_import',
  bm.month_start,
  'Migration 017 legacy budget opening-state import',
  bm.created_at
FROM public.budget_months bm
ORDER BY bm.month_start;

INSERT INTO public.budget_funding_entries (
  operation_id,
  amount_delta,
  source_kind,
  source_label,
  created_at
)
SELECT
  bo.id,
  coalesce(sum(b.amount), 0)::numeric(18, 2),
  'legacy_import',
  'Legacy budget import assumption; historical real-world funding source is unknown',
  bo.created_at
FROM public.budget_operations bo
JOIN public.budget_months bm ON bm.id = bo.budget_month_id
LEFT JOIN public.budgets b ON b.month = to_char(bm.month_start, 'YYYY-MM')
WHERE bo.operation_type = 'legacy_import'
GROUP BY bo.id, bo.created_at;

UPDATE public.budgets b
SET budget_month_id = bm.id,
    starting_amount = b.amount::numeric(18, 2),
    starting_kind = 'legacy_import',
    created_by_operation_id = bo.id
FROM public.budget_months bm
JOIN public.budget_operations bo
  ON bo.budget_month_id = bm.id
 AND bo.operation_type = 'legacy_import'
WHERE b.month = to_char(bm.month_start, 'YYYY-MM');

INSERT INTO public.budget_lifecycle_events (
  operation_id,
  budget_id,
  state,
  actual_spent_snapshot,
  created_at
)
SELECT
  b.created_by_operation_id,
  b.id,
  'active',
  NULL,
  b.created_at
FROM public.budgets b
ORDER BY b.id;

-- Preserve every legacy ID while ensuring the next generated snapshot ID cannot
-- collide with an explicitly imported historical ID. ALTER SEQUENCE ... RESTART
-- is transactional, unlike setval(), so a failed migration restores sequence state.
DO $$
DECLARE
  v_sequence REGCLASS;
  v_next_id BIGINT;
BEGIN
  v_sequence := pg_get_serial_sequence('public.budgets', 'id')::regclass;
  IF v_sequence IS NULL THEN
    RAISE EXCEPTION 'Migration 017 preflight: budgets.id has no owned sequence';
  END IF;
  SELECT greatest(coalesce(max(id), 0) + 1, 1) INTO v_next_id FROM public.budgets;
  EXECUTE format('ALTER SEQUENCE %s RESTART WITH %s', v_sequence, v_next_id);
END;
$$;

