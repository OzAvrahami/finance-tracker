CREATE TABLE public.budget_unbudgeted_resolution_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operation_id BIGINT NOT NULL UNIQUE REFERENCES public.budget_operations(id) ON DELETE RESTRICT,
  funding_action_id BIGINT UNIQUE REFERENCES public.budget_funding_actions(id) ON DELETE RESTRICT,
  budget_month_id BIGINT NOT NULL REFERENCES public.budget_months(id) ON DELETE RESTRICT,
  category_id BIGINT NOT NULL REFERENCES public.categories(id) ON DELETE RESTRICT,
  budget_id BIGINT NOT NULL REFERENCES public.budgets(id) ON DELETE RESTRICT,
  event_kind TEXT NOT NULL CHECK (event_kind IN ('apply','reversal')),
  resolution_mode TEXT NOT NULL CHECK (resolution_mode IN ('created','reactivated')),
  raw_actual_snapshot NUMERIC(18,2) NOT NULL,
  existing_funded_snapshot NUMERIC(18,2) NOT NULL,
  applied_funding NUMERIC(18,2) NOT NULL,
  resulting_final_funded NUMERIC(18,2) NOT NULL,
  resulting_deficit NUMERIC(18,2) NOT NULL,
  reverses_event_id BIGINT UNIQUE REFERENCES public.budget_unbudgeted_resolution_events(id) ON DELETE RESTRICT,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT timezone('utc'::text,now()),
  CHECK (raw_actual_snapshot::text NOT IN ('NaN','Infinity','-Infinity') AND raw_actual_snapshot>0),
  CHECK (existing_funded_snapshot::text NOT IN ('NaN','Infinity','-Infinity') AND existing_funded_snapshot>=0),
  CHECK (applied_funding::text NOT IN ('NaN','Infinity','-Infinity') AND applied_funding>=0),
  CHECK (resulting_final_funded::text NOT IN ('NaN','Infinity','-Infinity') AND resulting_final_funded>=0),
  CHECK (resulting_deficit::text NOT IN ('NaN','Infinity','-Infinity') AND resulting_deficit>=0),
  CHECK ((event_kind='apply' AND resulting_final_funded=existing_funded_snapshot+applied_funding)
      OR (event_kind='reversal' AND resulting_final_funded=existing_funded_snapshot-applied_funding)),
  CHECK (resulting_deficit=greatest(raw_actual_snapshot-resulting_final_funded,0)),
  CHECK ((applied_funding=0 AND funding_action_id IS NULL)
      OR (applied_funding>0 AND funding_action_id IS NOT NULL)),
  CHECK ((event_kind='apply' AND reverses_event_id IS NULL)
      OR (event_kind='reversal' AND reverses_event_id IS NOT NULL))
);

