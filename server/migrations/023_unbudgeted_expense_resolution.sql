-- Migration 023: explicit resolution of transaction-authoritative unbudgeted expenses.
--
-- A late-created snapshot opens at zero. Funding is recorded only through the
-- existing funded-action ledger. Inactive snapshots are explicitly reactivated
-- without rewriting their immutable opening state.

BEGIN;

DO $$
BEGIN
  IF to_regclass('public.budget_funding_actions') IS NULL
     OR to_regclass('public.budget_funding_action_legs') IS NULL
     OR to_regclass('public.budget_savings_entries') IS NULL
     OR to_regclass('public.budget_month_overrides') IS NULL
     OR to_regprocedure('public.budget_action_month_lifecycle(text)') IS NULL
     OR to_regprocedure('public.get_budget_deficit_resolution_preview(text,bigint,jsonb)') IS NULL
     OR to_regprocedure('public.budget_assert_reconciled(bigint)') IS NULL THEN
    RAISE EXCEPTION 'Migration 023 preflight: Migrations 017 through 022 are required';
  END IF;
  IF to_regclass('public.budget_unbudgeted_resolution_events') IS NOT NULL
     OR to_regclass('public.budget_unbudgeted_resolution_history') IS NOT NULL
     OR to_regprocedure('public.budget_funding_source_rows(text,bigint)') IS NOT NULL
     OR to_regprocedure('public.get_budget_unbudgeted_resolution_preview(text,bigint,numeric,jsonb)') IS NOT NULL
     OR to_regprocedure('public.apply_budget_unbudgeted_resolution(text,bigint,numeric,jsonb,uuid,text,text)') IS NOT NULL
     OR to_regprocedure('public.reverse_budget_unbudgeted_resolution(bigint,uuid,text)') IS NOT NULL THEN
    RAISE EXCEPTION 'Migration 023 preflight: unexpected partial unbudgeted-resolution schema exists';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.budgets
    WHERE starting_kind NOT IN (
      'manual','legacy_import','copied','recurring_default','carryover_only','monthly_override'
    )
  ) OR EXISTS (
    SELECT 1 FROM public.budget_operations
    WHERE operation_type NOT IN (
      'legacy_import','manual_funding','establish_budget','adjustment','removal',
      'reactivation','copy','reversal','month_initialization','carryover_out',
      'carryover_in','monthly_override_set','monthly_override_remove',
      'unused_return_out','unused_return_in','unused_to_savings',
      'unused_disposition_reversal','budget_reallocation','deficit_resolution',
      'funding_action_reversal'
    )
  ) OR EXISTS (
    SELECT 1 FROM public.budget_funding_actions
    WHERE action_kind NOT IN ('planned_reallocation','deficit_resolution','reversal')
  ) THEN
    RAISE EXCEPTION 'Migration 023 preflight: unexpected funded-budget domain value';
  END IF;
END;
$$;

