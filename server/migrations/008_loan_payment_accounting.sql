-- Migration 008: separate loan accounting from the cash transaction ledger.
--
-- Existing loans stay in `legacy` mode and retain the historical transaction
-- total/count summary behavior. A loan is moved to `loan_payments` only by an
-- explicit migration/repair or by the server-owned new-loan creation path.

BEGIN;

ALTER TABLE public.loans
  ADD COLUMN IF NOT EXISTS calculation_mode TEXT NOT NULL DEFAULT 'legacy',
  ADD COLUMN IF NOT EXISTS next_payment_date DATE,
  ADD COLUMN IF NOT EXISTS payment_source_id BIGINT REFERENCES public.payment_sources(id);

ALTER TABLE public.loans
  DROP CONSTRAINT IF EXISTS loans_calculation_mode_check;

ALTER TABLE public.loans
  ADD CONSTRAINT loans_calculation_mode_check
  CHECK (calculation_mode IN ('legacy', 'loan_payments'));

CREATE TABLE IF NOT EXISTS public.loan_payments (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loan_id               BIGINT NOT NULL REFERENCES public.loans(id) ON DELETE CASCADE,
  transaction_id        BIGINT REFERENCES public.transactions(id) ON DELETE SET NULL,
  installment_number    INTEGER NOT NULL CHECK (installment_number > 0),
  payment_date          DATE NOT NULL,
  payment_amount        NUMERIC(18, 2) NOT NULL CHECK (payment_amount >= 0),
  principal_amount      NUMERIC(24, 10) NOT NULL CHECK (principal_amount >= 0),
  interest_amount       NUMERIC(24, 10) NOT NULL CHECK (interest_amount >= 0),
  annual_interest_rate  NUMERIC(12, 6) CHECK (
    annual_interest_rate IS NULL OR annual_interest_rate >= 0
  ),
  source_kind           TEXT NOT NULL CHECK (
    source_kind IN ('existing_transaction', 'reconstructed', 'manual')
  ),
  notes                 TEXT,
  created_at            TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at            TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT timezone('utc'::text, now()),
  CONSTRAINT loan_payments_loan_installment_key UNIQUE (loan_id, installment_number),
  CONSTRAINT loan_payments_transaction_key UNIQUE (transaction_id),
  CONSTRAINT loan_payments_components_reconcile CHECK (
    abs(payment_amount - principal_amount - interest_amount) <= 0.00000001
  )
);

CREATE INDEX IF NOT EXISTS idx_loan_payments_loan_date
  ON public.loan_payments (loan_id, payment_date, installment_number);

ALTER TABLE public.loan_payments ENABLE ROW LEVEL SECURITY;

-- One authoritative summary path. SECURITY DEFINER is used because both
-- table triggers and the service-role RPC below call this function. Pinning
-- search_path and schema-qualifying every relation prevents object shadowing.
CREATE OR REPLACE FUNCTION public.refresh_loan_summary(p_loan_id BIGINT)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_loan public.loans%ROWTYPE;
  v_payment_count BIGINT := 0;
  v_paid_principal NUMERIC := 0;
  v_cash_total NUMERIC := 0;
  v_balance NUMERIC := 0;
  v_remaining INTEGER := 0;
BEGIN
  IF p_loan_id IS NULL THEN
    RETURN;
  END IF;

  SELECT *
  INTO v_loan
  FROM public.loans
  WHERE id = p_loan_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RETURN;
  END IF;

  IF v_loan.calculation_mode = 'loan_payments' THEN
    SELECT
      count(*),
      coalesce(sum(principal_amount), 0)
    INTO v_payment_count, v_paid_principal
    FROM public.loan_payments
    WHERE loan_id = p_loan_id;

    -- Components remain high precision in loan_payments. The displayed/stored
    -- loan summary is monetary and therefore rounded once to agorot here.
    v_balance := round(greatest(v_loan.original_amount - v_paid_principal, 0), 2);
    v_remaining := greatest(
      coalesce(v_loan.total_installments, 0) - v_payment_count,
      0
    )::integer;

    UPDATE public.loans
    SET
      current_balance = v_balance,
      remaining_installments = v_remaining,
      status = CASE
        -- Debt status is principal-based. Exhausting the expected installment
        -- count does not forgive a residual balance.
        WHEN v_balance <= 0.005 THEN 'paid'
        -- Refreshing an in-arrears loan must not silently cure a deliberate
        -- defaulted status merely because its principal is still positive.
        WHEN v_loan.status = 'defaulted' THEN 'defaulted'
        ELSE 'active'
      END
    WHERE id = p_loan_id;
  ELSE
    -- Compatibility mode: intentionally preserve the old live behavior for
    -- loans that have not yet been audited/migrated.
    SELECT count(*), coalesce(sum(total_amount), 0)
    INTO v_payment_count, v_cash_total
    FROM public.transactions
    WHERE loan_id = p_loan_id;

    UPDATE public.loans
    SET
      current_balance = v_loan.original_amount - v_cash_total,
      remaining_installments = coalesce(v_loan.total_installments, 0) - v_payment_count
    WHERE id = p_loan_id;
  END IF;
END;
$$;

-- Preserve the existing trigger/function identity so the live
-- on_transaction_change trigger and repository schema converge. In
-- loan_payments mode this refresh reads principal components only; transaction
-- cash amounts can no longer reduce principal directly.
CREATE OR REPLACE FUNCTION public.recalculate_loan_status()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    PERFORM public.refresh_loan_summary(NEW.loan_id);
    RETURN NEW;
  ELSIF TG_OP = 'DELETE' THEN
    PERFORM public.refresh_loan_summary(OLD.loan_id);
    RETURN OLD;
  END IF;

  IF OLD.loan_id IS DISTINCT FROM NEW.loan_id THEN
    PERFORM public.refresh_loan_summary(OLD.loan_id);
  END IF;
  PERFORM public.refresh_loan_summary(NEW.loan_id);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_transaction_change ON public.transactions;
CREATE TRIGGER on_transaction_change
AFTER INSERT OR UPDATE OR DELETE ON public.transactions
FOR EACH ROW
EXECUTE FUNCTION public.recalculate_loan_status();

