-- Preserve each existing UPDATE grantee's access to old columns, while
-- preventing table-wide grants from exposing protected void metadata.
REVOKE CREATE ON SCHEMA public FROM PUBLIC,anon,authenticated,service_role;
DO $trusted_schema$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname IN ('anon','authenticated','service_role') AND has_schema_privilege(oid,'public','CREATE')) THEN
    RAISE EXCEPTION 'Untrusted API role inherits public CREATE; resolve role membership before Savings installation';
  END IF;
END $trusted_schema$;
DO $permissions$
DECLARE r RECORD; v_role TEXT; v_columns TEXT;
BEGIN
  SELECT string_agg(quote_ident(attname),',') INTO v_columns FROM pg_attribute WHERE attrelid='public.transactions'::regclass AND attnum>0 AND NOT attisdropped AND attname NOT IN ('voided_at','void_request_key','void_fingerprint','void_reason');
  FOR r IN SELECT acl.grantee,acl.is_grantable FROM pg_class c CROSS JOIN LATERAL aclexplode(coalesce(c.relacl,acldefault('r',c.relowner))) acl WHERE c.oid='public.transactions'::regclass AND acl.privilege_type='UPDATE' AND acl.grantee<>c.relowner LOOP
