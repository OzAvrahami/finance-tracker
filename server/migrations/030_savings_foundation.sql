CREATE OR REPLACE FUNCTION public.get_funded_budget_month(p_month text)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
DECLARE
  v_month_start DATE:=public.budget_month_start_from_key(p_month);
  v_month_id BIGINT;
  v_funding JSONB; v_categories JSONB; v_history JSONB;
  v_carryover_history JSONB; v_disposition_history JSONB;
  v_action_history JSONB; v_resolution_history JSONB;
  v_total_actual NUMERIC(18,2); v_budgeted_actual NUMERIC(18,2);
BEGIN
  SELECT id INTO v_month_id FROM public.budget_months WHERE month_start=v_month_start;
  IF EXISTS(
    SELECT 1 FROM public.budget_actual_transactions(NULL,NULL)
    WHERE movement_type='expense' AND transaction_date>=v_month_start
      AND transaction_date<(v_month_start+interval '1 month')::date
      AND total_amount::text IN ('NaN','Infinity','-Infinity')
  ) THEN
    RAISE EXCEPTION 'Budget actual spending contains a non-finite amount' USING ERRCODE='22003';
  END IF;

  SELECT jsonb_build_object(
    'available',coalesce(s.available,0)::numeric(18,2)::text,
    'starting_total',coalesce(s.starting_total,0)::numeric(18,2)::text,
    'total_allocated',coalesce(s.total_allocated,0)::numeric(18,2)::text,
    'active_allocated',coalesce(s.active_allocated,0)::numeric(18,2)::text,
    'inactive_retained_funding',coalesce(s.inactive_retained_funding,0)::numeric(18,2)::text,
    'unallocated',coalesce(s.unallocated,0)::numeric(18,2)::text
  ) INTO v_funding
  FROM (SELECT 1) seed
  LEFT JOIN public.budget_month_funding_state s ON s.budget_month_id=v_month_id;

  WITH actuals AS (
    SELECT category_id,sum(total_amount)::numeric(18,2) AS actual_spent
    FROM public.budget_actual_transactions(NULL,NULL)
    WHERE movement_type='expense' AND transaction_date>=v_month_start
      AND transaction_date<(v_month_start+interval '1 month')::date
    GROUP BY category_id
  ), keys AS (
    SELECT category_id FROM public.budget_category_composition WHERE budget_month_id=v_month_id
    UNION SELECT category_id FROM actuals
  )
  SELECT coalesce(jsonb_agg(jsonb_build_object(
    'budget_id',c.budget_id,'category_id',keys.category_id,
    'categories',CASE WHEN keys.category_id IS NULL THEN NULL ELSE jsonb_build_object(
      'name',cat.name,'icon',cat.icon,'type',cat.type) END,
    'lifecycle_state',coalesce(c.lifecycle_state,'no_budget'),
    'is_active_budget',coalesce(c.lifecycle_state='active',false),
    'is_active_zero',coalesce(c.lifecycle_state='active' AND c.final_funded=0,false),
    'is_unbudgeted',coalesce(c.lifecycle_state<>'active',true),
    'starting_amount',CASE WHEN c.opening_base IS NULL THEN NULL ELSE c.opening_base::text END,
    'starting_kind',c.starting_kind,
    'adjustment_total',CASE WHEN c.budget_id IS NULL THEN '0.00' ELSE
      (c.final_funded-c.opening_base)::numeric(18,2)::text END,
    'fallback_base',CASE WHEN c.budget_id IS NULL THEN NULL ELSE c.fallback_base::text END,
    'fallback_source',c.fallback_source,
    'recurring_default',CASE WHEN rd.amount IS NULL THEN NULL ELSE rd.amount::numeric(18,2)::text END,
    'month_override',CASE WHEN c.current_override IS NULL THEN NULL ELSE c.current_override::text END,
    'override_adjustment_total',coalesce(c.override_adjustment_total,0)::numeric(18,2)::text,
    'effective_base',CASE WHEN c.budget_id IS NULL THEN NULL ELSE c.effective_base::text END,
    'incoming_carryover',coalesce(c.incoming_carryover,0)::numeric(18,2)::text,
    'outgoing_carryover',coalesce(c.outgoing_carryover,0)::numeric(18,2)::text,
    'incoming_reallocation_resolution',coalesce(c.incoming_reallocation_resolution,0)::numeric(18,2)::text,
    'outgoing_reallocation',coalesce(c.outgoing_reallocation,0)::numeric(18,2)::text,
    'incoming_unbudgeted_resolution',coalesce(c.incoming_unbudgeted_resolution,0)::numeric(18,2)::text,
    'outgoing_unbudgeted_resolution',coalesce(c.outgoing_unbudgeted_resolution,0)::numeric(18,2)::text,
    'funding_action_adjustment_total',(
      coalesce(c.incoming_reallocation_resolution,0)-coalesce(c.outgoing_reallocation,0)
    )::numeric(18,2)::text,
    'unused_disposition_adjustment',coalesce(c.unused_disposition_adjustment,0)::numeric(18,2)::text,
    'other_adjustments',coalesce(c.other_adjustments,0)::numeric(18,2)::text,
    'unused_balance_policy',p.policy,
    'final_funded',CASE WHEN c.final_funded IS NULL THEN NULL ELSE c.final_funded::text END,
    'amount',CASE WHEN c.final_funded IS NULL THEN NULL ELSE c.final_funded::text END,
    'actual_spent',coalesce(a.actual_spent,0)::numeric(18,2)::text,
    'remaining',CASE WHEN c.lifecycle_state='active'
      THEN (c.final_funded-coalesce(a.actual_spent,0))::numeric(18,2)::text ELSE NULL END,
    'deficit',CASE WHEN c.lifecycle_state='active'
      THEN greatest(coalesce(a.actual_spent,0)-c.final_funded,0)::numeric(18,2)::text ELSE '0.00' END
  ) ORDER BY coalesce(cat.name,''),keys.category_id),'[]'::jsonb) INTO v_categories
  FROM keys
  LEFT JOIN public.budget_category_composition c
    ON c.budget_month_id=v_month_id AND c.category_id IS NOT DISTINCT FROM keys.category_id
  LEFT JOIN actuals a ON a.category_id IS NOT DISTINCT FROM keys.category_id
  LEFT JOIN public.categories cat ON cat.id=keys.category_id
  LEFT JOIN public.budget_recurring_defaults rd ON rd.category_id=keys.category_id
  LEFT JOIN public.budget_unused_balance_policies p ON p.category_id=keys.category_id;

  SELECT coalesce(sum(total_amount),0)::numeric(18,2) INTO v_total_actual
  FROM public.budget_actual_transactions(NULL,NULL) WHERE movement_type='expense'
    AND transaction_date>=v_month_start AND transaction_date<(v_month_start+interval '1 month')::date;
  SELECT coalesce(sum(t.total_amount),0)::numeric(18,2) INTO v_budgeted_actual
  FROM public.budget_actual_transactions(NULL,NULL) t
  WHERE t.movement_type='expense' AND t.transaction_date>=v_month_start
    AND t.transaction_date<(v_month_start+interval '1 month')::date
    AND EXISTS(SELECT 1 FROM public.budget_category_composition c
      WHERE c.budget_month_id=v_month_id AND c.lifecycle_state='active' AND c.category_id=t.category_id);

  SELECT coalesce(jsonb_agg(jsonb_build_object(
    'id',o.id,'parent_operation_id',o.parent_operation_id,
    'root_operation_id',coalesce(o.parent_operation_id,o.id),
    'operation_type',o.operation_type,'effective_date',o.effective_date,
    'created_at',o.created_at,'reason',o.reason,'reverses_operation_id',o.reverses_operation_id,
    'funding_entries',coalesce((SELECT jsonb_agg(jsonb_build_object(
      'id',fe.id,'amount_delta',fe.amount_delta::numeric(18,2)::text,
      'source_kind',fe.source_kind,'source_label',fe.source_label,
      'reverses_funding_entry_id',fe.reverses_funding_entry_id) ORDER BY fe.id)
      FROM public.budget_funding_entries fe WHERE fe.operation_id=o.id),'[]'::jsonb),
    'movements',coalesce((SELECT jsonb_agg(jsonb_build_object(
      'id',m.id,'source_budget_id',m.source_budget_id,
      'destination_budget_id',m.destination_budget_id,'amount',m.amount::numeric(18,2)::text
      ) ORDER BY m.id) FROM public.budget_movements m WHERE m.operation_id=o.id),'[]'::jsonb),
    'lifecycle_events',coalesce((SELECT jsonb_agg(jsonb_build_object(
      'id',le.id,'budget_id',le.budget_id,'state',le.state,
      'actual_spent_snapshot',CASE WHEN le.actual_spent_snapshot IS NULL THEN NULL
        ELSE le.actual_spent_snapshot::numeric(18,2)::text END) ORDER BY le.id)
      FROM public.budget_lifecycle_events le WHERE le.operation_id=o.id),'[]'::jsonb)
  ) ORDER BY o.id),'[]'::jsonb) INTO v_history
  FROM public.budget_operations o WHERE o.budget_month_id=v_month_id;

  SELECT coalesce(jsonb_agg(jsonb_build_object(
    'transfer_id',i.id,'batch_id',i.operation_id,
    'source_month',to_char(sm.month_start,'YYYY-MM'),
    'destination_month',to_char(dm.month_start,'YYYY-MM'),
    'category_id',i.category_id,'amount',i.amount::text,
    'source_final_funded_snapshot',i.funded_before::text,
    'source_raw_actual_spent_snapshot',i.raw_actual_snapshot::text,
    'source_effective_actual_spent_snapshot',greatest(i.raw_actual_snapshot,0)::numeric(18,2)::text,
    'reverses_transfer_id',i.reversed_item_id,'created_at',i.created_at
  ) ORDER BY i.id),'[]'::jsonb) INTO v_carryover_history
  FROM public.budget_operation_items i
  JOIN public.budget_months sm ON sm.id=i.budget_month_id
  JOIN public.budget_months dm ON dm.id=i.destination_budget_month_id
  WHERE i.item_kind='carryover' AND i.category_id IS NOT NULL
    AND (i.budget_month_id=v_month_id OR i.destination_budget_month_id=v_month_id);

  SELECT coalesce(jsonb_agg(jsonb_build_object(
    'event_id',i.id,'batch_id',i.operation_id,'event_kind',i.action_kind,'policy',i.policy,
    'category_id',i.category_id,'category_name',cat.name,'source_budget_id',i.source_budget_id,
    'source_month',to_char(sm.month_start,'YYYY-MM'),
    'destination_month',to_char(dm.month_start,'YYYY-MM'),'amount',i.amount::text,
    'source_final_funded_snapshot',i.funded_before::text,
    'source_raw_actual_snapshot',i.raw_actual_snapshot::text,
    'source_effective_actual_snapshot',greatest(i.raw_actual_snapshot,0)::numeric(18,2)::text,
    'source_operation_id',i.source_operation_id,'destination_operation_id',i.destination_operation_id,
    'carryover_transfer_id',CASE WHEN i.policy='carry_forward' THEN i.linked_item_id END,
    'savings_entry_id',i.savings_entry_id,'reverses_event_id',i.reversed_item_id,
    'created_at',i.created_at
  ) ORDER BY i.id),'[]'::jsonb) INTO v_disposition_history
  FROM public.budget_operation_items i
  JOIN public.budget_months sm ON sm.id=i.budget_month_id
  JOIN public.budget_months dm ON dm.id=i.destination_budget_month_id
  JOIN public.categories cat ON cat.id=i.category_id
  WHERE i.item_kind='unused_disposition'
    AND (i.budget_month_id=v_month_id OR i.destination_budget_month_id=v_month_id);

  SELECT coalesce(jsonb_agg(jsonb_build_object(
    'action_id',a.id,'action_kind',CASE WHEN a.reversed_item_id IS NOT NULL THEN 'reversal'
      WHEN a.item_kind='reallocation' THEN 'planned_reallocation'
      WHEN a.item_kind='deficit_resolution' THEN 'deficit_resolution' ELSE a.action_kind END,
    'month',p_month,'destination_budget_id',a.destination_budget_id,
    'requested_amount',a.amount::text,'applied_amount',a.amount::text,
    'destination_final_funded_snapshot',CASE WHEN a.funded_before IS NULL THEN NULL ELSE a.funded_before::text END,
    'destination_raw_actual_snapshot',CASE WHEN a.raw_actual_snapshot IS NULL THEN NULL ELSE a.raw_actual_snapshot::text END,
    'deficit_before',CASE WHEN a.deficit_before IS NULL THEN NULL ELSE a.deficit_before::text END,
    'deficit_after',CASE WHEN a.deficit_after IS NULL THEN NULL ELSE a.deficit_after::text END,
    'reversed_action_id',a.reversed_item_id,'created_at',a.created_at,
    'legs',coalesce((SELECT jsonb_agg(jsonb_build_object(
      'id',l.id,'source_kind',l.source_kind,'source_budget_id',l.source_budget_id,
      'amount',l.amount::text,'source_capacity_snapshot',l.source_capacity_snapshot::text,
      'source_final_funded_snapshot',CASE WHEN l.funded_before IS NULL THEN NULL ELSE l.funded_before::text END,
      'source_raw_actual_snapshot',CASE WHEN l.raw_actual_snapshot IS NULL THEN NULL ELSE l.raw_actual_snapshot::text END,
      'source_effective_actual_snapshot',CASE WHEN l.raw_actual_snapshot IS NULL THEN NULL
        ELSE greatest(l.raw_actual_snapshot,0)::numeric(18,2)::text END,
      'movement_id',l.movement_id,'savings_entry_id',l.savings_entry_id) ORDER BY l.id)
      FROM public.budget_operation_items l WHERE l.item_kind='allocation_leg' AND l.linked_item_id=a.id),'[]'::jsonb)
  ) ORDER BY a.id),'[]'::jsonb) INTO v_action_history
  FROM public.budget_operation_items a
  WHERE a.budget_month_id=v_month_id AND a.item_kind IN ('reallocation','funding_action','deficit_resolution');

  SELECT coalesce(jsonb_agg(jsonb_build_object(
    'event_id',i.id,'event_kind',i.action_kind,'resolution_mode',i.resolution_mode,
    'month',p_month,'category_id',i.category_id,'budget_id',i.destination_budget_id,
    'raw_actual_snapshot',i.raw_actual_snapshot::text,
    'existing_funded_snapshot',i.funded_before::text,'applied_funding',i.amount::text,
    'resulting_final_funded',i.funded_after::text,'resulting_deficit',i.deficit_after::text,
    'funding_action_id',i.linked_item_id,'reverses_event_id',i.reversed_item_id,
    'created_at',i.created_at
  ) ORDER BY i.id),'[]'::jsonb) INTO v_resolution_history
  FROM public.budget_operation_items i
  WHERE i.item_kind='unbudgeted_resolution' AND i.budget_month_id=v_month_id;

  RETURN jsonb_build_object(
    'month',p_month,'currency','ILS','funding',v_funding,
    'actuals',jsonb_build_object('total',v_total_actual::text,'budgeted',v_budgeted_actual::text,
      'unbudgeted',(v_total_actual-v_budgeted_actual)::numeric(18,2)::text),
    'categories',v_categories,'history',v_history,
    'recurring',public.get_budget_recurring_preview(p_month),
    'carryover',public.get_budget_carryover_preview(p_month),
    'carryover_history',v_carryover_history,
    'month_overrides',public.get_budget_month_override_preview(p_month),
    'unused_disposition_history',v_disposition_history,
    'savings',jsonb_build_object('balance',(SELECT balance_text FROM public.budget_savings_state)),
    'funding_action_history',v_action_history,
    'unbudgeted_resolution_history',v_resolution_history,
    'action_lifecycle',public.budget_action_month_lifecycle(p_month)
  );
END; $function$;

CREATE OR REPLACE FUNCTION public.set_funded_budget_amount(p_budget_id bigint, p_target_amount numeric, p_request_key uuid, p_reason text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
DECLARE
  v_budget public.budgets%ROWTYPE;
  v_month public.budget_months%ROWTYPE;
  v_state public.budget_category_state%ROWTYPE;
  v_latest_state TEXT;
  v_actual NUMERIC(18, 2);
  v_unallocated NUMERIC(18, 2);
  v_delta NUMERIC(18, 2);
  v_operation_id BIGINT;
  v_existing public.budget_operations%ROWTYPE;
  v_fingerprint TEXT;
BEGIN
  IF p_target_amount IS NULL OR p_target_amount::text IN ('NaN', 'Infinity', '-Infinity')
     OR p_target_amount < 0 OR p_target_amount <> round(p_target_amount, 2)
     OR p_target_amount > 9999999999999999.99 THEN
    RAISE EXCEPTION 'target_amount must be a nonnegative two-decimal value' USING ERRCODE = '22023';
  END IF;
  IF p_request_key IS NULL THEN RAISE EXCEPTION 'request_key is required' USING ERRCODE = '22023'; END IF;

  SELECT * INTO v_budget FROM public.budgets WHERE id = p_budget_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Budget % does not exist', p_budget_id USING ERRCODE = 'P0002'; END IF;
  SELECT * INTO v_month FROM public.budget_months WHERE id = v_budget.budget_month_id FOR UPDATE;
  SELECT * INTO v_budget FROM public.budgets WHERE id = p_budget_id FOR UPDATE;
  SELECT * INTO v_state FROM public.budget_category_state WHERE budget_id = p_budget_id;
  v_latest_state := v_state.lifecycle_state;

  v_fingerprint := 'set_amount|' || p_budget_id || '|' || p_target_amount::numeric(18, 2)::text;
  SELECT * INTO v_existing FROM public.budget_operations WHERE request_key = p_request_key;
  IF FOUND THEN
    IF v_existing.budget_month_id <> v_month.id
       OR v_existing.operation_type <> 'adjustment'
       OR v_existing.request_fingerprint <> v_fingerprint THEN
      RAISE EXCEPTION 'request_key was already used for a different budget operation' USING ERRCODE = '23505';
    END IF;
    RETURN public.get_funded_budget_month(to_char(v_month.month_start, 'YYYY-MM'));
  END IF;

  IF v_latest_state <> 'active' THEN
    RAISE EXCEPTION 'Budget % is inactive; reactivate it before adjusting funding', p_budget_id USING ERRCODE = '55000';
  END IF;
  v_delta := p_target_amount - v_state.final_funded;
  IF v_delta = 0 THEN
    INSERT INTO public.budget_operations (
      budget_month_id, request_key, request_fingerprint, operation_type, effective_date, reason
    ) VALUES (v_month.id, p_request_key, v_fingerprint, 'adjustment', v_month.month_start, p_reason);
    PERFORM public.budget_assert_reconciled(v_month.id);
    RETURN public.get_funded_budget_month(to_char(v_month.month_start, 'YYYY-MM'));
  END IF;

  SELECT unallocated INTO v_unallocated FROM public.budget_month_funding_state
  WHERE budget_month_id = v_month.id;
  IF EXISTS (
    SELECT 1 FROM public.budget_actual_transactions(NULL,NULL)
    WHERE movement_type = 'expense' AND category_id = v_budget.category_id
      AND transaction_date >= v_month.month_start
      AND transaction_date < (v_month.month_start + interval '1 month')::date
      AND total_amount::text IN ('NaN', 'Infinity', '-Infinity')
  ) THEN
    RAISE EXCEPTION 'Budget actual spending contains a non-finite amount' USING ERRCODE = '22003';
  END IF;
  SELECT coalesce(sum(total_amount), 0)::numeric(18, 2) INTO v_actual
  FROM public.budget_actual_transactions(NULL,NULL)
  WHERE movement_type = 'expense' AND category_id = v_budget.category_id
    AND transaction_date >= v_month.month_start
    AND transaction_date < (v_month.month_start + interval '1 month')::date;

  IF v_delta > 0 AND v_delta > v_unallocated THEN
    RAISE EXCEPTION 'Insufficient unallocated funds: requested %, available %', v_delta, v_unallocated USING ERRCODE = '23514';
  END IF;
  IF v_delta < 0 AND -v_delta > greatest(v_state.final_funded - v_actual, 0) THEN
    RAISE EXCEPTION 'Cannot release spent funding; eligible release is %', greatest(v_state.final_funded - v_actual, 0)
      USING ERRCODE = '23514';
  END IF;

  INSERT INTO public.budget_operations (
    budget_month_id, request_key, request_fingerprint, operation_type, effective_date, reason
  ) VALUES (v_month.id, p_request_key, v_fingerprint, 'adjustment', v_month.month_start, p_reason)
  RETURNING id INTO v_operation_id;

  INSERT INTO public.budget_movements (operation_id, source_budget_id, destination_budget_id, amount)
  VALUES (
    v_operation_id,
    CASE WHEN v_delta < 0 THEN p_budget_id ELSE NULL END,
    CASE WHEN v_delta > 0 THEN p_budget_id ELSE NULL END,
    abs(v_delta)
  );

  PERFORM public.budget_assert_reconciled(v_month.id);
  RETURN public.get_funded_budget_month(to_char(v_month.month_start, 'YYYY-MM'));
END;
$function$;

CREATE OR REPLACE FUNCTION public.remove_funded_budget(p_budget_id bigint, p_request_key uuid, p_reason text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
DECLARE
  v_budget public.budgets%ROWTYPE;
  v_month public.budget_months%ROWTYPE;
  v_state public.budget_category_state%ROWTYPE;
  v_actual NUMERIC(18, 2);
  v_release NUMERIC(18, 2);
  v_operation_id BIGINT;
  v_existing public.budget_operations%ROWTYPE;
  v_fingerprint TEXT;
BEGIN
  IF p_request_key IS NULL THEN RAISE EXCEPTION 'request_key is required' USING ERRCODE = '22023'; END IF;
  SELECT * INTO v_budget FROM public.budgets WHERE id = p_budget_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Budget % does not exist', p_budget_id USING ERRCODE = 'P0002'; END IF;
  SELECT * INTO v_month FROM public.budget_months WHERE id = v_budget.budget_month_id FOR UPDATE;
  SELECT * INTO v_budget FROM public.budgets WHERE id = p_budget_id FOR UPDATE;
  v_fingerprint := 'remove|' || p_budget_id;
  SELECT * INTO v_existing FROM public.budget_operations WHERE request_key = p_request_key;
  IF FOUND THEN
    IF v_existing.budget_month_id <> v_month.id OR v_existing.operation_type <> 'removal'
       OR v_existing.request_fingerprint <> v_fingerprint THEN
      RAISE EXCEPTION 'request_key was already used for a different budget operation' USING ERRCODE = '23505';
    END IF;
    RETURN public.get_funded_budget_month(to_char(v_month.month_start, 'YYYY-MM'));
  END IF;

  SELECT * INTO v_state FROM public.budget_category_state WHERE budget_id = p_budget_id;
  IF v_state.lifecycle_state <> 'active' THEN
    RAISE EXCEPTION 'Budget % is not active', p_budget_id USING ERRCODE = '55000';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.budget_actual_transactions(NULL,NULL)
    WHERE movement_type = 'expense' AND category_id = v_budget.category_id
      AND transaction_date >= v_month.month_start
      AND transaction_date < (v_month.month_start + interval '1 month')::date
      AND total_amount::text IN ('NaN', 'Infinity', '-Infinity')
  ) THEN
    RAISE EXCEPTION 'Budget actual spending contains a non-finite amount' USING ERRCODE = '22003';
  END IF;
  SELECT coalesce(sum(total_amount), 0)::numeric(18, 2) INTO v_actual
  FROM public.budget_actual_transactions(NULL,NULL)
  WHERE movement_type = 'expense' AND category_id = v_budget.category_id
    AND transaction_date >= v_month.month_start
    AND transaction_date < (v_month.month_start + interval '1 month')::date;
  v_release := greatest(v_state.final_funded - v_actual, 0);

  INSERT INTO public.budget_operations (
    budget_month_id, request_key, request_fingerprint, operation_type, effective_date, reason
  ) VALUES (v_month.id, p_request_key, v_fingerprint, 'removal', v_month.month_start, p_reason)
  RETURNING id INTO v_operation_id;
  IF v_release > 0 THEN
    INSERT INTO public.budget_movements (operation_id, source_budget_id, destination_budget_id, amount)
    VALUES (v_operation_id, p_budget_id, NULL, v_release);
  END IF;
  INSERT INTO public.budget_lifecycle_events (operation_id, budget_id, state, actual_spent_snapshot)
  VALUES (v_operation_id, p_budget_id, 'inactive', v_actual);

  PERFORM public.budget_assert_reconciled(v_month.id);
  RETURN public.get_funded_budget_month(to_char(v_month.month_start, 'YYYY-MM'));
END;
$function$;

CREATE OR REPLACE FUNCTION public.reverse_funded_budget_operation(p_operation_id bigint, p_request_key uuid, p_reason text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
DECLARE
  v_original public.budget_operations%ROWTYPE;
  v_month public.budget_months%ROWTYPE;
  v_existing public.budget_operations%ROWTYPE;
  v_funding public.budget_funding_entries%ROWTYPE;
  v_movement public.budget_movements%ROWTYPE;
  v_source_state public.budget_category_state%ROWTYPE;
  v_actual NUMERIC(18, 2);
  v_unallocated NUMERIC(18, 2);
  v_reversal_id BIGINT;
  v_fingerprint TEXT;
BEGIN
  IF EXISTS (SELECT 1 FROM public.budget_operations WHERE id=p_operation_id AND operation_type IN ('savings_reserve_retirement','savings_reserve_retirement_reversal','savings_account_transfer','savings_account_transfer_reversal')) THEN RAISE EXCEPTION 'פעולת חיסכון מחייבת פקודת תיקון ייעודית' USING ERRCODE='23514'; END IF;
IF p_request_key IS NULL THEN RAISE EXCEPTION 'request_key is required' USING ERRCODE = '22023'; END IF;
  SELECT * INTO v_original FROM public.budget_operations WHERE id = p_operation_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Budget operation % does not exist', p_operation_id USING ERRCODE = 'P0002'; END IF;
  SELECT * INTO v_month FROM public.budget_months WHERE id = v_original.budget_month_id FOR UPDATE;
  SELECT * INTO v_original FROM public.budget_operations WHERE id = p_operation_id;
  v_fingerprint := 'reverse|' || p_operation_id;
  SELECT * INTO v_existing FROM public.budget_operations WHERE request_key = p_request_key;
  IF FOUND THEN
    IF v_existing.operation_type <> 'reversal' OR v_existing.reverses_operation_id <> p_operation_id
       OR v_existing.request_fingerprint <> v_fingerprint THEN
      RAISE EXCEPTION 'request_key was already used for a different budget operation' USING ERRCODE = '23505';
    END IF;
    RETURN public.get_funded_budget_month(to_char(v_month.month_start, 'YYYY-MM'));
  END IF;
  IF EXISTS (SELECT 1 FROM public.budget_operations WHERE reverses_operation_id = p_operation_id) THEN
    RAISE EXCEPTION 'Budget operation % has already been reversed', p_operation_id USING ERRCODE = '23505';
  END IF;

  IF v_original.operation_type = 'adjustment' THEN
    SELECT * INTO v_movement FROM public.budget_movements WHERE operation_id = p_operation_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Adjustment operation % has no movement', p_operation_id; END IF;
    PERFORM 1 FROM public.budgets
    WHERE id IN (v_movement.source_budget_id, v_movement.destination_budget_id)
    ORDER BY id FOR UPDATE;
  END IF;

  INSERT INTO public.budget_operations (
    budget_month_id, request_key, request_fingerprint, operation_type,
    effective_date, reason, reverses_operation_id
  ) VALUES (
    v_month.id, p_request_key, v_fingerprint, 'reversal', v_month.month_start,
    p_reason, p_operation_id
  ) RETURNING id INTO v_reversal_id;

  IF v_original.operation_type = 'manual_funding' THEN
    SELECT * INTO v_funding FROM public.budget_funding_entries WHERE operation_id = p_operation_id;
    IF v_funding.source_kind <> 'manual_available_funds' OR v_funding.amount_delta <= 0 THEN
      RAISE EXCEPTION 'Only positive manual funding operations can be reversed';
    END IF;
    SELECT unallocated INTO v_unallocated FROM public.budget_month_funding_state WHERE budget_month_id = v_month.id;
    IF v_funding.amount_delta > v_unallocated THEN
      RAISE EXCEPTION 'Funding reversal would make unallocated funds negative' USING ERRCODE = '23514';
    END IF;
    INSERT INTO public.budget_funding_entries (
      operation_id, amount_delta, source_kind, source_label, reverses_funding_entry_id
    ) VALUES (
      v_reversal_id, -v_funding.amount_delta, 'manual_available_funds',
      'Reversal: ' || v_funding.source_label, v_funding.id
    );
  ELSIF v_original.operation_type = 'adjustment' THEN
    IF v_movement.source_budget_id IS NULL THEN
      SELECT * INTO v_source_state FROM public.budget_category_state WHERE budget_id = v_movement.destination_budget_id;
      IF EXISTS (
        SELECT 1 FROM public.budget_actual_transactions(NULL,NULL) t
        JOIN public.budgets b ON b.category_id = t.category_id
        WHERE b.id = v_movement.destination_budget_id
          AND t.movement_type = 'expense'
          AND t.transaction_date >= v_month.month_start
          AND t.transaction_date < (v_month.month_start + interval '1 month')::date
          AND t.total_amount::text IN ('NaN', 'Infinity', '-Infinity')
      ) THEN
        RAISE EXCEPTION 'Budget actual spending contains a non-finite amount' USING ERRCODE = '22003';
      END IF;
      SELECT coalesce(sum(t.total_amount), 0)::numeric(18, 2) INTO v_actual
      FROM public.budget_actual_transactions(NULL,NULL) t
      JOIN public.budgets b ON b.category_id = t.category_id
      WHERE b.id = v_movement.destination_budget_id
        AND t.movement_type = 'expense'
        AND t.transaction_date >= v_month.month_start
        AND t.transaction_date < (v_month.month_start + interval '1 month')::date;
      IF v_movement.amount > greatest(v_source_state.final_funded - v_actual, 0) THEN
        RAISE EXCEPTION 'Adjustment reversal would release spent funding' USING ERRCODE = '23514';
      END IF;
    ELSE
      SELECT unallocated INTO v_unallocated FROM public.budget_month_funding_state WHERE budget_month_id = v_month.id;
      IF v_movement.amount > v_unallocated THEN
        RAISE EXCEPTION 'Adjustment reversal requires more unallocated funds than are available' USING ERRCODE = '23514';
      END IF;
    END IF;
    INSERT INTO public.budget_movements (
      operation_id, source_budget_id, destination_budget_id, amount
    ) VALUES (
      v_reversal_id, v_movement.destination_budget_id, v_movement.source_budget_id, v_movement.amount
    );
  ELSE
    RAISE EXCEPTION
      'Operation type % must be corrected through its lifecycle command, not generic reversal',
      v_original.operation_type USING ERRCODE = '0A000';
  END IF;

  PERFORM public.budget_assert_reconciled(v_month.id);
  RETURN public.get_funded_budget_month(to_char(v_month.month_start, 'YYYY-MM'));
END;
$function$;

CREATE OR REPLACE FUNCTION public.copy_funded_budget_month(p_from_month text, p_to_month text, p_request_key uuid, p_reason text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
DECLARE
  v_from_start DATE := public.budget_month_start_from_key(p_from_month);
  v_to_start DATE := public.budget_month_start_from_key(p_to_month);
  v_from_id BIGINT;
  v_to_id BIGINT;
  v_operation_id BIGINT;
  v_existing public.budget_operations%ROWTYPE;
  v_unallocated NUMERIC(18, 2);
  v_additions NUMERIC(18, 2) := 0;
  v_releases NUMERIC(18, 2) := 0;
  v_target_actual NUMERIC(18, 2);
  v_target_id BIGINT;
  v_target_final NUMERIC(18, 2);
  v_target_state TEXT;
  v_delta NUMERIC(18, 2);
  v_fingerprint TEXT;
  v_result JSONB;
  v_skipped JSONB;
  source_row RECORD;
BEGIN
  IF p_request_key IS NULL THEN RAISE EXCEPTION 'request_key is required' USING ERRCODE = '22023'; END IF;
  IF v_from_start = v_to_start THEN
    RAISE EXCEPTION 'Source and target budget months must differ' USING ERRCODE = '22023';
  END IF;
  SELECT id INTO v_from_id FROM public.budget_months WHERE month_start = v_from_start;
  IF NOT FOUND THEN RAISE EXCEPTION 'Source month has no funded budget'; END IF;

  -- Copy can release target funding based on actual spending, so it shares the
  -- transaction-first serialization order used by carryover and overrides.
  LOCK TABLE public.transactions IN SHARE MODE;
  INSERT INTO public.budget_months (month_start) VALUES (v_to_start)
  ON CONFLICT (month_start) DO NOTHING;
  SELECT id INTO v_to_id FROM public.budget_months WHERE month_start = v_to_start;
  PERFORM 1 FROM public.budget_months WHERE id IN (v_from_id, v_to_id) ORDER BY id FOR UPDATE;
  PERFORM 1 FROM public.budgets
    WHERE budget_month_id IN (v_from_id, v_to_id) ORDER BY id FOR UPDATE;
  PERFORM 1 FROM public.budget_month_overrides
    WHERE budget_month_id = v_to_id ORDER BY category_id FOR SHARE;
  PERFORM public.budget_assert_reconciled(v_from_id);
  PERFORM public.budget_assert_reconciled(v_to_id);

  v_fingerprint := 'copy|' || p_from_month || '|' || p_to_month;
  SELECT * INTO v_existing FROM public.budget_operations WHERE request_key = p_request_key;
  IF FOUND THEN
    IF v_existing.budget_month_id <> v_to_id OR v_existing.operation_type <> 'copy'
       OR v_existing.request_fingerprint <> v_fingerprint THEN
      RAISE EXCEPTION 'request_key was already used for a different budget operation'
        USING ERRCODE = '23505';
    END IF;
    v_result := public.get_funded_budget_month(p_to_month);
    SELECT coalesce(jsonb_agg(jsonb_build_object(
      'category_id', mo.category_id, 'amount', mo.amount::numeric(18, 2)::text,
      'reason', 'MONTH_OVERRIDE_PRESERVED'
    ) ORDER BY mo.category_id), '[]'::jsonb) INTO v_skipped
    FROM public.budget_month_overrides mo
    WHERE mo.budget_month_id = v_to_id
      AND EXISTS (
        SELECT 1 FROM public.budget_category_state src
        WHERE src.budget_month_id = v_from_id AND src.category_id = mo.category_id
          AND src.lifecycle_state = 'active'
      );
    RETURN v_result || jsonb_build_object('copy_preserved_overrides', v_skipped);
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.budget_category_state
    WHERE budget_month_id = v_from_id AND lifecycle_state = 'active'
  ) THEN
    RAISE EXCEPTION 'Source month has no active category budgets';
  END IF;

  FOR source_row IN
    SELECT src.* FROM public.budget_category_state src
    WHERE src.budget_month_id = v_from_id AND src.lifecycle_state = 'active'
      AND NOT EXISTS (
        SELECT 1 FROM public.budget_month_overrides mo
        WHERE mo.budget_month_id = v_to_id AND mo.category_id = src.category_id
      )
    ORDER BY src.category_id
  LOOP
    SELECT cs.budget_id, cs.final_funded, cs.lifecycle_state
    INTO v_target_id, v_target_final, v_target_state
    FROM public.budget_category_state cs
    WHERE cs.budget_month_id = v_to_id AND cs.category_id = source_row.category_id;
    IF NOT FOUND THEN
      v_additions := v_additions + source_row.final_funded;
    ELSE
      v_delta := source_row.final_funded - v_target_final;
      IF v_delta > 0 THEN
        v_additions := v_additions + v_delta;
      ELSIF v_delta < 0 THEN
        IF EXISTS (
          SELECT 1 FROM public.budget_actual_transactions(NULL,NULL)
          WHERE movement_type = 'expense' AND category_id = source_row.category_id
            AND transaction_date >= v_to_start
            AND transaction_date < (v_to_start + interval '1 month')::date
            AND total_amount::text IN ('NaN', 'Infinity', '-Infinity')
        ) THEN
          RAISE EXCEPTION 'Budget actual spending contains a non-finite amount' USING ERRCODE = '22003';
        END IF;
        SELECT greatest(coalesce(sum(total_amount), 0), 0)::numeric(18, 2)
        INTO v_target_actual
        FROM public.budget_actual_transactions(NULL,NULL)
        WHERE movement_type = 'expense' AND category_id = source_row.category_id
          AND transaction_date >= v_to_start
          AND transaction_date < (v_to_start + interval '1 month')::date;
        IF -v_delta > greatest(v_target_final - v_target_actual, 0) THEN
          RAISE EXCEPTION 'Copy cannot release spent funding from target category %', source_row.category_id
            USING ERRCODE = '23514';
        END IF;
        v_releases := v_releases + (-v_delta);
      END IF;
    END IF;
  END LOOP;
  SELECT unallocated INTO v_unallocated FROM public.budget_month_funding_state WHERE budget_month_id = v_to_id;
  IF v_additions > v_unallocated + v_releases THEN
    RAISE EXCEPTION 'Destination month needs % additional funded money; only % is available',
      v_additions, v_unallocated + v_releases USING ERRCODE = '23514';
  END IF;

  INSERT INTO public.budget_operations (
    budget_month_id, request_key, request_fingerprint, operation_type, effective_date, reason
  ) VALUES (v_to_id, p_request_key, v_fingerprint, 'copy', v_to_start, p_reason)
  RETURNING id INTO v_operation_id;

  FOR source_row IN
    SELECT src.* FROM public.budget_category_state src
    WHERE src.budget_month_id = v_from_id AND src.lifecycle_state = 'active'
      AND NOT EXISTS (
        SELECT 1 FROM public.budget_month_overrides mo
        WHERE mo.budget_month_id = v_to_id AND mo.category_id = src.category_id
      )
    ORDER BY src.category_id
  LOOP
    SELECT cs.budget_id, cs.final_funded, cs.lifecycle_state
    INTO v_target_id, v_target_final, v_target_state
    FROM public.budget_category_state cs
    WHERE cs.budget_month_id = v_to_id AND cs.category_id = source_row.category_id;
    IF NOT FOUND THEN
      INSERT INTO public.budgets (
        category_id, month, amount, budget_month_id, starting_amount,
        starting_kind, created_by_operation_id
      ) VALUES (
        source_row.category_id, p_to_month, source_row.final_funded, v_to_id,
        source_row.final_funded, 'copied', v_operation_id
      ) RETURNING id INTO v_target_id;
      INSERT INTO public.budget_lifecycle_events (operation_id, budget_id, state)
      VALUES (v_operation_id, v_target_id, 'active');
    ELSE
      v_delta := source_row.final_funded - v_target_final;
      IF v_delta <> 0 THEN
        INSERT INTO public.budget_movements (
          operation_id, source_budget_id, destination_budget_id, amount
        ) VALUES (
          v_operation_id,
          CASE WHEN v_delta < 0 THEN v_target_id ELSE NULL END,
          CASE WHEN v_delta > 0 THEN v_target_id ELSE NULL END,
          abs(v_delta)
        );
      END IF;
      IF v_target_state = 'inactive' THEN
        INSERT INTO public.budget_lifecycle_events (operation_id, budget_id, state)
        VALUES (v_operation_id, v_target_id, 'active');
      END IF;
    END IF;
  END LOOP;

  PERFORM public.budget_assert_reconciled(v_to_id);
  v_result := public.get_funded_budget_month(p_to_month);
  SELECT coalesce(jsonb_agg(jsonb_build_object(
    'category_id', mo.category_id, 'amount', mo.amount::numeric(18, 2)::text,
    'reason', 'MONTH_OVERRIDE_PRESERVED'
  ) ORDER BY mo.category_id), '[]'::jsonb) INTO v_skipped
  FROM public.budget_month_overrides mo
  WHERE mo.budget_month_id = v_to_id
    AND EXISTS (
      SELECT 1 FROM public.budget_category_state src
      WHERE src.budget_month_id = v_from_id AND src.category_id = mo.category_id
        AND src.lifecycle_state = 'active'
    );
  RETURN v_result || jsonb_build_object('copy_preserved_overrides', v_skipped);
END;
$function$;

CREATE OR REPLACE FUNCTION public.budget_carryover_candidate_rows(p_destination_month text)
 RETURNS TABLE(category_id bigint, category_name text, category_icon text, source_budget_id bigint, destination_budget_id bigint, source_final_funded numeric, source_raw_actual_spent numeric, source_effective_actual_spent numeric, eligible_amount numeric, status text, blocked_reason text)
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
DECLARE
  v_destination_start DATE:=public.budget_month_start_from_key(p_destination_month);
  v_source_start DATE:=(v_destination_start-interval '1 month')::date;
  v_source_id BIGINT; v_destination_id BIGINT; v_destination_initialized BOOLEAN:=false;
BEGIN
  SELECT id INTO v_source_id FROM public.budget_months WHERE month_start=v_source_start;
  SELECT id INTO v_destination_id FROM public.budget_months WHERE month_start=v_destination_start;
  IF v_destination_id IS NOT NULL THEN
    SELECT EXISTS(SELECT 1 FROM public.budget_operations
      WHERE budget_month_id=v_destination_id AND operation_type='month_initialization')
    INTO v_destination_initialized;
  END IF;
  IF EXISTS(SELECT 1 FROM public.budget_actual_transactions(NULL,NULL) WHERE movement_type='expense'
    AND transaction_date>=v_source_start
    AND transaction_date<(v_destination_start+interval '1 month')::date
    AND total_amount::text IN ('NaN','Infinity','-Infinity')) THEN
    RAISE EXCEPTION 'Carryover actual spending contains a non-finite amount' USING ERRCODE='22003';
  END IF;
  IF EXISTS(SELECT 1 FROM public.budget_actual_transactions(NULL,NULL) t WHERE t.movement_type='expense'
    AND t.transaction_date>=v_source_start
    AND t.transaction_date<(v_destination_start+interval '1 month')::date
    GROUP BY t.category_id,date_trunc('month',t.transaction_date)
    HAVING sum(t.total_amount)<>round(sum(t.total_amount),2)
       OR abs(sum(t.total_amount))>9999999999999999.99) THEN
    RAISE EXCEPTION 'Carryover actual spending must fit finite NUMERIC(18,2) exactly' USING ERRCODE='22003';
  END IF;
  RETURN QUERY
  WITH source_actuals AS(
    SELECT t.category_id,sum(t.total_amount)::numeric(18,2) actual
    FROM public.budget_actual_transactions(NULL,NULL) t WHERE t.movement_type='expense'
      AND t.transaction_date>=v_source_start AND t.transaction_date<v_destination_start
    GROUP BY t.category_id
  ),destination_actuals AS(
    SELECT t.category_id,sum(t.total_amount)::numeric(18,2) actual
    FROM public.budget_actual_transactions(NULL,NULL) t WHERE t.movement_type='expense'
      AND t.transaction_date>=v_destination_start
      AND t.transaction_date<(v_destination_start+interval '1 month')::date
    GROUP BY t.category_id
  ),candidate AS(
    SELECT c.id category_id,c.name,c.icon,src.budget_id source_budget_id,
      dst.budget_id destination_budget_id,coalesce(src.final_funded,0)::numeric(18,2) source_final_funded,
      coalesce(sa.actual,0)::numeric(18,2) source_raw_actual_spent,
      greatest(coalesce(sa.actual,0),0)::numeric(18,2) source_effective_actual_spent,
      greatest(coalesce(src.final_funded,0)-greatest(coalesce(sa.actual,0),0),0)::numeric(18,2) eligible_amount,
      c.is_active,src.lifecycle_state source_lifecycle,dst.lifecycle_state destination_lifecycle,
      coalesce(da.actual,0)::numeric(18,2) destination_actual,
      coalesce(dst.final_funded,0)::numeric(18,2) destination_final,
      mo.category_id IS NOT NULL AND NOT v_destination_initialized override_pending,
      rd.category_id IS NOT NULL AND NOT v_destination_initialized recurring_pending,
      EXISTS(
        SELECT 1 FROM public.budget_operation_items original
        WHERE original.item_kind='carryover' AND original.category_id IS NOT NULL
          AND original.source_budget_id=src.budget_id AND original.reversed_item_id IS NULL
          AND NOT EXISTS(SELECT 1 FROM public.budget_operation_items correction
            WHERE correction.item_kind='carryover' AND correction.reversed_item_id=original.id)
      ) already_applied
    FROM public.budget_unused_balance_policies policy
    JOIN public.categories c ON c.id=policy.category_id
    LEFT JOIN public.budget_category_state src
      ON src.budget_month_id=v_source_id AND src.category_id=c.id
    LEFT JOIN source_actuals sa ON sa.category_id=c.id
    LEFT JOIN public.budget_category_state dst
      ON dst.budget_month_id=v_destination_id AND dst.category_id=c.id
    LEFT JOIN destination_actuals da ON da.category_id=c.id
    LEFT JOIN public.budget_recurring_defaults rd ON rd.category_id=c.id
    LEFT JOIN public.budget_month_overrides mo
      ON mo.budget_month_id=v_destination_id AND mo.category_id=c.id
    WHERE policy.policy='carry_forward' AND c.type='expense'
  )
  SELECT candidate.category_id,candidate.name,candidate.icon,candidate.source_budget_id,
    candidate.destination_budget_id,candidate.source_final_funded,
    candidate.source_raw_actual_spent,candidate.source_effective_actual_spent,candidate.eligible_amount,
    CASE WHEN candidate.already_applied THEN 'already_applied'
      WHEN NOT candidate.is_active OR candidate.source_budget_id IS NULL
        OR candidate.source_lifecycle<>'active' OR candidate.eligible_amount<=0 THEN 'blocked'
      WHEN candidate.destination_budget_id IS NOT NULL AND candidate.destination_lifecycle<>'active' THEN 'blocked'
      WHEN candidate.destination_budget_id IS NULL AND (candidate.override_pending OR candidate.recurring_pending) THEN 'blocked'
      WHEN candidate.destination_budget_id IS NULL AND candidate.destination_actual>0 THEN 'blocked'
      WHEN candidate.destination_budget_id IS NOT NULL AND candidate.destination_actual>candidate.destination_final THEN 'blocked'
      ELSE 'ready' END,
    CASE WHEN candidate.already_applied THEN NULL
      WHEN NOT candidate.is_active THEN 'CATEGORY_INACTIVE'
      WHEN candidate.source_budget_id IS NULL THEN 'SOURCE_BUDGET_MISSING'
      WHEN candidate.source_lifecycle<>'active' THEN 'SOURCE_BUDGET_INACTIVE'
      WHEN candidate.eligible_amount<=0 THEN 'NO_ELIGIBLE_BALANCE'
      WHEN candidate.destination_budget_id IS NOT NULL AND candidate.destination_lifecycle<>'active'
        THEN 'DESTINATION_BUDGET_INACTIVE'
      WHEN candidate.destination_budget_id IS NULL AND candidate.override_pending
        THEN 'MONTH_OVERRIDE_INITIALIZATION_REQUIRED'
      WHEN candidate.destination_budget_id IS NULL AND candidate.recurring_pending
        THEN 'RECURRING_INITIALIZATION_REQUIRED'
      WHEN candidate.destination_budget_id IS NULL AND candidate.destination_actual>0
        THEN 'UNBUDGETED_ACTUAL_EXISTS'
      WHEN candidate.destination_budget_id IS NOT NULL AND candidate.destination_actual>candidate.destination_final
        THEN 'DESTINATION_DEFICIT'
      ELSE NULL END
  FROM candidate ORDER BY candidate.name,candidate.category_id;
END;
$function$;

CREATE OR REPLACE FUNCTION public.reverse_budget_carryover(p_transfer_id bigint, p_request_key uuid, p_reason text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
DECLARE
  v_original public.budget_operation_items%ROWTYPE; v_original_root public.budget_operations%ROWTYPE;
  v_source public.budget_category_state%ROWTYPE; v_destination public.budget_category_state%ROWTYPE;
  v_source_month public.budget_months%ROWTYPE; v_destination_month public.budget_months%ROWTYPE;
  v_destination_actual NUMERIC(18,2); v_existing public.budget_operations%ROWTYPE;
  v_root_id BIGINT; v_source_operation_id BIGINT; v_destination_operation_id BIGINT;
  v_source_funding public.budget_funding_entries%ROWTYPE;
  v_destination_funding public.budget_funding_entries%ROWTYPE;
  v_source_movement_id BIGINT; v_destination_movement_id BIGINT;
  v_source_funding_id BIGINT; v_destination_funding_id BIGINT;
BEGIN
  IF p_transfer_id IS NULL OR p_request_key IS NULL THEN
    RAISE EXCEPTION 'transfer_id and request_key are required' USING ERRCODE='22023';
  END IF;
  SELECT * INTO v_original FROM public.budget_operation_items
  WHERE id=p_transfer_id AND item_kind='carryover' AND category_id IS NOT NULL
    AND reversed_item_id IS NULL;
  IF NOT FOUND THEN RAISE EXCEPTION 'Original carryover transfer % does not exist',p_transfer_id USING ERRCODE='P0002'; END IF;
  SELECT * INTO v_original_root FROM public.budget_operations WHERE id=v_original.operation_id;
  SELECT * INTO v_existing FROM public.budget_operations WHERE request_key=p_request_key;
  IF FOUND THEN
    IF v_existing.operation_type<>'carryover_out'
       OR v_existing.request_fingerprint<>'carryover_reverse|'||p_transfer_id THEN
      RAISE EXCEPTION 'request_key was already used for a different carryover request' USING ERRCODE='23505';
    END IF;
    RETURN jsonb_build_object(
      'source',public.get_funded_budget_month((SELECT month FROM public.budget_month_funding_state
        WHERE budget_month_id=v_original.budget_month_id)),
      'destination',public.get_funded_budget_month((SELECT month FROM public.budget_month_funding_state
        WHERE budget_month_id=v_original.destination_budget_month_id)));
  END IF;
  IF EXISTS(SELECT 1 FROM public.budget_operation_items
    WHERE item_kind='carryover' AND reversed_item_id=p_transfer_id) THEN
    RAISE EXCEPTION 'Carryover transfer % has already been reversed',p_transfer_id USING ERRCODE='23505';
  END IF;
  LOCK TABLE public.transactions IN SHARE MODE;
  PERFORM 1 FROM public.budget_months
    WHERE id IN(v_original.budget_month_id,v_original.destination_budget_month_id) ORDER BY id FOR UPDATE;
  PERFORM 1 FROM public.budgets
    WHERE id IN(v_original.source_budget_id,v_original.destination_budget_id) ORDER BY id FOR UPDATE;
  SELECT * INTO v_existing FROM public.budget_operations WHERE request_key=p_request_key;
  IF FOUND THEN
    IF v_existing.operation_type<>'carryover_out'
       OR v_existing.request_fingerprint<>'carryover_reverse|'||p_transfer_id THEN
      RAISE EXCEPTION 'request_key was already used for a different carryover request' USING ERRCODE='23505';
    END IF;
    RETURN jsonb_build_object(
      'source',public.get_funded_budget_month((SELECT month FROM public.budget_month_funding_state
        WHERE budget_month_id=v_original.budget_month_id)),
      'destination',public.get_funded_budget_month((SELECT month FROM public.budget_month_funding_state
        WHERE budget_month_id=v_original.destination_budget_month_id)));
  END IF;
  IF EXISTS(SELECT 1 FROM public.budget_operation_items
    WHERE item_kind='carryover' AND reversed_item_id=p_transfer_id) THEN
    RAISE EXCEPTION 'Carryover transfer % has already been reversed',p_transfer_id USING ERRCODE='23505';
  END IF;
  SELECT * INTO v_source FROM public.budget_category_state WHERE budget_id=v_original.source_budget_id;
  SELECT * INTO v_destination FROM public.budget_category_state WHERE budget_id=v_original.destination_budget_id;
  SELECT * INTO v_source_month FROM public.budget_months WHERE id=v_original.budget_month_id;
  SELECT * INTO v_destination_month FROM public.budget_months WHERE id=v_original.destination_budget_month_id;
  IF v_source.lifecycle_state<>'active' OR v_destination.lifecycle_state<>'active' THEN
    RAISE EXCEPTION 'Carryover reversal requires active source and destination budgets' USING ERRCODE='23514';
  END IF;
  IF EXISTS(SELECT 1 FROM public.budget_actual_transactions(NULL,NULL) WHERE movement_type='expense'
    AND category_id=v_destination.category_id AND transaction_date>=v_destination_month.month_start
    AND transaction_date<(v_destination_month.month_start+interval '1 month')::date
    AND total_amount::text IN ('NaN','Infinity','-Infinity')) THEN
    RAISE EXCEPTION 'Carryover actual spending contains a non-finite amount' USING ERRCODE='22003';
  END IF;
  SELECT greatest(coalesce(sum(total_amount),0),0)::numeric(18,2) INTO v_destination_actual
  FROM public.budget_actual_transactions(NULL,NULL) WHERE movement_type='expense' AND category_id=v_destination.category_id
    AND transaction_date>=v_destination_month.month_start
    AND transaction_date<(v_destination_month.month_start+interval '1 month')::date;
  IF v_original.amount>greatest(v_destination.final_funded-v_destination_actual,0) THEN
    RAISE EXCEPTION 'Carryover reversal would release spent destination funding' USING ERRCODE='23514';
  END IF;
  SELECT * INTO v_source_funding FROM public.budget_funding_entries WHERE id=v_original.source_funding_entry_id;
  SELECT * INTO v_destination_funding FROM public.budget_funding_entries WHERE id=v_original.destination_funding_entry_id;

  v_root_id:=nullif(current_setting('finance_tracker.budget_root_operation_id',true),'')::bigint;
  IF v_root_id IS NULL OR NOT EXISTS(SELECT 1 FROM public.budget_operations
    WHERE id=v_root_id AND parent_operation_id IS NULL AND reverses_operation_id=v_original.operation_id) THEN
    v_root_id:=public.budget_create_action_root(v_original.destination_budget_month_id,p_request_key,
      'carryover_reverse|'||p_transfer_id,'carryover_out',v_destination_month.month_start,
      p_reason,v_original.operation_id);
  END IF;
  INSERT INTO public.budget_operations(budget_month_id,request_key,request_fingerprint,operation_type,
    effective_date,reason,reverses_operation_id)
  VALUES(v_original.destination_budget_month_id,
    public.budget_derived_request_key(p_request_key,'destination-return'),
    'carryover_reverse|'||p_transfer_id,
    'carryover_out',v_destination_month.month_start,p_reason,v_original.destination_operation_id)
  RETURNING id INTO v_destination_operation_id;
  INSERT INTO public.budget_funding_entries(operation_id,amount_delta,source_kind,source_label,reverses_funding_entry_id)
  VALUES(v_destination_operation_id,-v_original.amount,'carryover_transfer',
    'Carryover reversal to '||to_char(v_source_month.month_start,'YYYY-MM'),v_destination_funding.id)
  RETURNING id INTO v_destination_funding_id;
  INSERT INTO public.budget_movements(operation_id,source_budget_id,amount)
  VALUES(v_destination_operation_id,v_original.destination_budget_id,v_original.amount)
  RETURNING id INTO v_destination_movement_id;
  INSERT INTO public.budget_operations(budget_month_id,request_key,request_fingerprint,operation_type,
    effective_date,reason,reverses_operation_id)
  VALUES(v_original.budget_month_id,public.budget_derived_request_key(p_request_key,'source-return'),
    'carryover_reverse_return|'||p_transfer_id,'carryover_in',v_source_month.month_start,p_reason,
    v_original.source_operation_id) RETURNING id INTO v_source_operation_id;
  INSERT INTO public.budget_funding_entries(operation_id,amount_delta,source_kind,source_label,reverses_funding_entry_id)
  VALUES(v_source_operation_id,v_original.amount,'carryover_transfer',
    'Carryover reversal from '||to_char(v_destination_month.month_start,'YYYY-MM'),v_source_funding.id)
  RETURNING id INTO v_source_funding_id;
  INSERT INTO public.budget_movements(operation_id,destination_budget_id,amount)
  VALUES(v_source_operation_id,v_original.source_budget_id,v_original.amount)
  RETURNING id INTO v_source_movement_id;
  INSERT INTO public.budget_operation_items(
    operation_id,item_kind,action_kind,budget_month_id,destination_budget_month_id,category_id,
    source_budget_id,destination_budget_id,source_operation_id,destination_operation_id,
    amount,raw_actual_snapshot,funded_before,source_movement_id,destination_movement_id,
    source_funding_entry_id,destination_funding_entry_id,reversed_item_id
  ) VALUES(v_root_id,'carryover','reversal',v_original.budget_month_id,
    v_original.destination_budget_month_id,v_original.category_id,v_original.source_budget_id,
    v_original.destination_budget_id,v_source_operation_id,v_destination_operation_id,
    v_original.amount,v_original.raw_actual_snapshot,v_original.funded_before,
    v_source_movement_id,v_destination_movement_id,v_source_funding_id,v_destination_funding_id,p_transfer_id);
  PERFORM public.budget_assert_reconciled(v_original.budget_month_id);
  PERFORM public.budget_assert_reconciled(v_original.destination_budget_month_id);
  RETURN jsonb_build_object('source',public.get_funded_budget_month(to_char(v_source_month.month_start,'YYYY-MM')),
    'destination',public.get_funded_budget_month(to_char(v_destination_month.month_start,'YYYY-MM')));
END;
$function$;

CREATE OR REPLACE FUNCTION public.set_budget_month_override(p_month text, p_category_id bigint, p_amount numeric, p_request_key uuid, p_reason text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
DECLARE
  v_month_start DATE:=public.budget_month_start_from_key(p_month);
  v_current_start DATE:=date_trunc('month',timezone('Asia/Jerusalem',statement_timestamp()))::date;
  v_month_id BIGINT; v_budget public.budget_category_state%ROWTYPE;
  v_base public.budget_category_composition%ROWTYPE; v_existing public.budget_operations%ROWTYPE;
  v_initialized BOOLEAN; v_fingerprint TEXT; v_operation_id BIGINT; v_item_id BIGINT;
  v_movement_id BIGINT; v_lifecycle_id BIGINT; v_delta NUMERIC(18,2);
  v_unallocated NUMERIC(18,2); v_raw_actual NUMERIC; v_effective_actual NUMERIC(18,2);
  v_base_headroom NUMERIC(18,2); v_total_headroom NUMERIC(18,2);
  v_eligible_release NUMERIC(18,2); v_fallback NUMERIC(18,2);
  v_fallback_source TEXT; v_prior_override NUMERIC(18,2);
BEGIN
  IF p_request_key IS NULL OR p_category_id IS NULL OR p_amount IS NULL THEN
    RAISE EXCEPTION 'month, category_id, amount, and request_key are required' USING ERRCODE='22023';
  END IF;
  IF p_amount::text IN ('NaN','Infinity','-Infinity') OR p_amount<0
     OR p_amount<>round(p_amount,2) OR p_amount>9999999999999999.99 THEN
    RAISE EXCEPTION 'Month override amount must be a finite nonnegative two-decimal value'
      USING ERRCODE='22023';
  END IF;
  IF v_month_start<v_current_start THEN
    RAISE EXCEPTION 'HISTORICAL_MONTH_OVERRIDE_FORBIDDEN: month overrides are limited to current/future Asia/Jerusalem months'
      USING ERRCODE='22023';
  END IF;
  v_fingerprint:='month_override_set|'||p_month||'|'||p_category_id||'|'||p_amount::numeric(18,2)::text;
  LOCK TABLE public.transactions IN SHARE MODE;
  INSERT INTO public.budget_months(month_start) VALUES(v_month_start) ON CONFLICT(month_start) DO NOTHING;
  SELECT id INTO v_month_id FROM public.budget_months WHERE month_start=v_month_start FOR UPDATE;
  PERFORM 1 FROM public.budgets WHERE budget_month_id=v_month_id ORDER BY id FOR UPDATE;
  PERFORM 1 FROM public.categories WHERE id=p_category_id FOR SHARE;
  IF NOT EXISTS(SELECT 1 FROM public.categories WHERE id=p_category_id AND type='expense' AND is_active) THEN
    RAISE EXCEPTION 'Month overrides are available only for active expense categories' USING ERRCODE='23514';
  END IF;
  PERFORM 1 FROM public.budget_recurring_defaults WHERE category_id=p_category_id FOR SHARE;
  PERFORM 1 FROM public.budget_month_overrides
    WHERE budget_month_id=v_month_id AND category_id=p_category_id FOR UPDATE;

  SELECT * INTO v_existing FROM public.budget_operations WHERE request_key=p_request_key;
  IF FOUND THEN
    IF v_existing.request_fingerprint<>v_fingerprint
       OR NOT EXISTS(SELECT 1 FROM public.budget_operation_items
         WHERE operation_id=coalesce(v_existing.parent_operation_id,v_existing.id)
           AND item_kind='month_override') THEN
      RAISE EXCEPTION 'request_key was already used for a different month override request' USING ERRCODE='23505';
    END IF;
    RETURN public.get_funded_budget_month(p_month);
  END IF;

  SELECT EXISTS(SELECT 1 FROM public.budget_operations
    WHERE budget_month_id=v_month_id AND operation_type='month_initialization') INTO v_initialized;
  SELECT * INTO v_budget FROM public.budget_category_state
    WHERE budget_month_id=v_month_id AND category_id=p_category_id;
  SELECT amount INTO v_prior_override FROM public.budget_month_overrides
    WHERE budget_month_id=v_month_id AND category_id=p_category_id;
  SELECT coalesce(amount,0)::numeric(18,2),
    CASE WHEN amount IS NULL THEN 'none' ELSE 'recurring_default' END
  INTO v_fallback,v_fallback_source
  FROM (SELECT (SELECT amount FROM public.budget_recurring_defaults
                WHERE category_id=p_category_id) AS amount) recurring;

  IF v_budget.budget_id IS NULL AND NOT v_initialized THEN
    v_operation_id:=public.budget_create_action_root(v_month_id,p_request_key,v_fingerprint,
      'monthly_override_set',v_month_start,p_reason,NULL);
    INSERT INTO public.budget_month_overrides(budget_month_id,category_id,amount)
    VALUES(v_month_id,p_category_id,p_amount::numeric(18,2))
    ON CONFLICT(budget_month_id,category_id) DO UPDATE
    SET amount=EXCLUDED.amount,updated_at=timezone('utc'::text,now());
    INSERT INTO public.budget_operation_items(
      operation_id,item_kind,action_kind,budget_month_id,category_id,amount,
      base_before,base_after,fallback_base_snapshot,source_kind
    ) VALUES(v_operation_id,'month_override','set',v_month_id,p_category_id,p_amount,
      coalesce(v_prior_override,v_fallback),p_amount,v_fallback,v_fallback_source);
    RETURN public.get_funded_budget_month(p_month);
  END IF;

  IF v_budget.budget_id IS NULL THEN
    SELECT coalesce(unallocated,0)::numeric(18,2) INTO v_unallocated
    FROM public.budget_month_funding_state WHERE budget_month_id=v_month_id;
    IF p_amount>v_unallocated THEN
      RAISE EXCEPTION 'MONTH_OVERRIDE_INSUFFICIENT_FUNDS: required %, available %, shortfall %',
        p_amount::numeric(18,2),v_unallocated,(p_amount-v_unallocated)::numeric(18,2)
        USING ERRCODE='23514';
    END IF;
    v_operation_id:=public.budget_create_action_root(v_month_id,p_request_key,v_fingerprint,
      'monthly_override_set',v_month_start,p_reason,NULL);
    INSERT INTO public.budgets(category_id,month,amount,budget_month_id,starting_amount,
      starting_kind,created_by_operation_id)
    VALUES(p_category_id,p_month,p_amount,v_month_id,p_amount,'monthly_override',v_operation_id)
    RETURNING id INTO v_budget.budget_id;
    INSERT INTO public.budget_lifecycle_events(operation_id,budget_id,state)
    VALUES(v_operation_id,v_budget.budget_id,'active') RETURNING id INTO v_lifecycle_id;
    INSERT INTO public.budget_month_overrides(budget_month_id,category_id,amount)
    VALUES(v_month_id,p_category_id,p_amount);
    INSERT INTO public.budget_operation_items(
      operation_id,item_kind,action_kind,budget_month_id,category_id,destination_budget_id,
      amount,base_before,base_after,fallback_base_snapshot,source_kind,lifecycle_event_id
    ) VALUES(v_operation_id,'month_override','initialize',v_month_id,p_category_id,v_budget.budget_id,
      p_amount,v_fallback,p_amount,v_fallback,v_fallback_source,v_lifecycle_id);
    PERFORM public.budget_assert_reconciled(v_month_id);
    RETURN public.get_funded_budget_month(p_month);
  END IF;

  IF v_budget.lifecycle_state<>'active' THEN
    RAISE EXCEPTION 'Month override requires an active category budget' USING ERRCODE='23514';
  END IF;
  SELECT * INTO v_base FROM public.budget_category_composition WHERE budget_id=v_budget.budget_id;
  v_delta:=p_amount::numeric(18,2)-v_base.effective_base;
  SELECT coalesce(unallocated,0)::numeric(18,2) INTO v_unallocated
  FROM public.budget_month_funding_state WHERE budget_month_id=v_month_id;
  IF v_delta>0 AND v_delta>v_unallocated THEN
    RAISE EXCEPTION 'MONTH_OVERRIDE_INSUFFICIENT_FUNDS: required %, available %, shortfall %',
      v_delta,v_unallocated,(v_delta-v_unallocated)::numeric(18,2) USING ERRCODE='23514';
  END IF;
  IF v_delta<0 THEN
    IF EXISTS(SELECT 1 FROM public.budget_actual_transactions(NULL,NULL) WHERE movement_type='expense'
      AND category_id=p_category_id AND transaction_date>=v_month_start
      AND transaction_date<(v_month_start+interval '1 month')::date
      AND total_amount::text IN ('NaN','Infinity','-Infinity')) THEN
      RAISE EXCEPTION 'Month override actual spending contains a non-finite amount' USING ERRCODE='22003';
    END IF;
    SELECT coalesce(sum(total_amount),0) INTO v_raw_actual FROM public.budget_actual_transactions(NULL,NULL)
    WHERE movement_type='expense' AND category_id=p_category_id
      AND transaction_date>=v_month_start AND transaction_date<(v_month_start+interval '1 month')::date;
    IF v_raw_actual<>round(v_raw_actual,2) OR abs(v_raw_actual)>9999999999999999.99 THEN
      RAISE EXCEPTION 'Month override actual spending must fit finite NUMERIC(18,2) exactly' USING ERRCODE='22003';
    END IF;
    v_effective_actual:=greatest(v_raw_actual,0)::numeric(18,2);
    v_base_headroom:=greatest(v_base.effective_base-v_effective_actual,0)::numeric(18,2);
    v_total_headroom:=greatest(v_base.final_funded-v_effective_actual,0)::numeric(18,2);
    v_eligible_release:=least(v_base_headroom,v_total_headroom)::numeric(18,2);
    IF -v_delta>v_eligible_release THEN
      RAISE EXCEPTION 'MONTH_OVERRIDE_RELEASE_BLOCKED: requested release %, eligible release %, shortfall %',
        -v_delta,v_eligible_release,(-v_delta-v_eligible_release)::numeric(18,2) USING ERRCODE='23514';
    END IF;
  END IF;
  v_operation_id:=public.budget_create_action_root(v_month_id,p_request_key,v_fingerprint,
    'monthly_override_set',v_month_start,p_reason,NULL);
  IF v_delta<>0 THEN
    INSERT INTO public.budget_movements(operation_id,source_budget_id,destination_budget_id,amount)
    VALUES(v_operation_id,CASE WHEN v_delta<0 THEN v_budget.budget_id END,
      CASE WHEN v_delta>0 THEN v_budget.budget_id END,abs(v_delta)) RETURNING id INTO v_movement_id;
  END IF;
  INSERT INTO public.budget_month_overrides(budget_month_id,category_id,amount)
  VALUES(v_month_id,p_category_id,p_amount::numeric(18,2))
  ON CONFLICT(budget_month_id,category_id) DO UPDATE
  SET amount=EXCLUDED.amount,updated_at=timezone('utc'::text,now());
  INSERT INTO public.budget_operation_items(
    operation_id,item_kind,action_kind,budget_month_id,category_id,destination_budget_id,
    amount,base_before,base_after,fallback_base_snapshot,source_kind,movement_id
  ) VALUES(v_operation_id,'month_override','set',v_month_id,p_category_id,v_budget.budget_id,
    p_amount,v_base.effective_base,p_amount,v_base.fallback_base,v_base.fallback_source,v_movement_id)
  RETURNING id INTO v_item_id;
  PERFORM public.budget_assert_reconciled(v_month_id);
  RETURN public.get_funded_budget_month(p_month);
END;
$function$;

CREATE OR REPLACE FUNCTION public.remove_budget_month_override(p_month text, p_category_id bigint, p_request_key uuid, p_reason text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
DECLARE
  v_month_start DATE:=public.budget_month_start_from_key(p_month);
  v_current_start DATE:=date_trunc('month',timezone('Asia/Jerusalem',statement_timestamp()))::date;
  v_month_id BIGINT; v_override NUMERIC(18,2); v_budget public.budget_category_state%ROWTYPE;
  v_base public.budget_category_composition%ROWTYPE; v_existing public.budget_operations%ROWTYPE;
  v_fingerprint TEXT; v_operation_id BIGINT; v_movement_id BIGINT; v_lifecycle_id BIGINT;
  v_delta NUMERIC(18,2); v_unallocated NUMERIC(18,2); v_raw_actual NUMERIC;
  v_effective_actual NUMERIC(18,2):=0; v_eligible_release NUMERIC(18,2);
  v_fallback NUMERIC(18,2); v_fallback_source TEXT; v_new_final NUMERIC(18,2);
BEGIN
  IF p_request_key IS NULL OR p_category_id IS NULL THEN
    RAISE EXCEPTION 'month, category_id, and request_key are required' USING ERRCODE='22023';
  END IF;
  IF v_month_start<v_current_start THEN
    RAISE EXCEPTION 'HISTORICAL_MONTH_OVERRIDE_FORBIDDEN: month overrides are limited to current/future Asia/Jerusalem months'
      USING ERRCODE='22023';
  END IF;
  v_fingerprint:='month_override_remove|'||p_month||'|'||p_category_id;
  LOCK TABLE public.transactions IN SHARE MODE;
  INSERT INTO public.budget_months(month_start) VALUES(v_month_start) ON CONFLICT(month_start) DO NOTHING;
  SELECT id INTO v_month_id FROM public.budget_months WHERE month_start=v_month_start FOR UPDATE;
  PERFORM 1 FROM public.budgets WHERE budget_month_id=v_month_id ORDER BY id FOR UPDATE;
  PERFORM 1 FROM public.categories WHERE id=p_category_id FOR SHARE;
  IF NOT EXISTS(SELECT 1 FROM public.categories WHERE id=p_category_id AND type='expense') THEN
    RAISE EXCEPTION 'Month overrides are available only for expense categories' USING ERRCODE='23514';
  END IF;
  PERFORM 1 FROM public.budget_recurring_defaults WHERE category_id=p_category_id FOR SHARE;
  PERFORM 1 FROM public.budget_month_overrides
    WHERE budget_month_id=v_month_id AND category_id=p_category_id FOR UPDATE;

  SELECT * INTO v_existing FROM public.budget_operations WHERE request_key=p_request_key;
  IF FOUND THEN
    IF v_existing.request_fingerprint<>v_fingerprint
       OR NOT EXISTS(SELECT 1 FROM public.budget_operation_items
         WHERE operation_id=coalesce(v_existing.parent_operation_id,v_existing.id)
           AND item_kind='month_override' AND action_kind='remove') THEN
      RAISE EXCEPTION 'request_key was already used for a different month override request' USING ERRCODE='23505';
    END IF;
    RETURN public.get_funded_budget_month(p_month);
  END IF;

  SELECT amount INTO v_override FROM public.budget_month_overrides
    WHERE budget_month_id=v_month_id AND category_id=p_category_id;
  SELECT * INTO v_budget FROM public.budget_category_state
    WHERE budget_month_id=v_month_id AND category_id=p_category_id;
  SELECT coalesce(amount,0)::numeric(18,2),
    CASE WHEN amount IS NULL THEN 'none' ELSE 'recurring_default' END
  INTO v_fallback,v_fallback_source
  FROM (SELECT (SELECT amount FROM public.budget_recurring_defaults
                WHERE category_id=p_category_id) AS amount) recurring;

  IF v_budget.budget_id IS NULL THEN
    v_operation_id:=public.budget_create_action_root(v_month_id,p_request_key,v_fingerprint,
      'monthly_override_remove',v_month_start,p_reason,NULL);
    IF v_override IS NOT NULL THEN
      DELETE FROM public.budget_month_overrides
      WHERE budget_month_id=v_month_id AND category_id=p_category_id;
    END IF;
    INSERT INTO public.budget_operation_items(
      operation_id,item_kind,action_kind,budget_month_id,category_id,
      base_before,base_after,fallback_base_snapshot,source_kind
    ) VALUES(v_operation_id,'month_override','remove',v_month_id,p_category_id,
      coalesce(v_override,v_fallback),v_fallback,v_fallback,v_fallback_source);
    RETURN public.get_funded_budget_month(p_month);
  END IF;
  SELECT * INTO v_base FROM public.budget_category_composition WHERE budget_id=v_budget.budget_id;
  IF v_override IS NULL THEN
    v_operation_id:=public.budget_create_action_root(v_month_id,p_request_key,v_fingerprint,
      'monthly_override_remove',v_month_start,p_reason,NULL);
    INSERT INTO public.budget_operation_items(
      operation_id,item_kind,action_kind,budget_month_id,category_id,destination_budget_id,
      base_before,base_after,fallback_base_snapshot,source_kind
    ) VALUES(v_operation_id,'month_override','remove',v_month_id,p_category_id,v_budget.budget_id,
      v_base.effective_base,v_base.effective_base,v_base.fallback_base,v_base.fallback_source);
    RETURN public.get_funded_budget_month(p_month);
  END IF;
  IF v_budget.lifecycle_state<>'active' THEN
    RAISE EXCEPTION 'Month override removal requires an active category budget' USING ERRCODE='23514';
  END IF;
  v_delta:=v_base.fallback_base-v_base.effective_base;
  IF EXISTS(SELECT 1 FROM public.budget_actual_transactions(NULL,NULL) WHERE movement_type='expense'
    AND category_id=p_category_id AND transaction_date>=v_month_start
    AND transaction_date<(v_month_start+interval '1 month')::date
    AND total_amount::text IN ('NaN','Infinity','-Infinity')) THEN
    RAISE EXCEPTION 'Month override actual spending contains a non-finite amount' USING ERRCODE='22003';
  END IF;
  SELECT coalesce(sum(total_amount),0) INTO v_raw_actual FROM public.budget_actual_transactions(NULL,NULL)
  WHERE movement_type='expense' AND category_id=p_category_id
    AND transaction_date>=v_month_start AND transaction_date<(v_month_start+interval '1 month')::date;
  IF v_raw_actual<>round(v_raw_actual,2) OR abs(v_raw_actual)>9999999999999999.99 THEN
    RAISE EXCEPTION 'Month override actual spending must fit finite NUMERIC(18,2) exactly' USING ERRCODE='22003';
  END IF;
  v_effective_actual:=greatest(v_raw_actual,0)::numeric(18,2);
  SELECT coalesce(unallocated,0)::numeric(18,2) INTO v_unallocated
  FROM public.budget_month_funding_state WHERE budget_month_id=v_month_id;
  IF v_delta>0 AND v_delta>v_unallocated THEN
    RAISE EXCEPTION 'MONTH_OVERRIDE_INSUFFICIENT_FUNDS: required %, available %, shortfall %',
      v_delta,v_unallocated,(v_delta-v_unallocated)::numeric(18,2) USING ERRCODE='23514';
  END IF;
  IF v_delta<0 THEN
    v_eligible_release:=least(greatest(v_base.effective_base-v_effective_actual,0),
      greatest(v_base.final_funded-v_effective_actual,0))::numeric(18,2);
    IF -v_delta>v_eligible_release THEN
      RAISE EXCEPTION 'MONTH_OVERRIDE_RELEASE_BLOCKED: requested release %, eligible release %, shortfall %',
        -v_delta,v_eligible_release,(-v_delta-v_eligible_release)::numeric(18,2) USING ERRCODE='23514';
    END IF;
  END IF;
  v_operation_id:=public.budget_create_action_root(v_month_id,p_request_key,v_fingerprint,
    'monthly_override_remove',v_month_start,p_reason,NULL);
  IF v_delta<>0 THEN
    INSERT INTO public.budget_movements(operation_id,source_budget_id,destination_budget_id,amount)
    VALUES(v_operation_id,CASE WHEN v_delta<0 THEN v_budget.budget_id END,
      CASE WHEN v_delta>0 THEN v_budget.budget_id END,abs(v_delta)) RETURNING id INTO v_movement_id;
  END IF;
  DELETE FROM public.budget_month_overrides
  WHERE budget_month_id=v_month_id AND category_id=p_category_id;
  INSERT INTO public.budget_operation_items(
    operation_id,item_kind,action_kind,budget_month_id,category_id,destination_budget_id,
    base_before,base_after,fallback_base_snapshot,source_kind,movement_id
  ) VALUES(v_operation_id,'month_override','remove',v_month_id,p_category_id,v_budget.budget_id,
    v_base.effective_base,v_base.fallback_base,v_base.fallback_base,v_base.fallback_source,v_movement_id);
  v_new_final:=v_base.final_funded+v_delta;
  IF v_base.fallback_base=0 AND v_new_final=0 AND v_effective_actual=0
     AND v_base.incoming_carryover=0 AND v_base.outgoing_carryover=0
     AND v_base.incoming_reallocation_resolution=0 AND v_base.outgoing_reallocation=0
     AND v_base.unbudgeted_resolution_adjustment=0
     AND v_base.unused_disposition_adjustment=0 AND v_base.other_adjustments=0 THEN
    INSERT INTO public.budget_lifecycle_events(operation_id,budget_id,state,actual_spent_snapshot)
    VALUES(v_operation_id,v_budget.budget_id,'inactive',0) RETURNING id INTO v_lifecycle_id;
  END IF;
  PERFORM public.budget_assert_reconciled(v_month_id);
  RETURN public.get_funded_budget_month(p_month);
END;
$function$;

CREATE OR REPLACE FUNCTION public.budget_month_disposition_candidate_rows(p_source_month text)
 RETURNS TABLE(category_id bigint, category_name text, category_icon text, source_budget_id bigint, policy text, source_final_funded numeric, source_raw_actual numeric, source_effective_actual numeric, eligible_amount numeric, status text, blocked_reason text)
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
DECLARE
  v_source_start DATE:=public.budget_month_start_from_key(p_source_month);
  v_destination_start DATE:=(v_source_start+interval '1 month')::date; v_source_id BIGINT;
BEGIN
  SELECT id INTO v_source_id FROM public.budget_months WHERE month_start=v_source_start;
  IF EXISTS(SELECT 1 FROM public.budget_actual_transactions(NULL,NULL) WHERE movement_type='expense'
    AND transaction_date>=v_source_start AND transaction_date<v_destination_start
    AND total_amount::text IN ('NaN','Infinity','-Infinity')) THEN
    RAISE EXCEPTION 'Month disposition actual spending contains a non-finite amount' USING ERRCODE='22003';
  END IF;
  IF EXISTS(SELECT 1 FROM public.budget_actual_transactions(NULL,NULL) t WHERE t.movement_type='expense'
    AND t.transaction_date>=v_source_start AND t.transaction_date<v_destination_start
    GROUP BY t.category_id HAVING sum(t.total_amount)<>round(sum(t.total_amount),2)
      OR abs(sum(t.total_amount))>9999999999999999.99) THEN
    RAISE EXCEPTION 'Month disposition actual spending must fit finite NUMERIC(18,2) exactly' USING ERRCODE='22003';
  END IF;
  RETURN QUERY
  WITH actuals AS(
    SELECT t.category_id,sum(t.total_amount)::numeric(18,2) actual
    FROM public.budget_actual_transactions(NULL,NULL) t WHERE t.movement_type='expense'
      AND t.transaction_date>=v_source_start AND t.transaction_date<v_destination_start GROUP BY t.category_id
  ),base AS(
    SELECT cs.budget_id,cs.category_id,cs.category_name,cs.category_icon,cs.category_type,
      c.is_active,cs.lifecycle_state,cs.final_funded::numeric(18,2) final_funded,
      coalesce(a.actual,0)::numeric(18,2) raw_actual,
      greatest(coalesce(a.actual,0),0)::numeric(18,2) effective_actual,
      greatest(cs.final_funded-greatest(coalesce(a.actual,0),0),0)::numeric(18,2) unused,
      p.policy,
      EXISTS(SELECT 1 FROM public.budget_operation_items original
        WHERE original.item_kind='unused_disposition' AND original.source_budget_id=cs.budget_id
          AND original.action_kind='apply' AND original.reversed_item_id IS NULL
          AND NOT EXISTS(SELECT 1 FROM public.budget_operation_items correction
            WHERE correction.item_kind='unused_disposition' AND correction.reversed_item_id=original.id)) disposed,
      carry.status carry_status,carry.blocked_reason carry_blocked
    FROM public.budget_category_state cs JOIN public.categories c ON c.id=cs.category_id
    LEFT JOIN actuals a ON a.category_id=cs.category_id
    LEFT JOIN public.budget_unused_balance_policies p ON p.category_id=cs.category_id
    LEFT JOIN public.budget_carryover_candidate_rows(to_char(v_destination_start,'YYYY-MM')) carry
      ON p.policy='carry_forward' AND carry.category_id=cs.category_id
    WHERE cs.budget_month_id=v_source_id
  )
  SELECT b.category_id,b.category_name,b.category_icon,b.budget_id,b.policy,b.final_funded,
    b.raw_actual,b.effective_actual,b.unused,
    CASE WHEN b.disposed OR (b.policy='carry_forward' AND b.carry_status='already_applied') THEN 'already_applied'
      WHEN b.category_type<>'expense' OR NOT b.is_active OR b.lifecycle_state<>'active' THEN 'blocked'
      WHEN b.unused<=0 THEN 'ineligible' WHEN b.policy IS NULL THEN 'blocked'
      WHEN b.policy='carry_forward' AND b.carry_status IS DISTINCT FROM 'ready' THEN 'blocked'
      ELSE 'ready' END,
    CASE WHEN b.disposed OR (b.policy='carry_forward' AND b.carry_status='already_applied') THEN NULL
      WHEN b.category_type<>'expense' THEN 'CATEGORY_NOT_EXPENSE'
      WHEN NOT b.is_active THEN 'CATEGORY_INACTIVE'
      WHEN b.lifecycle_state<>'active' THEN 'SOURCE_BUDGET_INACTIVE'
      WHEN b.unused<=0 THEN NULL WHEN b.policy IS NULL THEN 'POLICY_UNCONFIGURED'
      WHEN b.policy='carry_forward' AND b.carry_status IS DISTINCT FROM 'ready'
        THEN coalesce(b.carry_blocked,'CARRY_FORWARD_NOT_READY') ELSE NULL END
  FROM base b ORDER BY b.category_name,b.category_id;
END;
$function$;

CREATE OR REPLACE FUNCTION public.get_budget_month_disposition_preview(p_source_month text)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
DECLARE
  v_source_start DATE := public.budget_month_start_from_key(p_source_month);
  v_destination_start DATE := (v_source_start + interval '1 month')::date;
  v_current_start DATE := date_trunc('month',timezone('Asia/Jerusalem',statement_timestamp()))::date;
  v_source_id BIGINT;
  v_destination_id BIGINT;
  v_rows JSONB := '[]'::jsonb;
  v_material TEXT := '';
  v_deficits JSONB := '[]'::jsonb;
  v_unbudgeted JSONB := '[]'::jsonb;
  v_carry NUMERIC(18,2) := 0;
  v_return NUMERIC(18,2) := 0;
  v_savings NUMERIC(18,2) := 0;
  v_destination_unallocated NUMERIC(18,2) := 0;
  v_destination_available NUMERIC(18,2) := 0;
  v_source_available NUMERIC(18,2) := 0;
  v_source_unallocated NUMERIC(18,2) := 0;
  v_savings_balance NUMERIC(18,2) := 0;
  v_fingerprint TEXT;
  v_timing BOOLEAN;
BEGIN
  v_timing := v_destination_start=v_current_start;
  SELECT id INTO v_source_id FROM public.budget_months WHERE month_start=v_source_start;
  SELECT id INTO v_destination_id FROM public.budget_months WHERE month_start=v_destination_start;

  WITH rows AS (SELECT * FROM public.budget_month_disposition_candidate_rows(p_source_month))
  SELECT coalesce(jsonb_agg(jsonb_build_object(
      'category_id',category_id,
      'category',jsonb_build_object('name',category_name,'icon',category_icon,'type','expense'),
      'source_budget_id',source_budget_id,'policy',policy,
      'source_final_funded',source_final_funded::text,
      'source_raw_actual',source_raw_actual::text,
      'source_effective_actual',source_effective_actual::text,
      'eligible_unused',eligible_amount::text,
      'status',status,'blocked_reason',blocked_reason
    ) ORDER BY category_name,category_id),'[]'::jsonb),
    coalesce(string_agg(category_id||'|'||source_budget_id||'|'||coalesce(policy,'')||'|'
      ||source_final_funded::text||'|'||source_raw_actual::text||'|'
      ||source_effective_actual::text||'|'||eligible_amount::text||'|'
      ||status||'|'||coalesce(blocked_reason,''),';' ORDER BY category_id),''),
    coalesce(sum(eligible_amount) FILTER (WHERE status='ready' AND policy='carry_forward'),0),
    coalesce(sum(eligible_amount) FILTER (WHERE status='ready' AND policy='return_to_unallocated'),0),
    coalesce(sum(eligible_amount) FILTER (WHERE status='ready' AND policy='savings'),0)
  INTO v_rows,v_material,v_carry,v_return,v_savings FROM rows;

  WITH actuals AS (
    SELECT t.category_id,sum(t.total_amount)::numeric(18,2) actual
    FROM public.budget_actual_transactions(NULL,NULL) t
    WHERE t.movement_type='expense' AND t.transaction_date>=v_source_start
      AND t.transaction_date<v_destination_start
    GROUP BY t.category_id
  )
  SELECT coalesce(jsonb_agg(jsonb_build_object(
    'category_id',cs.category_id,'category_name',cs.category_name,
    'funded',cs.final_funded::numeric(18,2)::text,'actual',a.actual::text,
    'deficit',(a.actual-cs.final_funded)::numeric(18,2)::text
  ) ORDER BY cs.category_name,cs.category_id),'[]'::jsonb)
  INTO v_deficits
  FROM actuals a JOIN public.budget_category_state cs
    ON cs.budget_month_id=v_source_id AND cs.category_id=a.category_id
  WHERE cs.lifecycle_state='active' AND a.actual>cs.final_funded;

  WITH actuals AS (
    SELECT t.category_id,sum(t.total_amount)::numeric(18,2) actual
    FROM public.budget_actual_transactions(NULL,NULL) t
    WHERE t.movement_type='expense' AND t.transaction_date>=v_source_start
      AND t.transaction_date<v_destination_start
    GROUP BY t.category_id
  )
  SELECT coalesce(jsonb_agg(jsonb_build_object(
    'category_id',a.category_id,'actual',a.actual::text
  ) ORDER BY a.category_id NULLS FIRST),'[]'::jsonb)
  INTO v_unbudgeted
  FROM actuals a
  WHERE a.actual>0 AND NOT EXISTS (
    SELECT 1 FROM public.budget_category_state cs
    WHERE cs.budget_month_id=v_source_id AND cs.category_id IS NOT DISTINCT FROM a.category_id
      AND cs.lifecycle_state='active'
  );

  SELECT coalesce(available,0)::numeric(18,2),coalesce(unallocated,0)::numeric(18,2)
  INTO v_destination_available,v_destination_unallocated
  FROM public.budget_month_funding_state WHERE budget_month_id=v_destination_id;
  IF NOT FOUND THEN v_destination_available:=0; v_destination_unallocated:=0; END IF;
  SELECT coalesce(available,0)::numeric(18,2),coalesce(unallocated,0)::numeric(18,2)
  INTO v_source_available,v_source_unallocated
  FROM public.budget_month_funding_state WHERE budget_month_id=v_source_id;
  IF NOT FOUND THEN v_source_available:=0; v_source_unallocated:=0; END IF;
  SELECT balance INTO v_savings_balance FROM public.budget_savings_state;

  v_fingerprint:=md5('month_disposition|'||p_source_month||'|'
    ||to_char(v_destination_start,'YYYY-MM')||'|'||v_material||'|deficits:'
    ||v_deficits::text||'|unbudgeted:'||v_unbudgeted::text
    ||'|source-funding:'||v_source_available::text||'|'||v_source_unallocated::text
    ||'|destination-funding:'||v_destination_available::text||'|'||v_destination_unallocated::text
    ||'|savings:'||v_savings_balance::text);

  RETURN jsonb_build_object(
    'eligible',v_timing AND v_source_id IS NOT NULL,
    'reason',CASE WHEN NOT v_timing THEN 'IMMEDIATELY_COMPLETED_MONTH_ONLY'
                  WHEN v_source_id IS NULL THEN 'SOURCE_MONTH_MISSING' ELSE NULL END,
    'source_month',p_source_month,
    'destination_month',to_char(v_destination_start,'YYYY-MM'),
    'fingerprint',v_fingerprint,
    'categories',v_rows,
    'carry_forward_total',v_carry::text,
    'return_to_unallocated_total',v_return::text,
    'savings_total',v_savings::text,
    'source_available',v_source_available::text,
    'source_unallocated',v_source_unallocated::text,
    'destination_unallocated_before',v_destination_unallocated::text,
    'destination_unallocated_after',(v_destination_unallocated+v_return)::numeric(18,2)::text,
    'savings_balance_before',v_savings_balance::text,
    'savings_balance_after',(v_savings_balance+v_savings)::numeric(18,2)::text,
    'deficit_blockers',v_deficits,
    'unbudgeted_expense_blockers',v_unbudgeted,
    'can_apply',v_timing AND v_source_id IS NOT NULL
      AND jsonb_array_length(v_deficits)=0 AND jsonb_array_length(v_unbudgeted)=0
      AND NOT EXISTS (
        SELECT 1 FROM public.budget_month_disposition_candidate_rows(p_source_month)
        WHERE status='blocked'
      )
      AND EXISTS (
        SELECT 1 FROM public.budget_month_disposition_candidate_rows(p_source_month)
        WHERE status='ready'
      )
  );
END; $function$;

CREATE OR REPLACE FUNCTION public.get_budget_reallocation_preview(p_month text, p_source_kind text, p_source_category_id bigint, p_destination_kind text, p_destination_category_id bigint, p_amount numeric)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
DECLARE
  v_lifecycle TEXT:=public.budget_action_month_lifecycle(p_month);
  v_month_start DATE:=public.budget_month_start_from_key(p_month);
  v_month_id BIGINT;
  v_source_budget_id BIGINT; v_source_final NUMERIC(18,2);
  v_source_lifecycle TEXT; v_source_type TEXT; v_source_active BOOLEAN;
  v_destination_budget_id BIGINT; v_destination_final NUMERIC(18,2);
  v_destination_lifecycle TEXT; v_destination_type TEXT; v_destination_active BOOLEAN;
  v_source_raw NUMERIC(18,2):=0; v_source_effective NUMERIC(18,2):=0;
  v_capacity NUMERIC(18,2):=0; v_unallocated NUMERIC(18,2):=0;
  v_destination_raw NUMERIC(18,2):=0; v_destination_after NUMERIC(18,2);
  v_reason TEXT; v_material TEXT; v_fingerprint TEXT;
BEGIN
  IF p_amount IS NULL OR p_amount::text IN ('NaN','Infinity','-Infinity')
     OR p_amount<=0 OR p_amount<>round(p_amount,2) OR p_amount>9999999999999999.99 THEN
    RAISE EXCEPTION 'Reallocation amount must be a positive two-decimal value' USING ERRCODE='22023';
  END IF;
  IF p_source_kind IS NULL OR p_source_kind NOT IN ('category','unallocated')
     OR p_destination_kind IS NULL OR p_destination_kind NOT IN ('category','unallocated')
     OR (p_source_kind='unallocated' AND p_destination_kind='unallocated')
     OR (p_source_kind='category')<>(p_source_category_id IS NOT NULL)
     OR (p_destination_kind='category')<>(p_destination_category_id IS NOT NULL)
     OR (p_source_category_id IS NOT NULL AND p_source_category_id=p_destination_category_id) THEN
    RAISE EXCEPTION 'Invalid reallocation endpoints' USING ERRCODE='22023';
  END IF;
  SELECT id INTO v_month_id FROM public.budget_months WHERE month_start=v_month_start;
  SELECT coalesce(unallocated,0)::numeric(18,2) INTO v_unallocated
  FROM public.budget_month_funding_state WHERE budget_month_id=v_month_id;
  IF NOT FOUND THEN v_unallocated:=0; END IF;

  IF p_source_kind='category' THEN
    SELECT cs.budget_id,cs.final_funded,cs.lifecycle_state,cs.category_type,c.is_active
    INTO v_source_budget_id,v_source_final,v_source_lifecycle,v_source_type,v_source_active
    FROM public.budget_category_state cs
    JOIN public.categories c ON c.id=cs.category_id
    WHERE cs.budget_month_id=v_month_id AND cs.category_id=p_source_category_id;
    IF NOT FOUND OR v_source_lifecycle<>'active' OR v_source_type<>'expense'
       OR NOT v_source_active THEN
      v_reason:='SOURCE_BUDGET_NOT_ACTIVE';
    ELSE
      SELECT coalesce(sum(total_amount),0)::numeric(18,2) INTO v_source_raw FROM public.budget_actual_transactions(NULL,NULL)
      WHERE movement_type='expense' AND category_id=p_source_category_id
        AND transaction_date>=v_month_start AND transaction_date<(v_month_start+interval '1 month')::date;
      v_source_effective:=greatest(v_source_raw,0);
      v_capacity:=greatest(v_source_final-v_source_effective,0);
    END IF;
  ELSE v_capacity:=v_unallocated;
  END IF;

  IF p_destination_kind='category' THEN
    SELECT cs.budget_id,cs.final_funded,cs.lifecycle_state,cs.category_type,c.is_active
    INTO v_destination_budget_id,v_destination_final,v_destination_lifecycle,v_destination_type,v_destination_active
    FROM public.budget_category_state cs
    JOIN public.categories c ON c.id=cs.category_id
    WHERE cs.budget_month_id=v_month_id AND cs.category_id=p_destination_category_id;
    IF NOT FOUND OR v_destination_lifecycle<>'active' OR v_destination_type<>'expense'
       OR NOT v_destination_active THEN
      v_reason:=coalesce(v_reason,'DESTINATION_BUDGET_NOT_ACTIVE');
    ELSE
      SELECT coalesce(sum(total_amount),0)::numeric(18,2) INTO v_destination_raw FROM public.budget_actual_transactions(NULL,NULL)
      WHERE movement_type='expense' AND category_id=p_destination_category_id
        AND transaction_date>=v_month_start AND transaction_date<(v_month_start+interval '1 month')::date;
      v_destination_after:=v_destination_final+p_amount;
    END IF;
  END IF;
  IF v_lifecycle='closed' THEN v_reason:='BUDGET_MONTH_ALREADY_CLOSED';
  ELSIF v_lifecycle='immediately_completed_unclosed' THEN v_reason:='COMPLETED_MONTH_REALLOCATION_FORBIDDEN';
  ELSIF v_lifecycle<>'current' THEN v_reason:='BUDGET_ACTION_MONTH_FORBIDDEN';
  ELSIF p_amount>v_capacity THEN v_reason:=coalesce(v_reason,'REALLOCATION_SOURCE_INSUFFICIENT');
  END IF;
  v_material:=concat_ws('|','reallocation',p_month,v_lifecycle,p_source_kind,
    coalesce(p_source_category_id::text,''),p_destination_kind,
    coalesce(p_destination_category_id::text,''),p_amount::numeric(18,2)::text,
    coalesce(v_source_budget_id::text,''),coalesce(v_source_final::text,''),
    v_source_raw::text,v_source_effective::text,v_capacity::text,
    coalesce(v_destination_budget_id::text,''),coalesce(v_destination_final::text,''),
    v_destination_raw::text,v_unallocated::text,coalesce(v_reason,''));
  v_fingerprint:=md5(v_material);
  RETURN jsonb_build_object(
    'month',p_month,'lifecycle',v_lifecycle,'source_kind',p_source_kind,
    'source_category_id',p_source_category_id,'source_budget_id',v_source_budget_id,
    'source_funded',coalesce(v_source_final,0)::numeric(18,2)::text,
    'source_raw_actual',v_source_raw::text,'source_effective_actual',v_source_effective::text,
    'source_capacity',v_capacity::text,'destination_kind',p_destination_kind,
    'destination_category_id',p_destination_category_id,'destination_budget_id',v_destination_budget_id,
    'destination_before',coalesce(v_destination_final,0)::numeric(18,2)::text,
    'destination_after',coalesce(v_destination_after,0)::numeric(18,2)::text,
    'destination_raw_actual',v_destination_raw::text,'unallocated_before',v_unallocated::text,
    'unallocated_after',(v_unallocated
      +CASE WHEN p_destination_kind='unallocated' THEN p_amount ELSE 0 END
      -CASE WHEN p_source_kind='unallocated' THEN p_amount ELSE 0 END)::numeric(18,2)::text,
    'requested_amount',p_amount::numeric(18,2)::text,'fingerprint',v_fingerprint,
    'can_apply',v_reason IS NULL,'reason',v_reason
  );
END; $function$;

CREATE OR REPLACE FUNCTION public.get_budget_deficit_resolution_preview(p_month text, p_destination_category_id bigint, p_legs jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
DECLARE
  v_lifecycle TEXT:=public.budget_action_month_lifecycle(p_month);
  v_month_start DATE:=public.budget_month_start_from_key(p_month); v_month_id BIGINT;
  v_destination RECORD; v_raw NUMERIC(18,2):=0; v_deficit NUMERIC(18,2):=0;
  v_unallocated NUMERIC(18,2):=0; v_savings NUMERIC(18,2):=0;
  v_selected JSONB:='[]'::jsonb; v_sources JSONB:='[]'::jsonb;
  v_total NUMERIC(18,2):=0; v_reason TEXT; v_material TEXT:=''; v_seen TEXT[]:='{}';
  item JSONB; v_kind TEXT; v_amount NUMERIC(18,2); v_key TEXT;
  v_source RECORD;
BEGIN
  IF p_legs IS NULL OR jsonb_typeof(p_legs)<>'array' OR jsonb_array_length(p_legs)=0 THEN
    RAISE EXCEPTION 'At least one deficit funding leg is required' USING ERRCODE='22023';
  END IF;
  SELECT id INTO v_month_id FROM public.budget_months WHERE month_start=v_month_start;
  SELECT cs.*,c.is_active INTO v_destination FROM public.budget_category_state cs
  JOIN public.categories c ON c.id=cs.category_id
  WHERE cs.budget_month_id=v_month_id AND cs.category_id=p_destination_category_id;
  IF NOT FOUND THEN v_reason:='NO_BUDGET_DESTINATION';
  ELSIF v_destination.lifecycle_state<>'active' OR v_destination.category_type<>'expense'
        OR NOT v_destination.is_active THEN v_reason:='DESTINATION_BUDGET_NOT_ACTIVE';
  ELSE
    SELECT coalesce(sum(total_amount),0)::numeric(18,2) INTO v_raw FROM public.budget_actual_transactions(NULL,NULL)
    WHERE movement_type='expense' AND category_id=p_destination_category_id
      AND transaction_date>=v_month_start AND transaction_date<(v_month_start+interval '1 month')::date;
    v_deficit:=greatest(v_raw-v_destination.final_funded,0);
    IF v_deficit<=0 THEN v_reason:='NO_ACTIVE_DEFICIT'; END IF;
  END IF;
  SELECT capacity INTO v_unallocated FROM public.budget_funding_source_rows(p_month,p_destination_category_id)
  WHERE source_kind='unallocated';
  SELECT capacity INTO v_savings FROM public.budget_funding_source_rows(p_month,p_destination_category_id)
  WHERE source_kind='savings';
  SELECT coalesce(jsonb_agg(jsonb_build_object(
    'category_id',s.category_id,'budget_id',s.budget_id,'category_name',s.category_name,
    'final_funded',s.final_funded::text,'raw_actual',s.raw_actual::text,
    'effective_actual',s.effective_actual::text,'capacity',s.capacity::text
  ) ORDER BY s.category_name,s.category_id),'[]'::jsonb) INTO v_sources
  FROM public.budget_funding_source_rows(p_month,p_destination_category_id) s
  WHERE s.source_kind='category' AND s.capacity>0;

  FOR item IN SELECT value FROM jsonb_array_elements(p_legs) LOOP
    v_kind:=item->>'source_kind';
    IF jsonb_typeof(item) IS DISTINCT FROM 'object'
       OR v_kind IS NULL OR v_kind NOT IN ('category','unallocated','savings')
       OR jsonb_typeof(item->'amount') IS DISTINCT FROM 'string'
       OR (item->>'amount')!~'^(0|[1-9][0-9]*)(\.[0-9]{1,2})?$' THEN
      RAISE EXCEPTION 'Deficit funding leg has an invalid source or money format' USING ERRCODE='22023';
    END IF;
    v_amount:=(item->>'amount')::numeric;
    IF v_amount<=0 OR v_amount>9999999999999999.99 THEN
      RAISE EXCEPTION 'Deficit funding leg amount must be positive' USING ERRCODE='22023';
    END IF;
    v_key:=v_kind||':'||coalesce(item->>'category_id','');
    IF v_key=ANY(v_seen) THEN RAISE EXCEPTION 'Duplicate deficit funding source' USING ERRCODE='22023'; END IF;
    v_seen:=array_append(v_seen,v_key);
    SELECT * INTO v_source FROM public.budget_funding_source_rows(p_month,p_destination_category_id) s
    WHERE s.source_kind=v_kind
      AND (v_kind<>'category' OR s.category_id=NULLIF(item->>'category_id','')::bigint);
    IF NOT FOUND THEN
      v_reason:=coalesce(v_reason,'SOURCE_BUDGET_NOT_ACTIVE');
      SELECT NULL::text source_kind,NULL::bigint category_id,NULL::bigint budget_id,
        NULL::text category_name,NULL::numeric final_funded,NULL::numeric raw_actual,
        NULL::numeric effective_actual,0::numeric capacity INTO v_source;
    END IF;
    IF v_amount>v_source.capacity THEN v_reason:=coalesce(v_reason,
      CASE WHEN v_kind='savings' THEN 'SAVINGS_INSUFFICIENT' ELSE 'DEFICIT_SOURCE_INSUFFICIENT' END);
    END IF;
    v_total:=v_total+v_amount;
    v_selected:=v_selected||jsonb_build_array(jsonb_build_object(
      'source_kind',v_kind,'category_id',CASE WHEN v_kind='category' THEN v_source.category_id END,
      'source_budget_id',CASE WHEN v_kind='category' THEN v_source.budget_id END,
      'amount',v_amount::numeric(18,2)::text,
      'source_final_funded',CASE WHEN v_kind='category' THEN v_source.final_funded::text END,
      'source_raw_actual',CASE WHEN v_kind='category' THEN v_source.raw_actual::text END,
      'source_effective_actual',CASE WHEN v_kind='category' THEN v_source.effective_actual::text END,
      'source_capacity',v_source.capacity::numeric(18,2)::text));
    v_material:=v_material||'|'||v_key||'|'||v_amount::numeric(18,2)::text||'|'||v_source.capacity::text
      ||'|'||coalesce(v_source.budget_id::text,'')||'|'||coalesce(v_source.final_funded::text,'')
      ||'|'||coalesce(v_source.raw_actual::text,'')||'|'||coalesce(v_source.effective_actual::text,'');
  END LOOP;
  IF v_lifecycle='closed' THEN v_reason:='BUDGET_MONTH_ALREADY_CLOSED';
  ELSIF v_lifecycle NOT IN ('current','immediately_completed_unclosed') THEN v_reason:='BUDGET_ACTION_MONTH_FORBIDDEN';
  ELSIF v_total>v_deficit THEN v_reason:=coalesce(v_reason,'DEFICIT_RESOLUTION_EXCEEDS_DEFICIT');
  END IF;
  RETURN jsonb_build_object(
    'month',p_month,'lifecycle',v_lifecycle,'destination_category_id',p_destination_category_id,
    'destination_budget_id',v_destination.budget_id,
    'current_funded',coalesce(v_destination.final_funded,0)::numeric(18,2)::text,
    'actual',v_raw::text,'deficit',v_deficit::text,'unallocated_capacity',v_unallocated::text,
    'savings_balance',v_savings::text,'eligible_source_categories',v_sources,
    'selected_legs',v_selected,'requested_resolution',v_total::numeric(18,2)::text,
    'resulting_funded',(coalesce(v_destination.final_funded,0)+v_total)::numeric(18,2)::text,
    'remaining_deficit',greatest(v_deficit-v_total,0)::numeric(18,2)::text,
    'fingerprint',md5(concat_ws('|','deficit',p_month,v_lifecycle,p_destination_category_id,
      coalesce(v_destination.budget_id::text,''),coalesce(v_destination.final_funded::text,''),
      v_raw::text,v_deficit::text,v_unallocated::text,v_savings::text,v_material,coalesce(v_reason,''))),
    'can_apply',v_reason IS NULL,'reason',v_reason
  );
END; $function$;

CREATE OR REPLACE FUNCTION public.reverse_budget_funding_action(p_action_id bigint, p_request_key uuid, p_reason text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
DECLARE
  v_original public.budget_operation_items%ROWTYPE; v_original_operation public.budget_operations%ROWTYPE;
  v_existing public.budget_operations%ROWTYPE; v_month public.budget_months%ROWTYPE;
  v_operation_id BIGINT; v_action_id BIGINT; v_fingerprint TEXT:='funding_action_reverse|'||coalesce(p_action_id::text,'');
  v_required_unallocated NUMERIC(18,2):=0; v_unallocated NUMERIC(18,2):=0;
  v_savings_total NUMERIC(18,2):=0; v_original_funding public.budget_funding_entries%ROWTYPE;
  v_destination_release NUMERIC(18,2):=0; v_destination_raw NUMERIC(18,2):=0;
  v_destination_effective NUMERIC(18,2):=0; v_destination_final NUMERIC(18,2):=0;
  v_movement_id BIGINT; v_savings_entry_id BIGINT; original_leg RECORD;
BEGIN
  IF p_action_id IS NULL OR p_request_key IS NULL THEN
    RAISE EXCEPTION 'action_id and request_key are required' USING ERRCODE='22023';
  END IF;
  SELECT * INTO v_original FROM public.budget_operation_items
  WHERE id=p_action_id AND item_kind IN('reallocation','deficit_resolution') AND reversed_item_id IS NULL;
  IF NOT FOUND THEN RAISE EXCEPTION 'Funding action does not exist' USING ERRCODE='P0002'; END IF;
  SELECT * INTO v_original_operation FROM public.budget_operations WHERE id=v_original.operation_id;
  SELECT * INTO v_existing FROM public.budget_operations WHERE request_key=p_request_key;
  IF FOUND THEN
    IF v_existing.operation_type<>'funding_action_reversal' OR v_existing.request_fingerprint<>v_fingerprint THEN
      RAISE EXCEPTION 'request_key was already used for a different budget operation' USING ERRCODE='23505';
    END IF;
    RETURN jsonb_build_object('action_id',(SELECT id FROM public.budget_operation_items
      WHERE operation_id=coalesce(v_existing.parent_operation_id,v_existing.id)
        AND reversed_item_id=p_action_id LIMIT 1),
      'state',public.get_funded_budget_month(to_char((SELECT month_start FROM public.budget_months
        WHERE id=v_original.budget_month_id),'YYYY-MM')));
  END IF;
  LOCK TABLE public.transactions IN SHARE MODE;
  IF EXISTS(SELECT 1 FROM public.budget_operation_items
    WHERE item_kind='allocation_leg' AND linked_item_id=p_action_id AND source_kind='savings') THEN
    PERFORM pg_advisory_xact_lock(hashtext('finance_tracker_budget_savings'));
  END IF;
  SELECT * INTO v_month FROM public.budget_months WHERE id=v_original.budget_month_id FOR UPDATE;
  PERFORM 1 FROM public.budgets WHERE budget_month_id=v_original.budget_month_id ORDER BY id FOR UPDATE;
  IF public.budget_action_month_lifecycle(to_char(v_month.month_start,'YYYY-MM'))='closed' THEN
    RAISE EXCEPTION 'BUDGET_MONTH_ALREADY_CLOSED: closed months require a historical correction workflow' USING ERRCODE='23514';
  ELSIF public.budget_action_month_lifecycle(to_char(v_month.month_start,'YYYY-MM'))
        NOT IN('current','immediately_completed_unclosed') THEN
    RAISE EXCEPTION 'BUDGET_ACTION_MONTH_FORBIDDEN: action is outside the allowed month lifecycle' USING ERRCODE='23514';
  END IF;
  IF EXISTS(SELECT 1 FROM public.budget_operation_items
    WHERE item_kind=v_original.item_kind AND reversed_item_id=p_action_id) THEN
    RAISE EXCEPTION 'Funding action has already been reversed' USING ERRCODE='23505';
  END IF;
  SELECT coalesce(sum(l.amount),0) INTO v_required_unallocated
  FROM public.budget_operation_items l JOIN public.budget_movements m ON m.id=l.movement_id
  WHERE l.item_kind='allocation_leg' AND l.linked_item_id=p_action_id
    AND l.source_kind='category' AND m.destination_budget_id IS NULL;
  SELECT coalesce(unallocated,0)::numeric(18,2) INTO v_unallocated
  FROM public.budget_month_funding_state WHERE budget_month_id=v_original.budget_month_id;
  IF v_required_unallocated>v_unallocated THEN
    RAISE EXCEPTION 'FUNDING_ACTION_REVERSAL_BLOCKED: unallocated funding is insufficient' USING ERRCODE='23514';
  END IF;
  IF v_original.destination_budget_id IS NOT NULL THEN
    SELECT coalesce(sum(l.amount),0) INTO v_destination_release
    FROM public.budget_operation_items l JOIN public.budget_movements m ON m.id=l.movement_id
    WHERE l.item_kind='allocation_leg' AND l.linked_item_id=p_action_id
      AND m.destination_budget_id=v_original.destination_budget_id;
    SELECT final_funded INTO v_destination_final FROM public.budget_category_state
    WHERE budget_id=v_original.destination_budget_id;
    IF v_destination_release>v_destination_final THEN
      RAISE EXCEPTION 'FUNDING_ACTION_REVERSAL_BLOCKED: destination funding is insufficient' USING ERRCODE='23514';
    END IF;
    IF v_original.item_kind='reallocation' THEN
      SELECT coalesce(sum(t.total_amount),0)::numeric(18,2) INTO v_destination_raw
      FROM public.budget_actual_transactions(NULL,NULL) t JOIN public.budgets b ON b.category_id=t.category_id
      WHERE b.id=v_original.destination_budget_id AND t.movement_type='expense'
        AND t.transaction_date>=v_month.month_start
        AND t.transaction_date<(v_month.month_start+interval '1 month')::date;
      v_destination_effective:=greatest(v_destination_raw,0);
      IF v_destination_release>greatest(v_destination_final-v_destination_effective,0) THEN
        RAISE EXCEPTION 'FUNDING_ACTION_REVERSAL_BLOCKED: destination funding has been spent' USING ERRCODE='23514';
      END IF;
    END IF;
  END IF;
  v_operation_id:=public.budget_create_action_root(v_original.budget_month_id,p_request_key,v_fingerprint,
    'funding_action_reversal',v_month.month_start,p_reason,v_original.operation_id);
  INSERT INTO public.budget_operation_items(
    operation_id,item_kind,action_kind,budget_month_id,destination_budget_id,amount,
    funded_before,raw_actual_snapshot,deficit_before,deficit_after,reversed_item_id
  ) VALUES(v_operation_id,v_original.item_kind,'reversal',v_original.budget_month_id,
    v_original.destination_budget_id,v_original.amount,v_original.funded_before,
    v_original.raw_actual_snapshot,v_original.deficit_before,v_original.deficit_after,p_action_id)
  RETURNING id INTO v_action_id;
  SELECT coalesce(sum(amount),0) INTO v_savings_total FROM public.budget_operation_items
  WHERE item_kind='allocation_leg' AND linked_item_id=p_action_id AND source_kind='savings';
  IF v_savings_total>0 THEN
    SELECT * INTO v_original_funding FROM public.budget_funding_entries
    WHERE operation_id=v_original.operation_id AND source_kind='savings_withdrawal';
    INSERT INTO public.budget_funding_entries(operation_id,amount_delta,source_kind,source_label,reverses_funding_entry_id)
    VALUES(v_operation_id,-v_savings_total,'savings_withdrawal',
      'Reverse Savings-funded deficit resolution',v_original_funding.id);
  END IF;
  FOR original_leg IN
    SELECT l.*,m.source_budget_id original_source,m.destination_budget_id original_destination
    FROM public.budget_operation_items l JOIN public.budget_movements m ON m.id=l.movement_id
    WHERE l.item_kind='allocation_leg' AND l.linked_item_id=p_action_id ORDER BY l.id
  LOOP
    INSERT INTO public.budget_movements(operation_id,source_budget_id,destination_budget_id,amount)
    VALUES(v_operation_id,original_leg.original_destination,original_leg.original_source,original_leg.amount)
    RETURNING id INTO v_movement_id;
    v_savings_entry_id:=NULL;
    IF original_leg.source_kind='savings' THEN
      INSERT INTO public.budget_savings_entries(operation_id,category_id,amount_delta,entry_kind,
        reverses_entry_id,destination_budget_month_id,destination_budget_id,movement_id)
      VALUES(v_operation_id,(SELECT category_id FROM public.budgets WHERE id=v_original.destination_budget_id),
        original_leg.amount,'withdrawal_reversal',original_leg.savings_entry_id,
        v_original.budget_month_id,v_original.destination_budget_id,v_movement_id)
      RETURNING id INTO v_savings_entry_id;
    END IF;
    INSERT INTO public.budget_operation_items(
      operation_id,item_kind,action_kind,budget_month_id,source_kind,source_budget_id,
      destination_budget_id,amount,funded_before,raw_actual_snapshot,source_capacity_snapshot,
      movement_id,savings_entry_id,linked_item_id,reversed_item_id
    ) VALUES(v_operation_id,'allocation_leg','reversal',v_original.budget_month_id,
      original_leg.source_kind,original_leg.source_budget_id,v_original.destination_budget_id,
      original_leg.amount,original_leg.funded_before,original_leg.raw_actual_snapshot,
      original_leg.source_capacity_snapshot,v_movement_id,v_savings_entry_id,v_action_id,original_leg.id);
  END LOOP;
  PERFORM public.budget_assert_reconciled(v_original.budget_month_id);
  IF (SELECT balance FROM public.budget_savings_state)<0 THEN
    RAISE EXCEPTION 'Savings ledger cannot have a negative balance' USING ERRCODE='23514';
  END IF;
  RETURN jsonb_build_object('action_id',v_action_id,
    'state',public.get_funded_budget_month(to_char(v_month.month_start,'YYYY-MM')));
END;
$function$;

CREATE OR REPLACE FUNCTION public.budget_funding_source_rows(p_month text, p_excluded_category_id bigint DEFAULT NULL::bigint)
 RETURNS TABLE(source_kind text, category_id bigint, budget_id bigint, category_name text, final_funded numeric, raw_actual numeric, effective_actual numeric, capacity numeric)
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
WITH params AS (
  SELECT public.budget_month_start_from_key(p_month) month_start
), month_row AS (
  SELECT bm.id FROM public.budget_months bm,params p WHERE bm.month_start=p.month_start
), actuals AS (
  SELECT t.category_id,sum(t.total_amount)::numeric(18,2) raw_actual
  FROM public.budget_actual_transactions(NULL,NULL) t,params p
  WHERE t.movement_type='expense' AND t.transaction_date>=p.month_start
    AND t.transaction_date<(p.month_start+interval '1 month')::date
  GROUP BY t.category_id
), category_sources AS (
  SELECT 'category'::text source_kind,cs.category_id,cs.budget_id,cs.category_name,
    cs.final_funded::numeric(18,2) final_funded,
    coalesce(a.raw_actual,0)::numeric(18,2) raw_actual,
    greatest(coalesce(a.raw_actual,0),0)::numeric(18,2) effective_actual,
    greatest(cs.final_funded-greatest(coalesce(a.raw_actual,0),0),0)::numeric(18,2) capacity
  FROM public.budget_category_state cs
  JOIN month_row mr ON mr.id=cs.budget_month_id
  JOIN public.categories c ON c.id=cs.category_id
  LEFT JOIN actuals a ON a.category_id=cs.category_id
  WHERE cs.lifecycle_state='active' AND cs.category_type='expense' AND c.is_active
    AND cs.category_id IS DISTINCT FROM p_excluded_category_id
)
SELECT * FROM category_sources
UNION ALL
SELECT 'unallocated',NULL,NULL,NULL,NULL,NULL,NULL,
  coalesce((SELECT s.unallocated FROM public.budget_month_funding_state s JOIN month_row mr ON mr.id=s.budget_month_id),0)::numeric(18,2)
UNION ALL
SELECT 'savings',NULL,NULL,NULL,NULL,NULL,NULL,
  coalesce((SELECT balance FROM public.budget_savings_state),0)::numeric(18,2);
$function$;

CREATE OR REPLACE FUNCTION public.get_budget_unbudgeted_resolution_preview(p_month text, p_category_id bigint, p_requested_amount numeric, p_legs jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
DECLARE
  v_month_start DATE:=public.budget_month_start_from_key(p_month);
  v_lifecycle TEXT:=public.budget_action_month_lifecycle(p_month);
  v_month_id BIGINT; v_category public.categories%ROWTYPE;
  v_budget_id BIGINT; v_budget_lifecycle TEXT; v_existing_funded NUMERIC(18,2):=0;
  v_mode TEXT:='created'; v_raw NUMERIC(18,2):=0; v_needed_to_cover_actual NUMERIC(18,2):=0;
  v_unallocated NUMERIC(18,2):=0; v_savings NUMERIC(18,2):=0;
  v_sources JSONB:='[]'::jsonb; v_selected JSONB:='[]'::jsonb;
  v_total NUMERIC(18,2):=0; v_resulting NUMERIC(18,2):=0; v_deficit NUMERIC(18,2):=0;
  v_reason TEXT; v_material TEXT:=''; v_seen TEXT[]:='{}';
  item JSONB; v_kind TEXT; v_amount NUMERIC(18,2); v_key TEXT; v_source RECORD;
  v_pending_override BOOLEAN:=false;
BEGIN
  IF p_requested_amount IS NULL OR p_requested_amount::text IN ('NaN','Infinity','-Infinity')
     OR p_requested_amount<0 OR p_requested_amount<>round(p_requested_amount,2)
     OR p_requested_amount>9999999999999999.99 THEN
    RAISE EXCEPTION 'requested_amount must be a nonnegative two-decimal value' USING ERRCODE='22023';
  END IF;
  IF p_legs IS NULL OR jsonb_typeof(p_legs)<>'array' THEN
    RAISE EXCEPTION 'legs must be an array' USING ERRCODE='22023';
  END IF;
  SELECT * INTO v_category FROM public.categories WHERE id=p_category_id;
  IF NOT FOUND THEN v_reason:='INVALID_BUDGET_CATEGORY';
  ELSIF v_category.type<>'expense' THEN v_reason:='INVALID_BUDGET_CATEGORY';
  ELSIF NOT v_category.is_active THEN v_reason:='CATEGORY_NOT_ACTIVE';
  END IF;
  SELECT id INTO v_month_id FROM public.budget_months WHERE month_start=v_month_start;
  SELECT cs.budget_id,cs.lifecycle_state,cs.final_funded
    INTO v_budget_id,v_budget_lifecycle,v_existing_funded
  FROM public.budget_category_state cs
  WHERE cs.budget_month_id=v_month_id AND cs.category_id=p_category_id;
  IF FOUND THEN
    IF v_budget_lifecycle='active' THEN v_reason:=coalesce(v_reason,'NO_UNBUDGETED_EXPENSE');
    ELSE v_mode:='reactivated'; END IF;
  ELSE
    v_budget_id:=NULL; v_budget_lifecycle:='no_budget'; v_existing_funded:=0;
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.budget_actual_transactions(NULL,NULL)
    WHERE movement_type='expense' AND category_id=p_category_id
      AND transaction_date>=v_month_start AND transaction_date<(v_month_start+interval '1 month')::date
      AND total_amount::text IN ('NaN','Infinity','-Infinity')
  ) THEN
    RAISE EXCEPTION 'Unbudgeted actual spending contains a non-finite amount' USING ERRCODE='22003';
  END IF;
  SELECT coalesce(sum(total_amount),0)::numeric(18,2) INTO v_raw FROM public.budget_actual_transactions(NULL,NULL)
  WHERE movement_type='expense' AND category_id=p_category_id
    AND transaction_date>=v_month_start AND transaction_date<(v_month_start+interval '1 month')::date;
  IF v_raw<=0 THEN v_reason:=coalesce(v_reason,'NO_UNBUDGETED_EXPENSE'); END IF;
  v_pending_override:=v_budget_id IS NULL AND EXISTS (
    SELECT 1 FROM public.budget_month_overrides
    WHERE budget_month_id=v_month_id AND category_id=p_category_id
  );
  IF v_pending_override THEN v_reason:=coalesce(v_reason,'UNBUDGETED_RESOLUTION_PENDING_OVERRIDE'); END IF;

  -- Recorded spending explains how much funding is needed to eliminate the
  -- existing deficit. It does not limit the monthly budget selected by the user.
  v_needed_to_cover_actual:=greatest(v_raw-v_existing_funded,0);
  IF p_requested_amount=0 AND (v_mode='created' OR v_existing_funded<v_raw) THEN
    v_reason:=coalesce(v_reason,'UNBUDGETED_RESOLUTION_REQUIRES_FUNDING');
  END IF;
  IF v_lifecycle='closed' THEN v_reason:='BUDGET_MONTH_ALREADY_CLOSED';
  ELSIF v_lifecycle NOT IN ('current','immediately_completed_unclosed') THEN
    v_reason:='BUDGET_ACTION_MONTH_FORBIDDEN';
  END IF;

  SELECT capacity INTO v_unallocated FROM public.budget_funding_source_rows(p_month,p_category_id)
  WHERE source_kind='unallocated';
  SELECT capacity INTO v_savings FROM public.budget_funding_source_rows(p_month,p_category_id)
  WHERE source_kind='savings';
  SELECT coalesce(jsonb_agg(jsonb_build_object(
    'category_id',s.category_id,'budget_id',s.budget_id,'category_name',s.category_name,
    'final_funded',s.final_funded::text,'raw_actual',s.raw_actual::text,
    'effective_actual',s.effective_actual::text,'capacity',s.capacity::text
  ) ORDER BY s.category_name,s.category_id),'[]'::jsonb) INTO v_sources
  FROM public.budget_funding_source_rows(p_month,p_category_id) s
  WHERE s.source_kind='category' AND s.capacity>0;

  FOR item IN SELECT value FROM jsonb_array_elements(p_legs) LOOP
    v_kind:=item->>'source_kind';
    IF jsonb_typeof(item) IS DISTINCT FROM 'object'
       OR v_kind IS NULL OR v_kind NOT IN ('category','unallocated','savings')
       OR jsonb_typeof(item->'amount') IS DISTINCT FROM 'string'
       OR (item->>'amount')!~'^(0|[1-9][0-9]*)(\.[0-9]{1,2})?$' THEN
      RAISE EXCEPTION 'Unbudgeted funding leg has an invalid source or money format' USING ERRCODE='22023';
    END IF;
    v_amount:=(item->>'amount')::numeric;
    IF v_amount<=0 OR v_amount>9999999999999999.99 THEN
      RAISE EXCEPTION 'Unbudgeted funding leg amount must be positive' USING ERRCODE='22023';
    END IF;
    v_key:=v_kind||':'||coalesce(item->>'category_id','');
    IF v_key=ANY(v_seen) THEN RAISE EXCEPTION 'Duplicate unbudgeted funding source' USING ERRCODE='22023'; END IF;
    v_seen:=array_append(v_seen,v_key);
    SELECT * INTO v_source FROM public.budget_funding_source_rows(p_month,p_category_id) s
    WHERE s.source_kind=v_kind
      AND (v_kind<>'category' OR s.category_id=NULLIF(item->>'category_id','')::bigint);
    IF NOT FOUND THEN
      v_reason:=coalesce(v_reason,'UNBUDGETED_RESOLUTION_SOURCE_INSUFFICIENT');
      SELECT NULL::text source_kind,NULL::bigint category_id,NULL::bigint budget_id,
        NULL::text category_name,NULL::numeric final_funded,NULL::numeric raw_actual,
        NULL::numeric effective_actual,0::numeric capacity INTO v_source;
    END IF;
    IF v_amount>v_source.capacity THEN v_reason:=coalesce(v_reason,
      CASE WHEN v_kind='savings' THEN 'SAVINGS_INSUFFICIENT' ELSE 'UNBUDGETED_RESOLUTION_SOURCE_INSUFFICIENT' END);
    END IF;
    v_total:=v_total+v_amount;
    v_selected:=v_selected||jsonb_build_array(jsonb_build_object(
      'source_kind',v_kind,'category_id',CASE WHEN v_kind='category' THEN v_source.category_id END,
      'source_budget_id',CASE WHEN v_kind='category' THEN v_source.budget_id END,
      'amount',v_amount::numeric(18,2)::text,
      'source_final_funded',CASE WHEN v_kind='category' THEN v_source.final_funded::text END,
      'source_raw_actual',CASE WHEN v_kind='category' THEN v_source.raw_actual::text END,
      'source_effective_actual',CASE WHEN v_kind='category' THEN v_source.effective_actual::text END,
      'source_capacity',v_source.capacity::numeric(18,2)::text));
    v_material:=v_material||'|'||v_key||'|'||v_amount::numeric(18,2)::text||'|'||v_source.capacity::text
      ||'|'||coalesce(v_source.budget_id::text,'')||'|'||coalesce(v_source.final_funded::text,'')
      ||'|'||coalesce(v_source.raw_actual::text,'')||'|'||coalesce(v_source.effective_actual::text,'');
  END LOOP;
  IF v_total<>p_requested_amount THEN
    v_reason:=coalesce(v_reason,'UNBUDGETED_RESOLUTION_LEG_TOTAL_MISMATCH');
  END IF;
  v_resulting:=v_existing_funded+p_requested_amount;
  v_deficit:=greatest(v_raw-v_resulting,0);
  RETURN jsonb_build_object(
    'month',p_month,'lifecycle',v_lifecycle,'category_id',p_category_id,
    'category',CASE WHEN v_category.id IS NULL THEN NULL ELSE jsonb_build_object(
      'id',v_category.id,'name',v_category.name,'icon',v_category.icon,'type',v_category.type,
      'is_active',v_category.is_active) END,
    'resolution_mode',v_mode,'budget_id',v_budget_id,'budget_lifecycle',v_budget_lifecycle,
    'raw_actual',v_raw::numeric(18,2)::text,
    'existing_funded',v_existing_funded::numeric(18,2)::text,
    'amount_needed_to_cover_actual',v_needed_to_cover_actual::numeric(18,2)::text,
    'requested_allocation',p_requested_amount::numeric(18,2)::text,
    'resulting_funded',v_resulting::numeric(18,2)::text,
    'remaining_deficit',v_deficit::numeric(18,2)::text,
    'unallocated_capacity',v_unallocated::numeric(18,2)::text,
    'savings_balance',v_savings::numeric(18,2)::text,
    'eligible_source_categories',v_sources,'selected_legs',v_selected,
    'pending_override',v_pending_override,
    'fingerprint',md5(concat_ws('|','unbudgeted',p_month,v_lifecycle,p_category_id,
      coalesce(v_category.type,''),coalesce(v_category.is_active::text,''),v_mode,
      coalesce(v_budget_id::text,''),v_budget_lifecycle,v_raw::text,v_existing_funded::text,
      p_requested_amount::numeric(18,2)::text,v_unallocated::text,v_savings::text,
      v_pending_override::text,v_material,coalesce(v_reason,''))),
    'can_apply',v_reason IS NULL,'reason',v_reason
  );
END; $function$;

CREATE OR REPLACE FUNCTION public.reverse_budget_unbudgeted_resolution(p_event_id bigint, p_request_key uuid, p_reason text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
DECLARE
  v_original public.budget_operation_items%ROWTYPE; v_existing public.budget_operations%ROWTYPE;
  v_month public.budget_months%ROWTYPE; v_operation_id BIGINT; v_action_id BIGINT;
  v_event_id BIGINT; v_fingerprint TEXT; v_current_final NUMERIC(18,2);
  v_current_raw NUMERIC(18,2); v_movement_id BIGINT; v_savings_entry_id BIGINT;
  v_lifecycle_id BIGINT; v_savings_total NUMERIC(18,2):=0;
  v_original_funding public.budget_funding_entries%ROWTYPE; original_leg RECORD;
BEGIN
  IF p_event_id IS NULL OR p_request_key IS NULL THEN
    RAISE EXCEPTION 'event_id and request_key are required' USING ERRCODE='22023';
  END IF;
  SELECT * INTO v_original FROM public.budget_operation_items
  WHERE id=p_event_id AND item_kind='unbudgeted_resolution' AND action_kind='apply'
    AND reversed_item_id IS NULL;
  IF NOT FOUND THEN RAISE EXCEPTION 'Unbudgeted resolution does not exist' USING ERRCODE='P0002'; END IF;
  v_fingerprint:='unbudgeted_resolution_reverse|'||p_event_id::text;
  SELECT * INTO v_existing FROM public.budget_operations WHERE request_key=p_request_key;
  IF FOUND THEN
    IF v_existing.operation_type<>'unbudgeted_resolution_reversal'
       OR v_existing.request_fingerprint<>v_fingerprint THEN
      RAISE EXCEPTION 'request_key was already used for a different budget operation' USING ERRCODE='23505';
    END IF;
    RETURN jsonb_build_object(
      'event_id',(SELECT id FROM public.budget_operation_items
        WHERE operation_id=coalesce(v_existing.parent_operation_id,v_existing.id)
          AND item_kind='unbudgeted_resolution' AND reversed_item_id=p_event_id LIMIT 1),
      'action_id',(SELECT id FROM public.budget_operation_items
        WHERE operation_id=coalesce(v_existing.parent_operation_id,v_existing.id)
          AND item_kind='funding_action' AND reversed_item_id=v_original.linked_item_id LIMIT 1),
      'state',public.get_funded_budget_month(to_char((SELECT month_start FROM public.budget_months
        WHERE id=v_original.budget_month_id),'YYYY-MM')));
  END IF;
  LOCK TABLE public.transactions IN SHARE MODE;
  IF v_original.linked_item_id IS NOT NULL AND EXISTS(SELECT 1 FROM public.budget_operation_items
    WHERE item_kind='allocation_leg' AND linked_item_id=v_original.linked_item_id AND source_kind='savings') THEN
    PERFORM pg_advisory_xact_lock(hashtext('finance_tracker_budget_savings'));
  END IF;
  SELECT * INTO v_month FROM public.budget_months WHERE id=v_original.budget_month_id FOR UPDATE;
  PERFORM 1 FROM public.budgets WHERE budget_month_id=v_month.id ORDER BY id FOR UPDATE;
  PERFORM 1 FROM public.categories WHERE id IN(
    SELECT v_original.category_id UNION SELECT b.category_id
    FROM public.budget_operation_items l JOIN public.budgets b ON b.id=l.source_budget_id
    WHERE l.item_kind='allocation_leg' AND l.linked_item_id=v_original.linked_item_id
  ) ORDER BY id FOR UPDATE;
  IF public.budget_action_month_lifecycle(to_char(v_month.month_start,'YYYY-MM'))='closed' THEN
    RAISE EXCEPTION 'BUDGET_MONTH_ALREADY_CLOSED: closed months require a historical correction workflow' USING ERRCODE='23514';
  ELSIF public.budget_action_month_lifecycle(to_char(v_month.month_start,'YYYY-MM'))
        NOT IN('current','immediately_completed_unclosed') THEN
    RAISE EXCEPTION 'BUDGET_ACTION_MONTH_FORBIDDEN: action is outside the allowed month lifecycle' USING ERRCODE='23514';
  END IF;
  IF EXISTS(SELECT 1 FROM public.budget_operation_items
    WHERE item_kind='unbudgeted_resolution' AND reversed_item_id=p_event_id) THEN
    RAISE EXCEPTION 'Unbudgeted resolution has already been reversed' USING ERRCODE='23505';
  END IF;
  SELECT final_funded INTO v_current_final FROM public.budget_category_state
  WHERE budget_id=v_original.destination_budget_id AND lifecycle_state='active';
  IF NOT FOUND OR v_current_final<v_original.amount THEN
    RAISE EXCEPTION 'UNBUDGETED_RESOLUTION_REVERSAL_BLOCKED: destination funding or lifecycle changed'
      USING ERRCODE='23514';
  END IF;
  SELECT coalesce(sum(total_amount),0)::numeric(18,2) INTO v_current_raw
  FROM public.budget_actual_transactions(NULL,NULL) WHERE movement_type='expense' AND category_id=v_original.category_id
    AND transaction_date>=v_month.month_start
    AND transaction_date<(v_month.month_start+interval '1 month')::date;
  v_operation_id:=public.budget_create_action_root(v_month.id,p_request_key,v_fingerprint,
    'unbudgeted_resolution_reversal',CASE WHEN v_month.month_start=
      date_trunc('month',timezone('Asia/Jerusalem',statement_timestamp()))::date
      THEN timezone('Asia/Jerusalem',statement_timestamp())::date
      ELSE (v_month.month_start+interval '1 month - 1 day')::date END,
    p_reason,v_original.operation_id);
  IF v_original.linked_item_id IS NOT NULL THEN
    INSERT INTO public.budget_operation_items(
      operation_id,item_kind,action_kind,budget_month_id,destination_budget_id,amount,
      funded_before,raw_actual_snapshot,deficit_after,reversed_item_id
    ) VALUES(v_operation_id,'funding_action','reversal',v_month.id,v_original.destination_budget_id,
      v_original.amount,v_current_final,v_original.raw_actual_snapshot,NULL,v_original.linked_item_id)
    RETURNING id INTO v_action_id;
    SELECT coalesce(sum(amount),0) INTO v_savings_total FROM public.budget_operation_items
    WHERE item_kind='allocation_leg' AND linked_item_id=v_original.linked_item_id AND source_kind='savings';
    IF v_savings_total>0 THEN
      SELECT * INTO v_original_funding FROM public.budget_funding_entries
      WHERE operation_id=v_original.operation_id AND source_kind='savings_withdrawal';
      INSERT INTO public.budget_funding_entries(operation_id,amount_delta,source_kind,source_label,reverses_funding_entry_id)
      VALUES(v_operation_id,-v_savings_total,'savings_withdrawal',
        'Reverse Savings-funded unbudgeted resolution',v_original_funding.id);
    END IF;
    FOR original_leg IN
      SELECT l.*,m.source_budget_id original_source,m.destination_budget_id original_destination
      FROM public.budget_operation_items l JOIN public.budget_movements m ON m.id=l.movement_id
      WHERE l.item_kind='allocation_leg' AND l.linked_item_id=v_original.linked_item_id ORDER BY l.id
    LOOP
      INSERT INTO public.budget_movements(operation_id,source_budget_id,destination_budget_id,amount)
      VALUES(v_operation_id,original_leg.original_destination,original_leg.original_source,original_leg.amount)
      RETURNING id INTO v_movement_id;
      v_savings_entry_id:=NULL;
      IF original_leg.source_kind='savings' THEN
        INSERT INTO public.budget_savings_entries(operation_id,category_id,amount_delta,entry_kind,
          reverses_entry_id,destination_budget_month_id,destination_budget_id,movement_id)
        VALUES(v_operation_id,v_original.category_id,original_leg.amount,'withdrawal_reversal',
          original_leg.savings_entry_id,v_month.id,v_original.destination_budget_id,v_movement_id)
        RETURNING id INTO v_savings_entry_id;
      END IF;
      INSERT INTO public.budget_operation_items(
        operation_id,item_kind,action_kind,budget_month_id,source_kind,source_budget_id,
        destination_budget_id,amount,funded_before,raw_actual_snapshot,source_capacity_snapshot,
        movement_id,savings_entry_id,linked_item_id,reversed_item_id
      ) VALUES(v_operation_id,'allocation_leg','reversal',v_month.id,original_leg.source_kind,
        original_leg.source_budget_id,v_original.destination_budget_id,original_leg.amount,
        original_leg.funded_before,original_leg.raw_actual_snapshot,original_leg.source_capacity_snapshot,
        v_movement_id,v_savings_entry_id,v_action_id,original_leg.id);
    END LOOP;
  END IF;
  INSERT INTO public.budget_lifecycle_events(operation_id,budget_id,state,actual_spent_snapshot)
  VALUES(v_operation_id,v_original.destination_budget_id,'inactive',greatest(v_current_raw,0))
  RETURNING id INTO v_lifecycle_id;
  INSERT INTO public.budget_operation_items(
    operation_id,item_kind,action_kind,budget_month_id,category_id,destination_budget_id,
    resolution_mode,raw_actual_snapshot,funded_before,amount,funded_after,deficit_after,
    lifecycle_event_id,linked_item_id,reversed_item_id
  ) VALUES(v_operation_id,'unbudgeted_resolution','reversal',v_month.id,v_original.category_id,
    v_original.destination_budget_id,v_original.resolution_mode,v_current_raw,v_current_final,
    v_original.amount,v_current_final-v_original.amount,
    greatest(v_current_raw-(v_current_final-v_original.amount),0),v_lifecycle_id,v_action_id,p_event_id)
  RETURNING id INTO v_event_id;
  PERFORM public.budget_assert_reconciled(v_month.id);
  IF (SELECT balance FROM public.budget_savings_state)<0 THEN
    RAISE EXCEPTION 'Savings ledger cannot have a negative balance' USING ERRCODE='23514';
  END IF;
  RETURN jsonb_build_object('event_id',v_event_id,'action_id',v_action_id,
    'state',public.get_funded_budget_month(to_char(v_month.month_start,'YYYY-MM')));
END;
$function$;

CREATE OR REPLACE FUNCTION public.transactions_filtered(p_from date DEFAULT NULL::date, p_to date DEFAULT NULL::date, p_category_id bigint DEFAULT NULL::bigint, p_payment_source_id bigint DEFAULT NULL::bigint, p_uncategorized_only boolean DEFAULT false, p_search text DEFAULT NULL::text)
 RETURNS TABLE(id integer, transaction_date date, description text, movement_type text, total_amount numeric, row_json jsonb)
 LANGUAGE sql
 STABLE
AS $function$
  SELECT
    t.id,
    t.transaction_date,
    t.description::text,
    t.movement_type::text,
    t.total_amount,
    pg_catalog.to_jsonb(t) || pg_catalog.jsonb_build_object(
      'categories',
      CASE WHEN c.id IS NULL THEN NULL
           ELSE pg_catalog.jsonb_build_object('name', c.name, 'icon', c.icon) END,
      'payment_sources',
      CASE WHEN ps.id IS NULL THEN NULL
           ELSE pg_catalog.jsonb_build_object(
             'id',     ps.id,
             'name',   ps.name,
             'method', ps.method,
             'slug',   ps.slug,
             'issuer', ps.issuer,
             'last4',  ps.last4
           ) END
    )
  FROM (SELECT * FROM public.transactions WHERE voided_at IS NULL) t
  -- LEFT JOIN is required: transactions with no category or no payment source
  -- must still appear (the "uncategorized only" filter depends on it).
  LEFT JOIN public.categories      c  ON c.id  = t.category_id
  LEFT JOIN public.payment_sources ps ON ps.id = t.payment_source_id
  WHERE (p_from IS NULL OR t.transaction_date >= p_from)
    AND (p_to   IS NULL OR t.transaction_date <= p_to)
    AND (p_category_id IS NULL OR t.category_id = p_category_id)
    AND (p_payment_source_id IS NULL OR t.payment_source_id = p_payment_source_id)
    AND (NOT COALESCE(p_uncategorized_only, false) OR t.category_id IS NULL)
    AND (
      public.transactions_search_pattern(p_search) IS NULL
      -- Mirrors the previous client-side search exactly: description,
      -- amount-as-text, category name, payment source name. Notes are NOT
      -- searched, because the old implementation did not search them.
      OR t.description        ILIKE public.transactions_search_pattern(p_search) ESCAPE '\'
      OR t.total_amount::text ILIKE public.transactions_search_pattern(p_search) ESCAPE '\'
      OR c.name               ILIKE public.transactions_search_pattern(p_search) ESCAPE '\'
      OR ps.name              ILIKE public.transactions_search_pattern(p_search) ESCAPE '\'
    );
$function$;

CREATE OR REPLACE FUNCTION public.transactions_page(p_from date DEFAULT NULL::date, p_to date DEFAULT NULL::date, p_category_id bigint DEFAULT NULL::bigint, p_payment_source_id bigint DEFAULT NULL::bigint, p_uncategorized_only boolean DEFAULT false, p_search text DEFAULT NULL::text, p_limit integer DEFAULT 100, p_sort_by text DEFAULT 'transaction_date'::text, p_sort_direction text DEFAULT 'desc'::text, p_cursor_id bigint DEFAULT NULL::bigint, p_cursor_date date DEFAULT NULL::date, p_cursor_amount numeric DEFAULT NULL::numeric, p_cursor_description text DEFAULT NULL::text, p_cursor_description_is_null boolean DEFAULT NULL::boolean, p_include_totals boolean DEFAULT false)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE
 SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_probe     integer;
  v_rows      jsonb;
  v_keys      jsonb;
  v_has_more  boolean := false;
  v_next_key  jsonb   := NULL;
  v_totals    jsonb   := NULL;
BEGIN
  IF p_limit IS NULL OR p_limit < 1 THEN
    RAISE EXCEPTION 'transactions_page: p_limit must be a positive integer, got %', p_limit;
  END IF;

  -- One row beyond the page, so has_more is derived from real data rather than
  -- guessed from a full page.
  v_probe := p_limit + 1;

  -- ---------------------------------------------------------------------
  -- transaction_date DESC, id DESC   (the default view)
  -- ---------------------------------------------------------------------
  IF p_sort_by = 'transaction_date' AND p_sort_direction = 'desc' THEN
    SELECT jsonb_agg(p.row_json ORDER BY p.transaction_date DESC, p.id DESC),
           jsonb_agg(p.k        ORDER BY p.transaction_date DESC, p.id DESC)
      INTO v_rows, v_keys
    FROM (
      SELECT f.transaction_date,
             f.id,
             f.row_json,
             jsonb_build_object(
               'td', to_char(f.transaction_date, 'YYYY-MM-DD'),
               'id', f.id
             ) AS k
      FROM public.transactions_filtered(
             p_from, p_to, p_category_id, p_payment_source_id,
             p_uncategorized_only, p_search) f
      WHERE p_cursor_id IS NULL
         OR f.transaction_date < p_cursor_date
         OR (f.transaction_date = p_cursor_date AND f.id < p_cursor_id)
      ORDER BY f.transaction_date DESC, f.id DESC
      LIMIT v_probe
    ) p;

  -- ---------------------------------------------------------------------
  -- transaction_date ASC, id DESC
  -- ---------------------------------------------------------------------
  ELSIF p_sort_by = 'transaction_date' AND p_sort_direction = 'asc' THEN
    SELECT jsonb_agg(p.row_json ORDER BY p.transaction_date ASC, p.id DESC),
           jsonb_agg(p.k        ORDER BY p.transaction_date ASC, p.id DESC)
      INTO v_rows, v_keys
    FROM (
      SELECT f.transaction_date,
             f.id,
             f.row_json,
             jsonb_build_object(
               'td', to_char(f.transaction_date, 'YYYY-MM-DD'),
               'id', f.id
             ) AS k
      FROM public.transactions_filtered(
             p_from, p_to, p_category_id, p_payment_source_id,
             p_uncategorized_only, p_search) f
      WHERE p_cursor_id IS NULL
         OR f.transaction_date > p_cursor_date
         OR (f.transaction_date = p_cursor_date AND f.id < p_cursor_id)
      ORDER BY f.transaction_date ASC, f.id DESC
      LIMIT v_probe
    ) p;

  -- ---------------------------------------------------------------------
  -- total_amount DESC, transaction_date DESC, id DESC
  -- ---------------------------------------------------------------------
  ELSIF p_sort_by = 'total_amount' AND p_sort_direction = 'desc' THEN
    SELECT jsonb_agg(p.row_json ORDER BY p.total_amount DESC, p.transaction_date DESC, p.id DESC),
           jsonb_agg(p.k        ORDER BY p.total_amount DESC, p.transaction_date DESC, p.id DESC)
      INTO v_rows, v_keys
    FROM (
      SELECT f.transaction_date,
             f.id,
             f.total_amount,
             f.row_json,
             jsonb_build_object(
               -- ::text, not a JSON number: NUMERIC must not round-trip a double.
               'av', f.total_amount::text,
               'td', to_char(f.transaction_date, 'YYYY-MM-DD'),
               'id', f.id
             ) AS k
      FROM public.transactions_filtered(
             p_from, p_to, p_category_id, p_payment_source_id,
             p_uncategorized_only, p_search) f
      WHERE p_cursor_id IS NULL
         OR f.total_amount < p_cursor_amount
         OR (f.total_amount = p_cursor_amount
             AND (f.transaction_date < p_cursor_date
                  OR (f.transaction_date = p_cursor_date AND f.id < p_cursor_id)))
      ORDER BY f.total_amount DESC, f.transaction_date DESC, f.id DESC
      LIMIT v_probe
    ) p;

  -- ---------------------------------------------------------------------
  -- total_amount ASC, transaction_date DESC, id DESC
  -- ---------------------------------------------------------------------
  ELSIF p_sort_by = 'total_amount' AND p_sort_direction = 'asc' THEN
    SELECT jsonb_agg(p.row_json ORDER BY p.total_amount ASC, p.transaction_date DESC, p.id DESC),
           jsonb_agg(p.k        ORDER BY p.total_amount ASC, p.transaction_date DESC, p.id DESC)
      INTO v_rows, v_keys
    FROM (
      SELECT f.transaction_date,
             f.id,
             f.total_amount,
             f.row_json,
             jsonb_build_object(
               'av', f.total_amount::text,
               'td', to_char(f.transaction_date, 'YYYY-MM-DD'),
               'id', f.id
             ) AS k
      FROM public.transactions_filtered(
             p_from, p_to, p_category_id, p_payment_source_id,
             p_uncategorized_only, p_search) f
      WHERE p_cursor_id IS NULL
         OR f.total_amount > p_cursor_amount
         OR (f.total_amount = p_cursor_amount
             AND (f.transaction_date < p_cursor_date
                  OR (f.transaction_date = p_cursor_date AND f.id < p_cursor_id)))
      ORDER BY f.total_amount ASC, f.transaction_date DESC, f.id DESC
      LIMIT v_probe
    ) p;

  -- ---------------------------------------------------------------------
  -- description ASC, transaction_date DESC, id DESC   (NULL descriptions last)
  -- ---------------------------------------------------------------------
  ELSIF p_sort_by = 'description' AND p_sort_direction = 'asc' THEN
    SELECT jsonb_agg(p.row_json ORDER BY (p.description IS NULL) ASC,
                                         p.description COLLATE "C" ASC,
                                         p.transaction_date DESC, p.id DESC),
           jsonb_agg(p.k        ORDER BY (p.description IS NULL) ASC,
                                         p.description COLLATE "C" ASC,
                                         p.transaction_date DESC, p.id DESC)
      INTO v_rows, v_keys
    FROM (
      SELECT f.transaction_date,
             f.id,
             f.description,
             f.row_json,
             jsonb_build_object(
               'dn', (f.description IS NULL),
               'dv', f.description,
               'td', to_char(f.transaction_date, 'YYYY-MM-DD'),
               'id', f.id
             ) AS k
      FROM public.transactions_filtered(
             p_from, p_to, p_category_id, p_payment_source_id,
             p_uncategorized_only, p_search) f
      WHERE p_cursor_id IS NULL
         OR (
           CASE
             -- Still inside the non-NULL block: everything that sorts after the
             -- cursor value, plus the entire NULL block that follows it.
             WHEN NOT p_cursor_description_is_null THEN
                  f.description IS NULL
               OR f.description COLLATE "C" > p_cursor_description COLLATE "C"
               OR (f.description COLLATE "C" = p_cursor_description COLLATE "C"
                   AND (f.transaction_date < p_cursor_date
                        OR (f.transaction_date = p_cursor_date AND f.id < p_cursor_id)))
             -- Already inside the trailing NULL block: only later NULL rows.
             ELSE
               f.description IS NULL
               AND (f.transaction_date < p_cursor_date
                    OR (f.transaction_date = p_cursor_date AND f.id < p_cursor_id))
           END
         )
      ORDER BY (f.description IS NULL) ASC,
               f.description COLLATE "C" ASC,
               f.transaction_date DESC, f.id DESC
      LIMIT v_probe
    ) p;

  -- ---------------------------------------------------------------------
  -- description DESC, transaction_date DESC, id DESC  (NULL descriptions last)
  -- ---------------------------------------------------------------------
  ELSIF p_sort_by = 'description' AND p_sort_direction = 'desc' THEN
    SELECT jsonb_agg(p.row_json ORDER BY (p.description IS NULL) ASC,
                                         p.description COLLATE "C" DESC,
                                         p.transaction_date DESC, p.id DESC),
           jsonb_agg(p.k        ORDER BY (p.description IS NULL) ASC,
                                         p.description COLLATE "C" DESC,
                                         p.transaction_date DESC, p.id DESC)
      INTO v_rows, v_keys
    FROM (
      SELECT f.transaction_date,
             f.id,
             f.description,
             f.row_json,
             jsonb_build_object(
               'dn', (f.description IS NULL),
               'dv', f.description,
               'td', to_char(f.transaction_date, 'YYYY-MM-DD'),
               'id', f.id
             ) AS k
      FROM public.transactions_filtered(
             p_from, p_to, p_category_id, p_payment_source_id,
             p_uncategorized_only, p_search) f
      WHERE p_cursor_id IS NULL
         OR (
           CASE
             WHEN NOT p_cursor_description_is_null THEN
                  f.description IS NULL
               OR f.description COLLATE "C" < p_cursor_description COLLATE "C"
               OR (f.description COLLATE "C" = p_cursor_description COLLATE "C"
                   AND (f.transaction_date < p_cursor_date
                        OR (f.transaction_date = p_cursor_date AND f.id < p_cursor_id)))
             ELSE
               f.description IS NULL
               AND (f.transaction_date < p_cursor_date
                    OR (f.transaction_date = p_cursor_date AND f.id < p_cursor_id))
           END
         )
      ORDER BY (f.description IS NULL) ASC,
               f.description COLLATE "C" DESC,
               f.transaction_date DESC, f.id DESC
      LIMIT v_probe
    ) p;

  ELSE
    RAISE EXCEPTION 'transactions_page: unsupported sort % %', p_sort_by, p_sort_direction;
  END IF;

  -- jsonb_agg over an empty set returns NULL, not '[]'.
  v_rows := COALESCE(v_rows, '[]'::jsonb);
  v_keys := COALESCE(v_keys, '[]'::jsonb);

  v_has_more := jsonb_array_length(v_rows) > p_limit;

  IF v_has_more THEN
    -- Drop the probe row. The explicit ORDER BY on the ordinality keeps the
    -- page order intact through the re-aggregation.
    SELECT jsonb_agg(e ORDER BY o)
      INTO v_rows
    FROM jsonb_array_elements(v_rows) WITH ORDINALITY AS x(e, o)
    WHERE o <= p_limit;

    -- Keyset position of the LAST ROW ACTUALLY RETURNED (0-based index),
    -- never the probe row.
    v_next_key := v_keys -> (p_limit - 1);
  END IF;

  -- Totals cover the whole filtered set, not the returned page: summing a
  -- single page would understate the user's real totals. Requested on the
  -- first page only, which is why this must be a real conditional.
  IF COALESCE(p_include_totals, false) THEN
    SELECT jsonb_build_object(
             'count',   COUNT(*),
             -- The income/expense split follows the existing movement_type
             -- contract: total_amount carries the magnitude and movement_type
             -- carries the direction. Unchanged from calculateSummaryStats.
             -- (Note: there is no CHECK constraint forcing total_amount >= 0;
             -- this mirrors whatever is stored, it does not assume a sign.)
             'income',  COALESCE(SUM(f.total_amount) FILTER (WHERE f.movement_type = 'income'),  0),
             'expense', COALESCE(SUM(f.total_amount) FILTER (WHERE f.movement_type = 'expense'), 0)
           )
      INTO v_totals
    FROM public.transactions_filtered(
           p_from, p_to, p_category_id, p_payment_source_id,
           p_uncategorized_only, p_search) f;
  END IF;

  RETURN jsonb_build_object(
    'data',     v_rows,
    'has_more', v_has_more,
    'next_key', v_next_key,
    'totals',   v_totals
  );
END;
$function$;

CREATE OR REPLACE FUNCTION public.dashboard_summary(p_from date, p_to date)
 RETURNS jsonb
 LANGUAGE sql
 STABLE
 SET search_path TO 'public', 'pg_temp'
AS $function$
  SELECT jsonb_build_object(
    'income',   COALESCE(SUM(total_amount) FILTER (WHERE movement_type = 'income'),  0),
    'expenses', COALESCE(SUM(total_amount) FILTER (WHERE movement_type = 'expense'), 0),
    'balance',  COALESCE(SUM(total_amount) FILTER (WHERE movement_type = 'income'),  0)
              - COALESCE(SUM(total_amount) FILTER (WHERE movement_type = 'expense'), 0),
    'count',    COUNT(*)
  )
  FROM (SELECT * FROM public.transactions WHERE voided_at IS NULL) transactions WHERE (p_from IS NULL OR transaction_date >= p_from)
    AND (p_to   IS NULL OR transaction_date <= p_to);
$function$;

CREATE OR REPLACE FUNCTION public.dashboard_monthly_series(p_months integer DEFAULT 6)
 RETURNS jsonb
 LANGUAGE sql
 STABLE
 SET search_path TO 'public', 'pg_temp'
AS $function$
  WITH bounds AS (
    SELECT date_trunc('month', CURRENT_DATE)::date AS current_month_start,
           GREATEST(COALESCE(p_months, 6), 1)      AS months
  ),
  months AS (
    SELECT generate_series(
             (SELECT current_month_start - ((months - 1) || ' months')::interval FROM bounds),
             (SELECT current_month_start FROM bounds),
             '1 month'::interval
           )::date AS month_start
  ),
  per_month AS (
    SELECT
      m.month_start,
      COALESCE(SUM(t.total_amount) FILTER (WHERE t.movement_type = 'income'),  0) AS income,
      COALESCE(SUM(t.total_amount) FILTER (WHERE t.movement_type = 'expense'), 0) AS expenses
    FROM months m
    LEFT JOIN (SELECT * FROM public.transactions WHERE voided_at IS NULL) t
      ON t.transaction_date >= m.month_start
     AND t.transaction_date <  (m.month_start + interval '1 month')
    GROUP BY m.month_start
  )
  SELECT COALESCE(jsonb_agg(
           jsonb_build_object(
             'month',    to_char(per_month.month_start, 'YYYY-MM'),
             'income',   per_month.income,
             'expenses', per_month.expenses
           )
           ORDER BY per_month.month_start
         ), '[]'::jsonb)
  FROM per_month;
$function$;

