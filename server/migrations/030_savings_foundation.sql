CREATE TABLE public.savings_accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  creation_request_key UUID NOT NULL UNIQUE,
  creation_fingerprint TEXT NOT NULL CHECK (btrim(creation_fingerprint) <> ''),
  name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 200 AND name=btrim(name)),
  purpose TEXT CHECK (length(purpose)<=2000),
  institution_name TEXT CHECK (length(institution_name)<=200),
  product_name TEXT CHECK (length(product_name)<=200),
  reference TEXT CHECK (length(reference)<=200),
  opened_on DATE NOT NULL,
  tracking_start_date DATE NOT NULL CHECK (tracking_start_date>=opened_on),
  currency_code TEXT NOT NULL DEFAULT 'ILS' CHECK (currency_code='ILS'),
  target_amount NUMERIC(18,2) CHECK (target_amount>0 AND target_amount::text NOT IN ('NaN','Infinity','-Infinity')),
  target_date DATE CHECK (target_date>=tracking_start_date),
  annual_interest_rate NUMERIC(12,6) CHECK (annual_interest_rate BETWEEN 0 AND 100),
  terms TEXT CHECK (length(terms)<=10000),
  liquidity_notes TEXT CHECK (length(liquidity_notes)<=10000),
  notes TEXT CHECK (length(notes)<=10000),
  release_date DATE CHECK (release_date>=opened_on),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','archived')),
  archived_at TIMESTAMPTZ,
  monthly_amount NUMERIC(18,2) CHECK (monthly_amount>0 AND monthly_amount::text NOT IN ('NaN','Infinity','-Infinity')),
  monthly_day SMALLINT CHECK (monthly_day BETWEEN 1 AND 31),
  plan_start_date DATE CHECK (plan_start_date>=tracking_start_date),
  next_due_date DATE CHECK (next_due_date>=plan_start_date),
  default_payment_source_id BIGINT REFERENCES public.payment_sources(id) ON DELETE RESTRICT,
  auto_deposit_enabled BOOLEAN NOT NULL DEFAULT false,
  plan_revision BIGINT NOT NULL DEFAULT 0 CHECK (plan_revision>=0),
  revision BIGINT NOT NULL DEFAULT 1 CHECK (revision>0),
  last_config_request_key UUID,
  last_config_fingerprint TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK ((status='archived')=(archived_at IS NOT NULL)),
  CHECK (num_nonnulls(monthly_amount,monthly_day,plan_start_date,next_due_date) IN (0,4)),
  CHECK (NOT auto_deposit_enabled OR (status='active' AND monthly_amount IS NOT NULL AND default_payment_source_id IS NOT NULL)),
  CHECK (num_nonnulls(last_config_request_key,last_config_fingerprint) IN (0,2))
);
CREATE INDEX savings_accounts_status_id ON public.savings_accounts(status,id);
CREATE INDEX savings_accounts_due ON public.savings_accounts(next_due_date,id) WHERE status='active' AND auto_deposit_enabled;
CREATE INDEX savings_accounts_payment_source ON public.savings_accounts(default_payment_source_id) WHERE default_payment_source_id IS NOT NULL;

CREATE TABLE public.savings_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id BIGINT NOT NULL REFERENCES public.savings_accounts(id) ON DELETE RESTRICT,
  command_id UUID NOT NULL,
  command_index SMALLINT NOT NULL CHECK (command_index>=0),
  command_kind TEXT NOT NULL CHECK (command_kind IN ('create_savings_account','post_savings_event','correct_savings_event','cancel_savings_event','apply_savings_surplus','reverse_savings_surplus')),
  command_fingerprint TEXT NOT NULL CHECK (btrim(command_fingerprint)<>''),
  event_kind TEXT NOT NULL CHECK (event_kind IN ('opening','deposit','withdrawal','interest_capitalized','interest_payout','occurrence_skip')),
  entry_action TEXT NOT NULL DEFAULT 'post' CHECK (entry_action IN ('post','reverse')),
  amount NUMERIC(18,2) NOT NULL CHECK (amount>=0 AND amount::text NOT IN ('NaN','Infinity','-Infinity')),
  effective_date DATE NOT NULL,
  source_kind TEXT NOT NULL CHECK (source_kind IN ('opening','manual','existing_transaction','recurring','budget_surplus','schedule_control')),
  transaction_id INTEGER REFERENCES public.transactions(id) ON DELETE RESTRICT,
  cash_movement_type TEXT CHECK (cash_movement_type IN ('expense','income')),
  cash_category_id BIGINT REFERENCES public.categories(id) ON DELETE RESTRICT,
  cash_payment_source_id BIGINT REFERENCES public.payment_sources(id) ON DELETE RESTRICT,
  cash_charge_date DATE,
  reverses_entry_id BIGINT UNIQUE REFERENCES public.savings_entries(id) ON DELETE RESTRICT,
  reversed_by_entry_id BIGINT UNIQUE REFERENCES public.savings_entries(id) ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
  supersedes_entry_id BIGINT UNIQUE REFERENCES public.savings_entries(id) ON DELETE RESTRICT,
  occurrence_month DATE,
  occurrence_root_id BIGINT REFERENCES public.savings_entries(id) ON DELETE RESTRICT,
  scheduled_due_date DATE,
  plan_revision BIGINT CHECK (plan_revision>=0),
  reason TEXT CHECK (length(reason)<=2000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(command_id,command_index),
  CHECK ((event_kind IN ('opening','occurrence_skip') OR amount>0) AND (event_kind<>'occurrence_skip' OR amount=0)),
  CHECK ((entry_action='reverse')=(reverses_entry_id IS NOT NULL)),
  CHECK (entry_action<>'reverse' OR num_nonnulls(reversed_by_entry_id,supersedes_entry_id,occurrence_month,occurrence_root_id,scheduled_due_date,plan_revision)=0),
  CHECK (num_nonnulls(transaction_id,cash_movement_type,cash_category_id,cash_payment_source_id,cash_charge_date)=CASE WHEN event_kind IN ('deposit','withdrawal','interest_payout') THEN 5 ELSE 0 END),
  CHECK (num_nonnulls(occurrence_month,scheduled_due_date,plan_revision) IN (0,3)),
  CHECK (occurrence_month IS NULL OR (entry_action='post' AND event_kind IN ('deposit','occurrence_skip') AND occurrence_month=date_trunc('month',occurrence_month)::date AND date_trunc('month',scheduled_due_date)::date=occurrence_month)),
  CHECK (occurrence_root_id IS NULL OR occurrence_month IS NOT NULL),
  CHECK (entry_action='reverse' OR (source_kind<>'recurring' AND event_kind<>'occurrence_skip') OR occurrence_month IS NOT NULL),
  CHECK (occurrence_month IS NULL OR (isfinite(occurrence_month) AND isfinite(scheduled_due_date))),
  CHECK ((event_kind='opening')=(source_kind='opening')),
  CHECK ((event_kind='occurrence_skip')=(source_kind='schedule_control')),
  CHECK (source_kind<>'budget_surplus' OR event_kind='deposit'),
  CHECK ((entry_action='post' AND supersedes_entry_id IS NULL AND event_kind<>'occurrence_skip') OR nullif(btrim(reason),'') IS NOT NULL)
);
CREATE UNIQUE INDEX savings_entries_one_opening ON public.savings_entries(account_id) WHERE event_kind='opening' AND entry_action='post' AND supersedes_entry_id IS NULL;
