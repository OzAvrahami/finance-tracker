CREATE VIEW public.savings_account_summary AS
WITH signed AS (
  SELECT account_id,event_kind,amount*CASE WHEN entry_action='post' THEN 1 ELSE -1 END AS delta FROM public.savings_entries
), totals AS (
  SELECT account_id,
    coalesce(sum(delta) FILTER (WHERE event_kind='opening'),0)::numeric(18,2) AS opening_balance,
    coalesce(sum(CASE WHEN event_kind IN ('opening','deposit','interest_capitalized') THEN delta WHEN event_kind='withdrawal' THEN -delta ELSE 0 END),0)::numeric(18,2) AS current_balance,
    coalesce(sum(delta) FILTER (WHERE event_kind='deposit'),0)::numeric(18,2) AS deposits_total,
    coalesce(sum(delta) FILTER (WHERE event_kind='withdrawal'),0)::numeric(18,2) AS withdrawals_total,
    coalesce(sum(delta) FILTER (WHERE event_kind='interest_capitalized'),0)::numeric(18,2) AS capitalized_interest_total,
    coalesce(sum(delta) FILTER (WHERE event_kind='interest_payout'),0)::numeric(18,2) AS paid_out_interest_total
  FROM signed GROUP BY account_id
)
SELECT a.id AS account_id,a.name,a.status,a.currency_code,a.tracking_start_date,a.revision,a.target_date,a.next_due_date,a.auto_deposit_enabled,a.plan_revision,
  a.target_amount::text,a.monthly_amount::text,a.annual_interest_rate::text,
  coalesce(t.opening_balance,0)::numeric(18,2)::text AS opening_balance,coalesce(t.current_balance,0)::numeric(18,2)::text AS current_balance,
  coalesce(t.deposits_total,0)::numeric(18,2)::text AS deposits_total,coalesce(t.withdrawals_total,0)::numeric(18,2)::text AS withdrawals_total,
  coalesce(t.capitalized_interest_total,0)::numeric(18,2)::text AS capitalized_interest_total,coalesce(t.paid_out_interest_total,0)::numeric(18,2)::text AS paid_out_interest_total,
  (coalesce(t.capitalized_interest_total,0)+coalesce(t.paid_out_interest_total,0))::numeric(18,2)::text AS realized_interest_total,
  CASE WHEN a.target_amount IS NOT NULL THEN greatest(a.target_amount-coalesce(t.current_balance,0),0)::numeric(18,2)::text END AS target_remaining
FROM public.savings_accounts a LEFT JOIN totals t ON t.account_id=a.id;

