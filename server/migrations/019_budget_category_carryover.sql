CREATE OR REPLACE FUNCTION public.validate_budget_carryover_transfer_insert()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_batch public.budget_carryover_batches%ROWTYPE;
  v_source public.budgets%ROWTYPE;
  v_destination public.budgets%ROWTYPE;
  v_source_operation public.budget_operations%ROWTYPE;
  v_destination_operation public.budget_operations%ROWTYPE;
  v_source_funding public.budget_funding_entries%ROWTYPE;
  v_destination_funding public.budget_funding_entries%ROWTYPE;
  v_source_movement public.budget_movements%ROWTYPE;
  v_destination_movement public.budget_movements%ROWTYPE;
BEGIN
  SELECT * INTO v_batch FROM public.budget_carryover_batches WHERE id = NEW.batch_id;
  SELECT * INTO v_source FROM public.budgets WHERE id = NEW.source_budget_id;
  SELECT * INTO v_destination FROM public.budgets WHERE id = NEW.destination_budget_id;
  SELECT * INTO v_source_operation FROM public.budget_operations WHERE id = NEW.source_operation_id;
  SELECT * INTO v_destination_operation FROM public.budget_operations WHERE id = NEW.destination_operation_id;

  IF v_source.category_id IS DISTINCT FROM v_destination.category_id THEN
    RAISE EXCEPTION 'Carryover source and destination budgets must use the same category';
  END IF;
  IF v_source.budget_month_id IS DISTINCT FROM v_batch.source_budget_month_id
     OR v_destination.budget_month_id IS DISTINCT FROM v_batch.destination_budget_month_id THEN
    RAISE EXCEPTION 'Carryover budgets do not match the batch months';
  END IF;

  IF NEW.reverses_transfer_id IS NULL THEN
    IF v_source_operation.operation_type <> 'carryover_out'
       OR v_destination_operation.operation_type <> 'carryover_in' THEN
      RAISE EXCEPTION 'Original carryover operations have invalid directions';
    END IF;
    IF EXISTS (
      SELECT 1
      FROM public.budget_carryover_transfers prior
      WHERE prior.source_budget_id = NEW.source_budget_id
        AND prior.destination_budget_id = NEW.destination_budget_id
        AND prior.reverses_transfer_id IS NULL
        AND NOT EXISTS (
          SELECT 1 FROM public.budget_carryover_transfers correction
          WHERE correction.reverses_transfer_id = prior.id
        )
    ) THEN
      RAISE EXCEPTION 'An unreversed carryover already exists for this category and month pair'
        USING ERRCODE = '23505';
    END IF;
  ELSE
    IF v_source_operation.operation_type <> 'carryover_in'
       OR v_destination_operation.operation_type <> 'carryover_out' THEN
      RAISE EXCEPTION 'Carryover reversal operations have invalid directions';
    END IF;
    IF NOT EXISTS (
      SELECT 1 FROM public.budget_carryover_transfers original
      WHERE original.id = NEW.reverses_transfer_id
        AND original.reverses_transfer_id IS NULL
        AND original.source_budget_id = NEW.source_budget_id
        AND original.destination_budget_id = NEW.destination_budget_id
        AND original.amount = NEW.amount
    ) THEN
      RAISE EXCEPTION 'Carryover reversal does not match its original transfer';
    END IF;
  END IF;

  IF v_source_operation.budget_month_id IS DISTINCT FROM v_batch.source_budget_month_id
     OR v_destination_operation.budget_month_id IS DISTINCT FROM v_batch.destination_budget_month_id THEN
    RAISE EXCEPTION 'Carryover operations do not match the batch months';
  END IF;

  SELECT * INTO v_source_funding
  FROM public.budget_funding_entries WHERE operation_id = NEW.source_operation_id;
  SELECT * INTO v_destination_funding
  FROM public.budget_funding_entries WHERE operation_id = NEW.destination_operation_id;
  SELECT * INTO v_source_movement
  FROM public.budget_movements WHERE operation_id = NEW.source_operation_id;
  SELECT * INTO v_destination_movement
  FROM public.budget_movements WHERE operation_id = NEW.destination_operation_id;

  IF NEW.reverses_transfer_id IS NULL THEN
    IF v_source_funding.source_kind <> 'carryover_transfer'
       OR v_source_funding.amount_delta <> -NEW.amount
       OR v_source_movement.source_budget_id IS DISTINCT FROM NEW.source_budget_id
       OR v_source_movement.destination_budget_id IS NOT NULL
       OR v_source_movement.amount <> NEW.amount
       OR v_destination_funding.source_kind <> 'carryover_transfer'
       OR v_destination_funding.amount_delta <> NEW.amount
       OR v_destination_movement.source_budget_id IS NOT NULL
       OR v_destination_movement.destination_budget_id IS DISTINCT FROM NEW.destination_budget_id
       OR v_destination_movement.amount <> NEW.amount THEN
      RAISE EXCEPTION 'Carryover funding and movements are not balanced';
    END IF;
  ELSE
    IF v_source_funding.source_kind <> 'carryover_transfer'
       OR v_source_funding.amount_delta <> NEW.amount
       OR v_source_movement.source_budget_id IS NOT NULL
       OR v_source_movement.destination_budget_id IS DISTINCT FROM NEW.source_budget_id
       OR v_source_movement.amount <> NEW.amount
       OR v_destination_funding.source_kind <> 'carryover_transfer'
       OR v_destination_funding.amount_delta <> -NEW.amount
       OR v_destination_movement.source_budget_id IS DISTINCT FROM NEW.destination_budget_id
       OR v_destination_movement.destination_budget_id IS NOT NULL
       OR v_destination_movement.amount <> NEW.amount THEN
      RAISE EXCEPTION 'Carryover reversal funding and movements are not balanced';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

