CREATE VIEW public.budget_carryover_settings_read AS
SELECT category_id, true AS enabled, created_at, updated_at
FROM public.budget_carryover_settings;

CREATE VIEW public.budget_category_carryover_state AS
WITH signed AS (
  SELECT
    t.source_budget_id,
    t.destination_budget_id,
    CASE WHEN t.reverses_transfer_id IS NULL THEN t.amount ELSE -t.amount END AS amount
  FROM public.budget_carryover_transfers t
)
SELECT
  b.id AS budget_id,
  coalesce(sum(s.amount) FILTER (WHERE s.destination_budget_id = b.id), 0)::numeric(18, 2)
    AS incoming_carryover,
  coalesce(sum(s.amount) FILTER (WHERE s.source_budget_id = b.id), 0)::numeric(18, 2)
    AS outgoing_carryover
FROM public.budgets b
LEFT JOIN signed s ON s.source_budget_id = b.id OR s.destination_budget_id = b.id
GROUP BY b.id;

CREATE OR REPLACE FUNCTION public.set_budget_carryover_enabled(
  p_category_id BIGINT,
  p_enabled BOOLEAN
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_category public.categories%ROWTYPE;
BEGIN
  IF p_category_id IS NULL OR p_enabled IS NULL THEN
    RAISE EXCEPTION 'category_id and enabled are required' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO v_category FROM public.categories WHERE id = p_category_id FOR SHARE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Category % does not exist', p_category_id USING ERRCODE = 'P0002';
  END IF;
  IF v_category.type <> 'expense' THEN
    RAISE EXCEPTION 'Carryover is available only for expense categories' USING ERRCODE = '23514';
  END IF;

  IF p_enabled THEN
    INSERT INTO public.budget_carryover_settings (category_id)
    VALUES (p_category_id)
    ON CONFLICT (category_id) DO UPDATE
    SET updated_at = timezone('utc'::text, now());
  ELSE
    DELETE FROM public.budget_carryover_settings WHERE category_id = p_category_id;
  END IF;

  RETURN jsonb_build_object('category_id', p_category_id, 'enabled', p_enabled);
END;
$$;

CREATE OR REPLACE FUNCTION public.budget_carryover_candidate_rows(p_destination_month TEXT)
RETURNS TABLE (
  category_id BIGINT,
  category_name TEXT,
  category_icon TEXT,
  source_budget_id BIGINT,
  destination_budget_id BIGINT,
  source_final_funded NUMERIC(18, 2),
  source_raw_actual_spent NUMERIC(18, 2),
  source_effective_actual_spent NUMERIC(18, 2),
  eligible_amount NUMERIC(18, 2),
  status TEXT,
  blocked_reason TEXT
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_destination_start DATE := public.budget_month_start_from_key(p_destination_month);
  v_source_start DATE := (v_destination_start - interval '1 month')::date;
  v_source_id BIGINT;
  v_destination_id BIGINT;
  v_destination_initialized BOOLEAN := false;
BEGIN
  SELECT id INTO v_source_id FROM public.budget_months WHERE month_start = v_source_start;
  SELECT id INTO v_destination_id FROM public.budget_months WHERE month_start = v_destination_start;
  IF v_destination_id IS NOT NULL THEN
    SELECT EXISTS (
      SELECT 1 FROM public.budget_operations
      WHERE budget_month_id = v_destination_id AND operation_type = 'month_initialization'
    ) INTO v_destination_initialized;
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.transactions
    WHERE movement_type = 'expense'
      AND transaction_date >= v_source_start
      AND transaction_date < v_destination_start
      AND total_amount::text IN ('NaN', 'Infinity', '-Infinity')
  ) OR EXISTS (
    SELECT 1 FROM public.transactions
    WHERE movement_type = 'expense'
      AND transaction_date >= v_destination_start
      AND transaction_date < (v_destination_start + interval '1 month')::date
      AND total_amount::text IN ('NaN', 'Infinity', '-Infinity')
  ) THEN
    RAISE EXCEPTION 'Carryover actual spending contains a non-finite amount' USING ERRCODE = '22003';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.transactions t
    WHERE t.movement_type = 'expense'
      AND t.transaction_date >= v_source_start
      AND t.transaction_date < (v_destination_start + interval '1 month')::date
    GROUP BY t.category_id, date_trunc('month', t.transaction_date)
    HAVING sum(t.total_amount) <> round(sum(t.total_amount), 2)
      OR abs(sum(t.total_amount)) > 9999999999999999.99
  ) THEN
    RAISE EXCEPTION 'Carryover actual spending must fit finite NUMERIC(18,2) exactly'
      USING ERRCODE = '22003';
  END IF;

  RETURN QUERY
  WITH source_actuals AS (
    SELECT t.category_id, coalesce(sum(t.total_amount), 0)::numeric(18, 2) AS actual
    FROM public.transactions t
    WHERE t.movement_type = 'expense'
      AND t.transaction_date >= v_source_start
      AND t.transaction_date < v_destination_start
    GROUP BY t.category_id
  ), destination_actuals AS (
    SELECT t.category_id, coalesce(sum(t.total_amount), 0)::numeric(18, 2) AS actual
    FROM public.transactions t
    WHERE t.movement_type = 'expense'
      AND t.transaction_date >= v_destination_start
      AND t.transaction_date < (v_destination_start + interval '1 month')::date
    GROUP BY t.category_id
  ), candidate AS (
    SELECT
      c.id AS category_id,
      c.name,
      c.icon,
      src.budget_id AS source_budget_id,
      dst.budget_id AS destination_budget_id,
      coalesce(src.final_funded, 0)::numeric(18, 2) AS source_final_funded,
      coalesce(sa.actual, 0)::numeric(18, 2) AS source_raw_actual_spent,
      greatest(coalesce(sa.actual, 0), 0)::numeric(18, 2) AS source_effective_actual_spent,
      greatest(
        coalesce(src.final_funded, 0) - greatest(coalesce(sa.actual, 0), 0),
        0
      )::numeric(18, 2) AS eligible_amount,
      c.is_active,
      src.lifecycle_state AS source_lifecycle,
      dst.lifecycle_state AS destination_lifecycle,
      coalesce(da.actual, 0)::numeric(18, 2) AS destination_actual,
      coalesce(dst.final_funded, 0)::numeric(18, 2) AS destination_final,
      rd.category_id IS NOT NULL AND NOT v_destination_initialized AS recurring_pending,
      EXISTS (
        SELECT 1
        FROM public.budget_carryover_transfers original
        WHERE original.source_budget_id = src.budget_id
          AND original.reverses_transfer_id IS NULL
          AND NOT EXISTS (
            SELECT 1 FROM public.budget_carryover_transfers correction
            WHERE correction.reverses_transfer_id = original.id
          )
      ) AS already_applied
    FROM public.budget_carryover_settings setting
    JOIN public.categories c ON c.id = setting.category_id
    LEFT JOIN public.budget_category_state src
      ON src.budget_month_id = v_source_id AND src.category_id = c.id
    LEFT JOIN source_actuals sa ON sa.category_id = c.id
    LEFT JOIN public.budget_category_state dst
      ON dst.budget_month_id = v_destination_id AND dst.category_id = c.id
    LEFT JOIN destination_actuals da ON da.category_id = c.id
    LEFT JOIN public.budget_recurring_defaults rd ON rd.category_id = c.id
    WHERE c.type = 'expense'
  )
  SELECT
    candidate.category_id,
    candidate.name,
    candidate.icon,
    candidate.source_budget_id,
    candidate.destination_budget_id,
    candidate.source_final_funded,
    candidate.source_raw_actual_spent,
    candidate.source_effective_actual_spent,
    candidate.eligible_amount,
    CASE
      WHEN candidate.already_applied THEN 'already_applied'
      WHEN NOT candidate.is_active THEN 'blocked'
      WHEN candidate.source_budget_id IS NULL THEN 'blocked'
      WHEN candidate.source_lifecycle <> 'active' THEN 'blocked'
      WHEN candidate.eligible_amount <= 0 THEN 'blocked'
      WHEN candidate.destination_budget_id IS NOT NULL
        AND candidate.destination_lifecycle <> 'active' THEN 'blocked'
      WHEN candidate.destination_budget_id IS NULL AND candidate.recurring_pending THEN 'blocked'
      WHEN candidate.destination_budget_id IS NULL AND candidate.destination_actual > 0 THEN 'blocked'
      WHEN candidate.destination_budget_id IS NOT NULL
        AND candidate.destination_actual > candidate.destination_final THEN 'blocked'
      ELSE 'ready'
    END,
    CASE
      WHEN candidate.already_applied THEN NULL
      WHEN NOT candidate.is_active THEN 'CATEGORY_INACTIVE'
      WHEN candidate.source_budget_id IS NULL THEN 'SOURCE_BUDGET_MISSING'
      WHEN candidate.source_lifecycle <> 'active' THEN 'SOURCE_BUDGET_INACTIVE'
      WHEN candidate.eligible_amount <= 0 THEN 'NO_ELIGIBLE_BALANCE'
      WHEN candidate.destination_budget_id IS NOT NULL
        AND candidate.destination_lifecycle <> 'active' THEN 'DESTINATION_BUDGET_INACTIVE'
      WHEN candidate.destination_budget_id IS NULL AND candidate.recurring_pending
        THEN 'RECURRING_INITIALIZATION_REQUIRED'
      WHEN candidate.destination_budget_id IS NULL AND candidate.destination_actual > 0
        THEN 'UNBUDGETED_ACTUAL_EXISTS'
      WHEN candidate.destination_budget_id IS NOT NULL
        AND candidate.destination_actual > candidate.destination_final THEN 'DESTINATION_DEFICIT'
      ELSE NULL
    END
  FROM candidate
  ORDER BY candidate.name, candidate.category_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.get_budget_carryover_preview(p_destination_month TEXT)
RETURNS JSONB
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_destination_start DATE := public.budget_month_start_from_key(p_destination_month);
  v_source_start DATE := (v_destination_start - interval '1 month')::date;
  v_current_start DATE := date_trunc(
    'month', timezone('Asia/Jerusalem', statement_timestamp())
  )::date;
  v_ready JSONB := '[]'::jsonb;
  v_blocked JSONB := '[]'::jsonb;
  v_applied JSONB := '[]'::jsonb;
  v_total NUMERIC(18, 2) := 0;
  v_material TEXT;
  v_fingerprint TEXT;
BEGIN
  IF v_destination_start <> v_current_start THEN
    RETURN jsonb_build_object(
      'eligible', false,
      'reason', 'CURRENT_MONTH_ONLY',
      'source_month', to_char(v_source_start, 'YYYY-MM'),
      'destination_month', p_destination_month,
      'fingerprint', md5('carryover|' || p_destination_month || '|ineligible'),
      'ready_categories', '[]'::jsonb,
      'ready_count', 0,
      'total_incoming', '0.00',
      'already_applied_categories', '[]'::jsonb,
      'blocked_categories', '[]'::jsonb,
      'can_apply', false
    );
  END IF;

  WITH rows AS (
    SELECT * FROM public.budget_carryover_candidate_rows(p_destination_month)
  )
  SELECT
    coalesce(jsonb_agg(jsonb_build_object(
      'category_id', category_id,
      'category', jsonb_build_object('name', category_name, 'icon', category_icon, 'type', 'expense'),
      'source_budget_id', source_budget_id,
      'destination_budget_id', destination_budget_id,
      'source_final_funded', source_final_funded::numeric(18, 2)::text,
      'source_raw_actual_spent', source_raw_actual_spent::numeric(18, 2)::text,
      'source_effective_actual_spent', source_effective_actual_spent::numeric(18, 2)::text,
      'amount', eligible_amount::numeric(18, 2)::text
    ) ORDER BY category_name, category_id) FILTER (WHERE status = 'ready'), '[]'::jsonb),
    coalesce(jsonb_agg(jsonb_build_object(
      'category_id', category_id,
      'category', jsonb_build_object('name', category_name, 'icon', category_icon, 'type', 'expense'),
      'source_raw_actual_spent', source_raw_actual_spent::numeric(18, 2)::text,
      'source_effective_actual_spent', source_effective_actual_spent::numeric(18, 2)::text,
      'amount', eligible_amount::numeric(18, 2)::text,
      'reason', blocked_reason
    ) ORDER BY category_name, category_id) FILTER (WHERE status = 'blocked'), '[]'::jsonb),
    coalesce(jsonb_agg(jsonb_build_object(
      'category_id', category_id,
      'category', jsonb_build_object('name', category_name, 'icon', category_icon, 'type', 'expense')
    ) ORDER BY category_name, category_id) FILTER (WHERE status = 'already_applied'), '[]'::jsonb),
    coalesce(sum(eligible_amount) FILTER (WHERE status = 'ready'), 0)::numeric(18, 2),
    coalesce(string_agg(
      category_id || '|' || coalesce(source_budget_id::text, '') || '|'
      || coalesce(destination_budget_id::text, '') || '|' || status || '|'
      || source_final_funded::numeric(18, 2)::text || '|'
      || source_raw_actual_spent::numeric(18, 2)::text || '|'
      || source_effective_actual_spent::numeric(18, 2)::text || '|'
      || eligible_amount::numeric(18, 2)::text || '|' || coalesce(blocked_reason, ''),
      ';' ORDER BY category_id
    ), '')
  INTO v_ready, v_blocked, v_applied, v_total, v_material
  FROM rows;

  v_fingerprint := md5(
    'carryover|' || to_char(v_source_start, 'YYYY-MM') || '|'
    || p_destination_month || '|' || v_material
  );

  RETURN jsonb_build_object(
    'eligible', true,
    'reason', NULL,
    'source_month', to_char(v_source_start, 'YYYY-MM'),
    'destination_month', p_destination_month,
    'fingerprint', v_fingerprint,
    'ready_categories', v_ready,
    'ready_count', jsonb_array_length(v_ready),
    'total_incoming', v_total::numeric(18, 2)::text,
    'already_applied_categories', v_applied,
    'blocked_categories', v_blocked,
    'can_apply', jsonb_array_length(v_ready) > 0
  );
END;
$$;

