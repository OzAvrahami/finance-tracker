-- Migration 019: balanced category budget carryover between adjacent months.
--
-- Carryover is an explicit, immutable, cross-month transfer. The source month
-- releases category funding and records an equal negative funding entry; the
-- destination month records equal positive funding and category allocation.
-- No read path in this migration creates financial state.

BEGIN;

DO $$
BEGIN
  IF to_regclass('public.budget_months') IS NULL
     OR to_regclass('public.budget_operations') IS NULL
     OR to_regclass('public.budget_recurring_defaults') IS NULL
     OR to_regprocedure('public.get_funded_budget_month(text)') IS NULL
     OR to_regprocedure('public.get_budget_recurring_preview(text)') IS NULL
     OR to_regprocedure('public.budget_assert_reconciled(bigint)') IS NULL THEN
    RAISE EXCEPTION 'Migration 019 preflight: funded budget foundation and recurring defaults from Migrations 017 and 018 are required';
  END IF;

  IF to_regclass('public.budget_carryover_settings') IS NOT NULL
     OR to_regclass('public.budget_carryover_batches') IS NOT NULL
     OR to_regclass('public.budget_carryover_transfers') IS NOT NULL THEN
    RAISE EXCEPTION 'Migration 019 preflight: unexpected partial carryover schema exists';
  END IF;
END;
$$;

ALTER TABLE public.budgets
  DROP CONSTRAINT budgets_starting_kind_check,
  ADD CONSTRAINT budgets_starting_kind_check CHECK (
    starting_kind IN (
      'manual', 'legacy_import', 'copied', 'recurring_default', 'carryover_only'
    )
  );

ALTER TABLE public.budget_operations
  DROP CONSTRAINT budget_operations_operation_type_check,
  ADD CONSTRAINT budget_operations_operation_type_check CHECK (operation_type IN (
    'legacy_import',
    'manual_funding',
    'establish_budget',
    'adjustment',
    'removal',
    'reactivation',
    'copy',
    'reversal',
    'month_initialization',
    'carryover_out',
    'carryover_in'
  ));

ALTER TABLE public.budget_funding_entries
  DROP CONSTRAINT budget_funding_entries_source_kind_check,
  ADD CONSTRAINT budget_funding_entries_source_kind_check CHECK (
    source_kind IN ('manual_available_funds', 'legacy_import', 'carryover_transfer')
  ),
  DROP CONSTRAINT budget_funding_entry_amount_shape,
  ADD CONSTRAINT budget_funding_entry_amount_shape CHECK (
    amount_delta::text NOT IN ('NaN', 'Infinity', '-Infinity')
    AND (
      (source_kind = 'legacy_import' AND amount_delta >= 0 AND reverses_funding_entry_id IS NULL)
      OR (source_kind = 'manual_available_funds' AND amount_delta <> 0)
      OR (source_kind = 'carryover_transfer' AND amount_delta <> 0)
    )
  );

CREATE TABLE public.budget_carryover_settings (
  category_id BIGINT PRIMARY KEY REFERENCES public.categories(id) ON DELETE RESTRICT,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE TABLE public.budget_carryover_batches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_key UUID NOT NULL UNIQUE,
  request_fingerprint TEXT NOT NULL CHECK (btrim(request_fingerprint) <> ''),
  source_budget_month_id BIGINT NOT NULL REFERENCES public.budget_months(id) ON DELETE RESTRICT,
  destination_budget_month_id BIGINT NOT NULL REFERENCES public.budget_months(id) ON DELETE RESTRICT,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT timezone('utc'::text, now()),
  CONSTRAINT budget_carryover_batches_distinct_months CHECK (
    source_budget_month_id <> destination_budget_month_id
  )
);

CREATE TABLE public.budget_carryover_transfers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id BIGINT NOT NULL REFERENCES public.budget_carryover_batches(id) ON DELETE RESTRICT,
  source_budget_id BIGINT NOT NULL REFERENCES public.budgets(id) ON DELETE RESTRICT,
  destination_budget_id BIGINT NOT NULL REFERENCES public.budgets(id) ON DELETE RESTRICT,
  source_operation_id BIGINT NOT NULL UNIQUE REFERENCES public.budget_operations(id) ON DELETE RESTRICT,
  destination_operation_id BIGINT NOT NULL UNIQUE REFERENCES public.budget_operations(id) ON DELETE RESTRICT,
  amount NUMERIC(18, 2) NOT NULL,
  source_final_funded_snapshot NUMERIC(18, 2) NOT NULL,
  source_raw_actual_spent_snapshot NUMERIC(18, 2) NOT NULL,
  source_effective_actual_spent_snapshot NUMERIC(18, 2) NOT NULL,
  reverses_transfer_id BIGINT UNIQUE REFERENCES public.budget_carryover_transfers(id) ON DELETE RESTRICT,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT timezone('utc'::text, now()),
  CONSTRAINT budget_carryover_transfer_amount_check CHECK (
    amount::text NOT IN ('NaN', 'Infinity', '-Infinity') AND amount > 0
  ),
  CONSTRAINT budget_carryover_transfer_final_snapshot_check CHECK (
    source_final_funded_snapshot::text NOT IN ('NaN', 'Infinity', '-Infinity')
    AND source_final_funded_snapshot >= 0
  ),
  CONSTRAINT budget_carryover_transfer_raw_actual_snapshot_check CHECK (
    source_raw_actual_spent_snapshot::text NOT IN ('NaN', 'Infinity', '-Infinity')
  ),
  CONSTRAINT budget_carryover_transfer_effective_actual_snapshot_check CHECK (
    source_effective_actual_spent_snapshot::text NOT IN ('NaN', 'Infinity', '-Infinity')
    AND source_effective_actual_spent_snapshot >= 0
  ),
  CONSTRAINT budget_carryover_transfer_distinct_budgets CHECK (
    source_budget_id <> destination_budget_id
  ),
  CONSTRAINT budget_carryover_transfer_not_self_reversing CHECK (
    reverses_transfer_id IS NULL OR reverses_transfer_id <> id
  )
);

