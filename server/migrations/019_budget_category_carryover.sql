-- Preserve the recurring-aware Migration 018 read and add carryover preview,
-- per-category composition, and immutable transfer history.
ALTER FUNCTION public.get_funded_budget_month(TEXT)
  RENAME TO get_funded_budget_month_recurring;

CREATE OR REPLACE FUNCTION public.get_funded_budget_month(p_month TEXT)
RETURNS JSONB
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_state JSONB := public.get_funded_budget_month_recurring(p_month);
  v_month_start DATE := public.budget_month_start_from_key(p_month);
  v_categories JSONB;
  v_history JSONB;
BEGIN
  SELECT coalesce(jsonb_agg(
    item || jsonb_build_object(
      'incoming_carryover', coalesce(cs.incoming_carryover, 0)::numeric(18, 2)::text,
      'outgoing_carryover', coalesce(cs.outgoing_carryover, 0)::numeric(18, 2)::text
    ) ORDER BY ordinality
  ), '[]'::jsonb)
  INTO v_categories
  FROM jsonb_array_elements(coalesce(v_state->'categories', '[]'::jsonb)) WITH ORDINALITY category(item, ordinality)
  LEFT JOIN public.budget_category_carryover_state cs
    ON cs.budget_id = NULLIF(item->>'budget_id', '')::bigint;

  SELECT coalesce(jsonb_agg(jsonb_build_object(
    'transfer_id', t.id,
    'batch_id', t.batch_id,
    'source_month', to_char(source_month.month_start, 'YYYY-MM'),
    'destination_month', to_char(destination_month.month_start, 'YYYY-MM'),
    'category_id', source_budget.category_id,
    'amount', t.amount::numeric(18, 2)::text,
    'source_final_funded_snapshot', t.source_final_funded_snapshot::numeric(18, 2)::text,
    'source_raw_actual_spent_snapshot', t.source_raw_actual_spent_snapshot::numeric(18, 2)::text,
    'source_effective_actual_spent_snapshot', t.source_effective_actual_spent_snapshot::numeric(18, 2)::text,
    'reverses_transfer_id', t.reverses_transfer_id,
    'created_at', t.created_at
  ) ORDER BY t.id), '[]'::jsonb)
  INTO v_history
  FROM public.budget_carryover_transfers t
  JOIN public.budget_carryover_batches batch ON batch.id = t.batch_id
  JOIN public.budget_months source_month ON source_month.id = batch.source_budget_month_id
  JOIN public.budget_months destination_month ON destination_month.id = batch.destination_budget_month_id
  JOIN public.budgets source_budget ON source_budget.id = t.source_budget_id
  WHERE source_month.month_start = v_month_start OR destination_month.month_start = v_month_start;

  RETURN v_state
    || jsonb_build_object('categories', v_categories)
    || jsonb_build_object('carryover', public.get_budget_carryover_preview(p_month))
    || jsonb_build_object('carryover_history', v_history);
END;
$$;

CREATE OR REPLACE FUNCTION public.apply_budget_carryover(
  p_destination_month TEXT,
  p_request_key UUID,
  p_preview_fingerprint TEXT,
  p_reason TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_destination_start DATE := public.budget_month_start_from_key(p_destination_month);
  v_source_start DATE := (v_destination_start - interval '1 month')::date;
  v_current_start DATE := date_trunc(
    'month', timezone('Asia/Jerusalem', statement_timestamp())
  )::date;
  v_source_month_id BIGINT;
  v_destination_month_id BIGINT;
  v_batch_id BIGINT;
  v_existing public.budget_carryover_batches%ROWTYPE;
  v_preview JSONB;
  v_fingerprint TEXT;
  v_source_operation_id BIGINT;
  v_destination_operation_id BIGINT;
  v_destination_budget_id BIGINT;
  candidate RECORD;
BEGIN
  IF p_request_key IS NULL OR p_preview_fingerprint IS NULL
     OR p_preview_fingerprint !~ '^[0-9a-f]{32}$' THEN
    RAISE EXCEPTION 'request_key and a valid preview fingerprint are required' USING ERRCODE = '22023';
  END IF;
  IF v_destination_start <> v_current_start THEN
    RAISE EXCEPTION 'Carryover can be applied only to the current Asia/Jerusalem month'
      USING ERRCODE = '22023';
  END IF;

  SELECT * INTO v_existing FROM public.budget_carryover_batches WHERE request_key = p_request_key;
  IF FOUND THEN
    IF v_existing.request_fingerprint <> 'carryover_apply|' || p_destination_month || '|' || p_preview_fingerprint THEN
      RAISE EXCEPTION 'request_key was already used for a different carryover request'
        USING ERRCODE = '23505';
    END IF;
    RETURN jsonb_build_object(
      'source', public.get_funded_budget_month(to_char(v_source_start, 'YYYY-MM')),
      'destination', public.get_funded_budget_month(p_destination_month)
    );
  END IF;

  SELECT id INTO v_source_month_id FROM public.budget_months WHERE month_start = v_source_start;
  IF v_source_month_id IS NULL THEN
    RAISE EXCEPTION 'Previous month has no funded budget state' USING ERRCODE = '23514';
  END IF;

  -- Transaction writes take ROW EXCLUSIVE on this table. Taking SHARE before
  -- any budget-month lock gives apply a short, deadlock-safe serialization
  -- boundary: the captured actuals cannot change through the final write.
  LOCK TABLE public.transactions IN SHARE MODE;

  INSERT INTO public.budget_months (month_start) VALUES (v_destination_start)
  ON CONFLICT (month_start) DO NOTHING;
  SELECT id INTO v_destination_month_id FROM public.budget_months WHERE month_start = v_destination_start;

  -- Canonical cross-month order: month rows by ID, budget rows by ID,
  -- settings/categories, then immutable operations and history.
  PERFORM 1 FROM public.budget_months
  WHERE id IN (v_source_month_id, v_destination_month_id)
  ORDER BY id FOR UPDATE;
  PERFORM 1 FROM public.budgets
  WHERE budget_month_id IN (v_source_month_id, v_destination_month_id)
  ORDER BY id FOR UPDATE;
  PERFORM 1 FROM public.categories c
  JOIN public.budget_carryover_settings setting ON setting.category_id = c.id
  ORDER BY c.id FOR SHARE OF c;
  PERFORM 1 FROM public.budget_carryover_settings
  ORDER BY category_id FOR SHARE;

  PERFORM public.budget_assert_reconciled(v_source_month_id);
  PERFORM public.budget_assert_reconciled(v_destination_month_id);

  -- A concurrent retry may have observed no batch before waiting on the
  -- canonical month locks. Re-check after serialization before writing.
  SELECT * INTO v_existing FROM public.budget_carryover_batches WHERE request_key = p_request_key;
  IF FOUND THEN
    IF v_existing.request_fingerprint <> 'carryover_apply|' || p_destination_month || '|' || p_preview_fingerprint THEN
      RAISE EXCEPTION 'request_key was already used for a different carryover request'
        USING ERRCODE = '23505';
    END IF;
    RETURN jsonb_build_object(
      'source', public.get_funded_budget_month(to_char(v_source_start, 'YYYY-MM')),
      'destination', public.get_funded_budget_month(p_destination_month)
    );
  END IF;

  v_preview := public.get_budget_carryover_preview(p_destination_month);
  v_fingerprint := v_preview->>'fingerprint';
  IF v_fingerprint IS DISTINCT FROM p_preview_fingerprint THEN
    RAISE EXCEPTION 'CARRYOVER_PREVIEW_STALE: carryover candidate material changed; refresh before applying'
      USING ERRCODE = '40001';
  END IF;

  INSERT INTO public.budget_carryover_batches (
    request_key, request_fingerprint, source_budget_month_id, destination_budget_month_id
  ) VALUES (
    p_request_key,
    'carryover_apply|' || p_destination_month || '|' || p_preview_fingerprint,
    v_source_month_id,
    v_destination_month_id
  ) RETURNING id INTO v_batch_id;

  FOR candidate IN
    SELECT item
    FROM jsonb_array_elements(v_preview->'ready_categories') AS captured(item)
    ORDER BY (item->>'category_id')::bigint
  LOOP
    INSERT INTO public.budget_operations (
      budget_month_id, request_key, request_fingerprint, operation_type, effective_date, reason
    ) VALUES (
      v_source_month_id,
      public.budget_derived_request_key(p_request_key, 'source|' || (candidate.item->>'category_id')),
      'carryover_out|' || v_batch_id || '|' || (candidate.item->>'category_id') || '|' || (candidate.item->>'amount'),
      'carryover_out', v_source_start, p_reason
    ) RETURNING id INTO v_source_operation_id;

    INSERT INTO public.budget_funding_entries (
      operation_id, amount_delta, source_kind, source_label
    ) VALUES (
      v_source_operation_id, -(candidate.item->>'amount')::numeric(18, 2), 'carryover_transfer',
      'Carryover to ' || p_destination_month
    );
    INSERT INTO public.budget_movements (
      operation_id, source_budget_id, destination_budget_id, amount
    ) VALUES (
      v_source_operation_id, (candidate.item->>'source_budget_id')::bigint, NULL,
      (candidate.item->>'amount')::numeric(18, 2)
    );

    INSERT INTO public.budget_operations (
      budget_month_id, request_key, request_fingerprint, operation_type, effective_date, reason
    ) VALUES (
      v_destination_month_id,
      public.budget_derived_request_key(p_request_key, 'destination|' || (candidate.item->>'category_id')),
      'carryover_in|' || v_batch_id || '|' || (candidate.item->>'category_id') || '|' || (candidate.item->>'amount'),
      'carryover_in', v_destination_start, p_reason
    ) RETURNING id INTO v_destination_operation_id;

    IF candidate.item->>'destination_budget_id' IS NULL THEN
      INSERT INTO public.budgets (
        category_id, month, amount, budget_month_id, starting_amount,
        starting_kind, created_by_operation_id
      ) VALUES (
        (candidate.item->>'category_id')::bigint, p_destination_month, 0, v_destination_month_id,
        0, 'carryover_only', v_destination_operation_id
      ) RETURNING id INTO v_destination_budget_id;
      INSERT INTO public.budget_lifecycle_events (operation_id, budget_id, state)
      VALUES (v_destination_operation_id, v_destination_budget_id, 'active');
    ELSE
      v_destination_budget_id := (candidate.item->>'destination_budget_id')::bigint;
    END IF;

    INSERT INTO public.budget_funding_entries (
      operation_id, amount_delta, source_kind, source_label
    ) VALUES (
      v_destination_operation_id, (candidate.item->>'amount')::numeric(18, 2), 'carryover_transfer',
      'Carryover from ' || to_char(v_source_start, 'YYYY-MM')
    );
    INSERT INTO public.budget_movements (
      operation_id, source_budget_id, destination_budget_id, amount
    ) VALUES (
      v_destination_operation_id, NULL, v_destination_budget_id,
      (candidate.item->>'amount')::numeric(18, 2)
    );

    INSERT INTO public.budget_carryover_transfers (
      batch_id, source_budget_id, destination_budget_id,
      source_operation_id, destination_operation_id, amount,
      source_final_funded_snapshot, source_raw_actual_spent_snapshot,
      source_effective_actual_spent_snapshot
    ) VALUES (
      v_batch_id, (candidate.item->>'source_budget_id')::bigint, v_destination_budget_id,
      v_source_operation_id, v_destination_operation_id,
      (candidate.item->>'amount')::numeric(18, 2),
      (candidate.item->>'source_final_funded')::numeric(18, 2),
      (candidate.item->>'source_raw_actual_spent')::numeric(18, 2),
      (candidate.item->>'source_effective_actual_spent')::numeric(18, 2)
    );
  END LOOP;

  PERFORM public.budget_assert_reconciled(v_source_month_id);
  PERFORM public.budget_assert_reconciled(v_destination_month_id);
  RETURN jsonb_build_object(
    'source', public.get_funded_budget_month(to_char(v_source_start, 'YYYY-MM')),
    'destination', public.get_funded_budget_month(p_destination_month)
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.reverse_budget_carryover(
  p_transfer_id BIGINT,
  p_request_key UUID,
  p_reason TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_original public.budget_carryover_transfers%ROWTYPE;
  v_batch public.budget_carryover_batches%ROWTYPE;
  v_source public.budget_category_state%ROWTYPE;
  v_destination public.budget_category_state%ROWTYPE;
  v_source_month public.budget_months%ROWTYPE;
  v_destination_month public.budget_months%ROWTYPE;
  v_destination_actual NUMERIC(18, 2);
  v_existing public.budget_operations%ROWTYPE;
  v_source_operation_id BIGINT;
  v_destination_operation_id BIGINT;
  v_source_funding public.budget_funding_entries%ROWTYPE;
  v_destination_funding public.budget_funding_entries%ROWTYPE;
BEGIN
  IF p_transfer_id IS NULL OR p_request_key IS NULL THEN
    RAISE EXCEPTION 'transfer_id and request_key are required' USING ERRCODE = '22023';
  END IF;
  SELECT * INTO v_original FROM public.budget_carryover_transfers WHERE id = p_transfer_id;
  IF NOT FOUND OR v_original.reverses_transfer_id IS NOT NULL THEN
    RAISE EXCEPTION 'Original carryover transfer % does not exist', p_transfer_id USING ERRCODE = 'P0002';
  END IF;
  SELECT * INTO v_batch FROM public.budget_carryover_batches WHERE id = v_original.batch_id;

  SELECT * INTO v_existing FROM public.budget_operations WHERE request_key = p_request_key;
  IF FOUND THEN
    IF v_existing.operation_type <> 'carryover_out'
       OR v_existing.request_fingerprint <> 'carryover_reverse|' || p_transfer_id THEN
      RAISE EXCEPTION 'request_key was already used for a different carryover request'
        USING ERRCODE = '23505';
    END IF;
    RETURN jsonb_build_object(
      'source', public.get_funded_budget_month((SELECT month FROM public.budget_month_funding_state WHERE budget_month_id = v_batch.source_budget_month_id)),
      'destination', public.get_funded_budget_month((SELECT month FROM public.budget_month_funding_state WHERE budget_month_id = v_batch.destination_budget_month_id))
    );
  END IF;
  IF EXISTS (SELECT 1 FROM public.budget_carryover_transfers WHERE reverses_transfer_id = p_transfer_id) THEN
    RAISE EXCEPTION 'Carryover transfer % has already been reversed', p_transfer_id USING ERRCODE = '23505';
  END IF;

  -- Keep the destination-spending safety check linearizable with transaction
  -- inserts, updates, and deletes for the duration of the compensating write.
  LOCK TABLE public.transactions IN SHARE MODE;

  PERFORM 1 FROM public.budget_months
  WHERE id IN (v_batch.source_budget_month_id, v_batch.destination_budget_month_id)
  ORDER BY id FOR UPDATE;
  PERFORM 1 FROM public.budgets
  WHERE id IN (v_original.source_budget_id, v_original.destination_budget_id)
  ORDER BY id FOR UPDATE;

  -- Re-check idempotency and prior reversal after the shared month/budget
  -- lock order has serialized concurrent correction attempts.
  SELECT * INTO v_existing FROM public.budget_operations WHERE request_key = p_request_key;
  IF FOUND THEN
    IF v_existing.operation_type <> 'carryover_out'
       OR v_existing.request_fingerprint <> 'carryover_reverse|' || p_transfer_id THEN
      RAISE EXCEPTION 'request_key was already used for a different carryover request'
        USING ERRCODE = '23505';
    END IF;
    RETURN jsonb_build_object(
      'source', public.get_funded_budget_month((SELECT month FROM public.budget_month_funding_state WHERE budget_month_id = v_batch.source_budget_month_id)),
      'destination', public.get_funded_budget_month((SELECT month FROM public.budget_month_funding_state WHERE budget_month_id = v_batch.destination_budget_month_id))
    );
  END IF;
  IF EXISTS (SELECT 1 FROM public.budget_carryover_transfers WHERE reverses_transfer_id = p_transfer_id) THEN
    RAISE EXCEPTION 'Carryover transfer % has already been reversed', p_transfer_id USING ERRCODE = '23505';
  END IF;

  SELECT * INTO v_source FROM public.budget_category_state WHERE budget_id = v_original.source_budget_id;
  SELECT * INTO v_destination FROM public.budget_category_state WHERE budget_id = v_original.destination_budget_id;
  SELECT * INTO v_source_month FROM public.budget_months WHERE id = v_batch.source_budget_month_id;
  SELECT * INTO v_destination_month FROM public.budget_months WHERE id = v_batch.destination_budget_month_id;
  IF v_source.lifecycle_state <> 'active' OR v_destination.lifecycle_state <> 'active' THEN
    RAISE EXCEPTION 'Carryover reversal requires active source and destination budgets'
      USING ERRCODE = '23514';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.transactions
    WHERE movement_type = 'expense'
      AND category_id = v_destination.category_id
      AND transaction_date >= v_destination_month.month_start
      AND transaction_date < (v_destination_month.month_start + interval '1 month')::date
      AND total_amount::text IN ('NaN', 'Infinity', '-Infinity')
  ) THEN
    RAISE EXCEPTION 'Carryover actual spending contains a non-finite amount' USING ERRCODE = '22003';
  END IF;
  SELECT greatest(coalesce(sum(total_amount), 0), 0)::numeric(18, 2)
  INTO v_destination_actual
  FROM public.transactions
  WHERE movement_type = 'expense'
    AND category_id = v_destination.category_id
    AND transaction_date >= v_destination_month.month_start
    AND transaction_date < (v_destination_month.month_start + interval '1 month')::date;
  IF v_original.amount > greatest(v_destination.final_funded - v_destination_actual, 0) THEN
    RAISE EXCEPTION 'Carryover reversal would release spent destination funding'
      USING ERRCODE = '23514';
  END IF;

  SELECT * INTO v_source_funding FROM public.budget_funding_entries
  WHERE operation_id = v_original.source_operation_id;
  SELECT * INTO v_destination_funding FROM public.budget_funding_entries
  WHERE operation_id = v_original.destination_operation_id;

  INSERT INTO public.budget_operations (
    budget_month_id, request_key, request_fingerprint, operation_type,
    effective_date, reason, reverses_operation_id
  ) VALUES (
    v_batch.destination_budget_month_id, p_request_key,
    'carryover_reverse|' || p_transfer_id, 'carryover_out',
    v_destination_month.month_start, p_reason, v_original.destination_operation_id
  ) RETURNING id INTO v_destination_operation_id;
  INSERT INTO public.budget_funding_entries (
    operation_id, amount_delta, source_kind, source_label, reverses_funding_entry_id
  ) VALUES (
    v_destination_operation_id, -v_original.amount, 'carryover_transfer',
    'Carryover reversal to ' || to_char(v_source_month.month_start, 'YYYY-MM'),
    v_destination_funding.id
  );
  INSERT INTO public.budget_movements (operation_id, source_budget_id, amount)
  VALUES (v_destination_operation_id, v_original.destination_budget_id, v_original.amount);

  INSERT INTO public.budget_operations (
    budget_month_id, request_key, request_fingerprint, operation_type,
    effective_date, reason, reverses_operation_id
  ) VALUES (
    v_batch.source_budget_month_id,
    public.budget_derived_request_key(p_request_key, 'source-return'),
    'carryover_reverse_return|' || p_transfer_id, 'carryover_in',
    v_source_month.month_start, p_reason, v_original.source_operation_id
  ) RETURNING id INTO v_source_operation_id;
  INSERT INTO public.budget_funding_entries (
    operation_id, amount_delta, source_kind, source_label, reverses_funding_entry_id
  ) VALUES (
    v_source_operation_id, v_original.amount, 'carryover_transfer',
    'Carryover reversal from ' || to_char(v_destination_month.month_start, 'YYYY-MM'),
    v_source_funding.id
  );
  INSERT INTO public.budget_movements (operation_id, destination_budget_id, amount)
  VALUES (v_source_operation_id, v_original.source_budget_id, v_original.amount);

  INSERT INTO public.budget_carryover_transfers (
    batch_id, source_budget_id, destination_budget_id,
    source_operation_id, destination_operation_id, amount,
    source_final_funded_snapshot, source_raw_actual_spent_snapshot,
    source_effective_actual_spent_snapshot,
    reverses_transfer_id
  ) VALUES (
    v_original.batch_id, v_original.source_budget_id, v_original.destination_budget_id,
    v_source_operation_id, v_destination_operation_id, v_original.amount,
    v_original.source_final_funded_snapshot, v_original.source_raw_actual_spent_snapshot,
    v_original.source_effective_actual_spent_snapshot,
