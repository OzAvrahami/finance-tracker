CREATE OR REPLACE FUNCTION public.validate_budget_carryover_batch_insert()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_source DATE;
  v_destination DATE;
BEGIN
  SELECT month_start INTO v_source FROM public.budget_months WHERE id = NEW.source_budget_month_id;
  SELECT month_start INTO v_destination FROM public.budget_months WHERE id = NEW.destination_budget_month_id;
  IF v_source IS NULL OR v_destination IS NULL
     OR v_destination <> (v_source + interval '1 month')::date THEN
    RAISE EXCEPTION 'Carryover must link consecutive calendar months'
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;

