-- Migration 020: month-specific funded-budget base overrides.
--
-- Override rows are mutable planning configuration. Once a category snapshot
-- exists, the funded result is represented only by immutable operations,
-- movements, lifecycle events, and append-only override provenance.

BEGIN;

DO $$
BEGIN
  IF to_regclass('public.budget_months') IS NULL
     OR to_regclass('public.budget_carryover_transfers') IS NULL
     OR to_regclass('public.budget_recurring_defaults') IS NULL
     OR to_regprocedure('public.get_funded_budget_month(text)') IS NULL
     OR to_regprocedure('public.budget_derived_request_key(uuid,text)') IS NULL THEN
    RAISE EXCEPTION 'Migration 020 preflight: Migrations 017, 018, and 019 are required';
  END IF;
  IF to_regclass('public.budget_month_overrides') IS NOT NULL
     OR to_regclass('public.budget_month_override_events') IS NOT NULL
     OR to_regclass('public.budget_category_base_state') IS NOT NULL
     OR to_regprocedure('public.set_budget_month_override(text,bigint,numeric,uuid,text)') IS NOT NULL
     OR to_regprocedure('public.remove_budget_month_override(text,bigint,uuid,text)') IS NOT NULL THEN
    RAISE EXCEPTION 'Migration 020 preflight: unexpected partial month-override schema exists';
  END IF;
END;
$$;

ALTER TABLE public.budgets
  DROP CONSTRAINT budgets_starting_kind_check,
  ADD CONSTRAINT budgets_starting_kind_check CHECK (
    starting_kind IN (
      'manual', 'legacy_import', 'copied', 'recurring_default',
      'carryover_only', 'monthly_override'
    )
  );

ALTER TABLE public.budget_operations
  DROP CONSTRAINT budget_operations_operation_type_check,
  ADD CONSTRAINT budget_operations_operation_type_check CHECK (operation_type IN (
    'legacy_import', 'manual_funding', 'establish_budget', 'adjustment',
    'removal', 'reactivation', 'copy', 'reversal', 'month_initialization',
    'carryover_out', 'carryover_in', 'monthly_override_set',
    'monthly_override_remove'
  ));

CREATE TABLE public.budget_month_overrides (
  budget_month_id BIGINT NOT NULL REFERENCES public.budget_months(id) ON DELETE RESTRICT,
  category_id BIGINT NOT NULL REFERENCES public.categories(id) ON DELETE RESTRICT,
  amount NUMERIC(18, 2) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT timezone('utc'::text, now()),
  PRIMARY KEY (budget_month_id, category_id),
  CONSTRAINT budget_month_overrides_amount_check CHECK (
    amount::text NOT IN ('NaN', 'Infinity', '-Infinity') AND amount >= 0
  )
);

CREATE TABLE public.budget_month_override_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_key UUID NOT NULL UNIQUE,
  request_fingerprint TEXT NOT NULL CHECK (btrim(request_fingerprint) <> ''),
  budget_month_id BIGINT NOT NULL REFERENCES public.budget_months(id) ON DELETE RESTRICT,
  category_id BIGINT NOT NULL REFERENCES public.categories(id) ON DELETE RESTRICT,
  budget_id BIGINT REFERENCES public.budgets(id) ON DELETE RESTRICT,
  financial_operation_id BIGINT REFERENCES public.budget_operations(id) ON DELETE RESTRICT,
  action TEXT NOT NULL CHECK (action IN ('set', 'remove', 'initialize')),
  requested_override_amount NUMERIC(18, 2),
  previous_effective_base NUMERIC(18, 2) NOT NULL,
  resulting_effective_base NUMERIC(18, 2) NOT NULL,
  fallback_base_snapshot NUMERIC(18, 2) NOT NULL,
  fallback_source TEXT NOT NULL CHECK (fallback_source IN (
    'none', 'manual', 'legacy_import', 'copied', 'recurring_default',
    'carryover_only', 'monthly_override'
  )),
  applied_base_delta NUMERIC(18, 2) NOT NULL,
  reverses_event_id BIGINT UNIQUE REFERENCES public.budget_month_override_events(id) ON DELETE RESTRICT,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT timezone('utc'::text, now()),
  CONSTRAINT budget_month_override_events_money_check CHECK (
    previous_effective_base::text NOT IN ('NaN', 'Infinity', '-Infinity')
    AND resulting_effective_base::text NOT IN ('NaN', 'Infinity', '-Infinity')
    AND fallback_base_snapshot::text NOT IN ('NaN', 'Infinity', '-Infinity')
    AND applied_base_delta::text NOT IN ('NaN', 'Infinity', '-Infinity')
    AND previous_effective_base >= 0
    AND resulting_effective_base >= 0
    AND fallback_base_snapshot >= 0
    AND (requested_override_amount IS NULL OR (
      requested_override_amount::text NOT IN ('NaN', 'Infinity', '-Infinity')
      AND requested_override_amount >= 0
    ))
  ),
  CONSTRAINT budget_month_override_events_action_amount_check CHECK (
    (action IN ('set', 'initialize') AND requested_override_amount IS NOT NULL)
    OR (action = 'remove' AND requested_override_amount IS NULL)
  ),
  CONSTRAINT budget_month_override_events_not_self_reversing CHECK (
    reverses_event_id IS NULL OR reverses_event_id <> id
  )
);

CREATE INDEX idx_budget_month_override_events_month_category
  ON public.budget_month_override_events (budget_month_id, category_id, id);
CREATE INDEX idx_budget_month_override_events_budget
  ON public.budget_month_override_events (budget_id, id)
  WHERE budget_id IS NOT NULL;

CREATE OR REPLACE FUNCTION public.validate_budget_month_override()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM public.categories
    WHERE id = NEW.category_id AND type = 'expense' AND is_active = true
  ) THEN
    RAISE EXCEPTION 'Month overrides are available only for active expense categories'
      USING ERRCODE = '23514';
  END IF;
  IF NEW.amount::text IN ('NaN', 'Infinity', '-Infinity') OR NEW.amount < 0 THEN
    RAISE EXCEPTION 'Month override amount must be a finite nonnegative NUMERIC(18,2) value'
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.prevent_category_type_with_month_override()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
  IF (OLD.type = 'expense' AND NEW.type <> 'expense'
      OR OLD.is_active = true AND NEW.is_active = false)
     AND EXISTS (
       SELECT 1 FROM public.budget_month_overrides WHERE category_id = OLD.id
     ) THEN
    RAISE EXCEPTION 'Remove month overrides before changing this category type or active state'
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.validate_budget_month_override_event()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_budget public.budgets%ROWTYPE;
  v_operation public.budget_operations%ROWTYPE;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.categories WHERE id = NEW.category_id AND type = 'expense') THEN
    RAISE EXCEPTION 'Month override events require an expense category' USING ERRCODE = '23514';
  END IF;
  IF NEW.budget_id IS NOT NULL THEN
    SELECT * INTO v_budget FROM public.budgets WHERE id = NEW.budget_id;
    IF NOT FOUND OR v_budget.budget_month_id <> NEW.budget_month_id
       OR v_budget.category_id <> NEW.category_id THEN
      RAISE EXCEPTION 'Month override event budget does not match its month/category'
        USING ERRCODE = '23514';
    END IF;
  END IF;
  IF NEW.financial_operation_id IS NOT NULL THEN
    SELECT * INTO v_operation FROM public.budget_operations WHERE id = NEW.financial_operation_id;
    IF NOT FOUND OR v_operation.budget_month_id <> NEW.budget_month_id
       OR v_operation.operation_type NOT IN ('monthly_override_set', 'monthly_override_remove', 'month_initialization') THEN
      RAISE EXCEPTION 'Month override event operation does not match its month/action'
        USING ERRCODE = '23514';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER budget_month_overrides_validate
BEFORE INSERT OR UPDATE ON public.budget_month_overrides
FOR EACH ROW EXECUTE FUNCTION public.validate_budget_month_override();
CREATE TRIGGER categories_month_override_guard
BEFORE UPDATE OF type, is_active ON public.categories
FOR EACH ROW EXECUTE FUNCTION public.prevent_category_type_with_month_override();
CREATE TRIGGER budget_month_override_events_validate
BEFORE INSERT ON public.budget_month_override_events
FOR EACH ROW EXECUTE FUNCTION public.validate_budget_month_override_event();
CREATE TRIGGER budget_month_override_events_immutable
BEFORE UPDATE OR DELETE ON public.budget_month_override_events
FOR EACH ROW EXECUTE FUNCTION public.prevent_budget_history_mutation();

CREATE VIEW public.budget_month_overrides_read AS
SELECT
  mo.budget_month_id,
  to_char(bm.month_start, 'YYYY-MM') AS month,
  mo.category_id,
  mo.amount::numeric(18, 2)::text AS amount_text,
  mo.created_at,
  mo.updated_at
FROM public.budget_month_overrides mo
JOIN public.budget_months bm ON bm.id = mo.budget_month_id;

-- This view is the authoritative base/carryover/other-adjustment decomposition.
-- Starting snapshots and all movements remain immutable; no mutable override row
-- is used to calculate funded history.
CREATE VIEW public.budget_category_base_state AS
WITH override_events AS (
  SELECT
    e.budget_id,
    coalesce(sum(e.applied_base_delta) FILTER (
      WHERE e.financial_operation_id IS NOT NULL
        AND e.action IN ('set', 'remove')
    ), 0)::numeric(18, 2) AS override_adjustment_total
  FROM public.budget_month_override_events e
  WHERE e.budget_id IS NOT NULL
  GROUP BY e.budget_id
), initialization AS (
  SELECT DISTINCT ON (e.budget_id)
    e.budget_id, e.fallback_base_snapshot, e.fallback_source
  FROM public.budget_month_override_events e
  WHERE e.action = 'initialize' AND e.budget_id IS NOT NULL
  ORDER BY e.budget_id, e.id
)
SELECT
  cs.budget_id,
  cs.budget_month_id,
  cs.month,
  cs.month_start,
  cs.category_id,
  CASE WHEN cs.starting_kind = 'monthly_override'
    THEN coalesce(init.fallback_base_snapshot, 0)
    ELSE cs.starting_amount
  END::numeric(18, 2) AS fallback_base,
  CASE WHEN cs.starting_kind = 'monthly_override'
    THEN coalesce(init.fallback_source, 'none')
    ELSE cs.starting_kind
  END AS fallback_source,
  mo.amount AS current_override,
  coalesce(events.override_adjustment_total, 0)::numeric(18, 2) AS override_adjustment_total,
  (cs.starting_amount + coalesce(events.override_adjustment_total, 0))::numeric(18, 2)
    AS effective_base,
  coalesce(carry.incoming_carryover, 0)::numeric(18, 2) AS incoming_carryover,
  coalesce(carry.outgoing_carryover, 0)::numeric(18, 2) AS outgoing_carryover,
  (
    cs.adjustment_total - coalesce(events.override_adjustment_total, 0)
    - coalesce(carry.incoming_carryover, 0) + coalesce(carry.outgoing_carryover, 0)
  )::numeric(18, 2) AS other_adjustments,
  cs.final_funded,
  cs.lifecycle_state
FROM public.budget_category_state cs
LEFT JOIN override_events events ON events.budget_id = cs.budget_id
LEFT JOIN initialization init ON init.budget_id = cs.budget_id
LEFT JOIN public.budget_month_overrides mo
  ON mo.budget_month_id = cs.budget_month_id AND mo.category_id = cs.category_id
LEFT JOIN public.budget_category_carryover_state carry ON carry.budget_id = cs.budget_id;

CREATE OR REPLACE FUNCTION public.get_budget_month_override_preview(p_month TEXT)
RETURNS JSONB
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_month_start DATE := public.budget_month_start_from_key(p_month);
  v_current_start DATE := date_trunc('month', timezone('Asia/Jerusalem', statement_timestamp()))::date;
  v_month_id BIGINT;
  v_rows JSONB;
BEGIN
  SELECT id INTO v_month_id FROM public.budget_months WHERE month_start = v_month_start;
  SELECT coalesce(jsonb_agg(jsonb_build_object(
    'category_id', mo.category_id,
    'category', jsonb_build_object('name', c.name, 'icon', c.icon, 'type', c.type),
    'amount', mo.amount::numeric(18, 2)::text,
    'initialized', base.budget_id IS NOT NULL,
    'fallback_base', coalesce(base.fallback_base, rd.amount, 0)::numeric(18, 2)::text,
    'fallback_source', coalesce(base.fallback_source,
      CASE WHEN rd.category_id IS NULL THEN 'none' ELSE 'recurring_default' END),
    'effective_base', coalesce(base.effective_base, mo.amount)::numeric(18, 2)::text
  ) ORDER BY c.name, mo.category_id), '[]'::jsonb)
  INTO v_rows
  FROM public.budget_month_overrides mo
  JOIN public.categories c ON c.id = mo.category_id
  LEFT JOIN public.budget_category_base_state base
    ON base.budget_month_id = mo.budget_month_id AND base.category_id = mo.category_id
  LEFT JOIN public.budget_recurring_defaults rd ON rd.category_id = mo.category_id
  WHERE mo.budget_month_id = v_month_id;
  RETURN jsonb_build_object(
    'eligible', v_month_start >= v_current_start,
    'month', p_month,
    'overrides', v_rows,
    'count', jsonb_array_length(v_rows)
  );
END;
$$;

