  FROM service_role;

DO $$
DECLARE v_month RECORD;
BEGIN
  FOR v_month IN SELECT id FROM public.budget_months ORDER BY id LOOP
    PERFORM public.budget_assert_reconciled(v_month.id);
  END LOOP;
  IF EXISTS (
    SELECT 1 FROM public.budget_category_base_state
    WHERE final_funded <> effective_base + incoming_carryover
      - outgoing_carryover + other_adjustments
  ) THEN
    RAISE EXCEPTION 'Migration 020 reconciliation: base/carryover composition mismatch';
  END IF;
END;
$$;

